-- Business development market data model

CREATE TABLE IF NOT EXISTS public.bd_scan_batches (
  scan_batch_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  scan_type text NOT NULL DEFAULT 'market_scan',
  provider text,
  regions_json text,
  industries_json text,
  roles_json text,
  revenue_min_gbp_m double precision,
  revenue_max_gbp_m double precision,
  requested_count integer NOT NULL DEFAULT 0,
  returned_count integer NOT NULL DEFAULT 0,
  status text NOT NULL DEFAULT 'pending',
  diagnostics text,
  created_by text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_bd_scan_batches_created
  ON public.bd_scan_batches (scan_type, created_at DESC);

CREATE TABLE IF NOT EXISTS public.bd_market_companies (
  market_company_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_provider text NOT NULL DEFAULT 'ai-open-source',
  provider_org_id text,
  scan_batch_id integer,
  service_key text,
  company_name text NOT NULL,
  normalized_company_key text,
  website text,
  domain text,
  industry text,
  subindustry text,
  country text,
  region text,
  city text,
  revenue_gbp_millions double precision,
  revenue_band_label text,
  employee_count integer,
  employee_band_label text,
  source_payload_json text,
  qualification_status text NOT NULL DEFAULT 'new',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_bd_market_company_key
  ON public.bd_market_companies (normalized_company_key, country);

CREATE INDEX IF NOT EXISTS ix_bd_market_company_domain
  ON public.bd_market_companies (domain);

CREATE INDEX IF NOT EXISTS ix_bd_market_company_batch
  ON public.bd_market_companies (scan_batch_id, updated_at DESC);

CREATE TABLE IF NOT EXISTS public.bd_company_verifications (
  verification_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  market_company_id integer NOT NULL,
  provider text NOT NULL,
  registry_company_id text,
  registry_jurisdiction text,
  legal_name text,
  company_status text,
  company_number text,
  sic_codes_json text,
  registered_address text,
  incorporation_date date,
  match_confidence double precision NOT NULL DEFAULT 0,
  verified_at timestamptz NOT NULL DEFAULT now(),
  source_url text,
  source_payload_json text
);

CREATE INDEX IF NOT EXISTS ix_bd_company_verifications_company
  ON public.bd_company_verifications (market_company_id, verified_at DESC);

CREATE TABLE IF NOT EXISTS public.bd_company_contacts (
  company_contact_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  market_company_id integer NOT NULL,
  source_provider text NOT NULL DEFAULT 'apollo',
  provider_person_id text,
  full_name text,
  job_title text,
  seniority text,
  department text,
  email text,
  phone text,
  linkedin_url text,
  is_primary_target boolean NOT NULL DEFAULT false,
  contact_fit_score double precision NOT NULL DEFAULT 0,
  source_payload_json text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_bd_company_contacts_company
  ON public.bd_company_contacts (market_company_id, is_primary_target DESC, contact_fit_score DESC);

CREATE TABLE IF NOT EXISTS public.bd_market_scores (
  market_score_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  market_company_id integer NOT NULL,
  primary_contact_id integer,
  overall_score double precision NOT NULL DEFAULT 0,
  industry_fit_score double precision NOT NULL DEFAULT 0,
  revenue_fit_score double precision NOT NULL DEFAULT 0,
  buyer_role_score double precision NOT NULL DEFAULT 0,
  service_need_score double precision NOT NULL DEFAULT 0,
  verification_score double precision NOT NULL DEFAULT 0,
  priority_band text,
  why_good_lead text,
  trigger_reason text,
  scored_by_model text,
  scored_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_bd_market_scores_company
  ON public.bd_market_scores (market_company_id, scored_at DESC);

ALTER TABLE public.bd_ai_generated_leads
  ADD COLUMN IF NOT EXISTS market_company_id integer,
  ADD COLUMN IF NOT EXISTS scan_batch_id integer,
  ADD COLUMN IF NOT EXISTS source_provider text;
