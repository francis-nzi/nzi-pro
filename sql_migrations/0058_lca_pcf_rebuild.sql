-- 0058_lca_pcf_rebuild.sql
--
-- Full replacement of the LCA/PCF feature. The previous tables
-- (lca_products, lca_inventory_items, lca_product_datasets,
-- lca_result_snapshots) were a working prototype never used for real
-- client delivery -- confirmed zero rows in production -- so this is a
-- clean rebuild, not a data migration.
--
-- Design points (see plan for full rationale):
--   - flat line items, no BOM tree (confirmed real-world workbooks
--     flatten multi-level BOMs for calculation purposes anyway)
--   - open, admin-editable module + material-category vocabularies
--     instead of 4 hardcoded stage keys
--   - a reusable, client-scoped component library (mirrors
--     custom_factors/job_custom_factors' client_db_id/is_global pattern)
--   - mass reconciliation (confirmed quantity vs captured line-item mass)
--   - scenario tables created now so Phase 3 (the what-if engine) is
--     additive-only; not wired into calc/UI until then
--   - lca_assessments replaces lca_products; a job can hold several
--     assessments (the "Model Register" pattern -- e.g. comparing a 6L
--     vs 9L variant of the same product)

DROP TABLE IF EXISTS lca_result_snapshots;
DROP TABLE IF EXISTS lca_inventory_items;
DROP TABLE IF EXISTS lca_product_datasets;
DROP TABLE IF EXISTS lca_products;

-- job_pcf_details (a separate, free-text-only "goal & scope" form, api/job_pcf_routes.py
-- + frontend/src/components/JobPcf.tsx) is superseded by lca_assessments, which already
-- captures the same fields (name/functional unit/boundary/standard/assumptions) per
-- assessment plus a real calculation engine. Confirmed empty (table had never been
-- created in production -- lazily created on first use, which never happened).
DROP TABLE IF EXISTS job_pcf_details;

