-- Phase 5 of the LCA/PCF rebuild (see plan for full rationale): a second,
-- structurally different assessment mode, assessment_type='service'
-- (the column has existed since Phase 1 but create_lca_assessment has
-- hard-rejected anything but 'product' until now). Activity x quantity
-- instead of material x mass, classified by GHG Protocol Scope 3 category
-- instead of EN 15804 lifecycle module.
--
-- Unification: rather than a separate Scope 3 taxonomy table, the 15
-- categories are seeded as 15 more rows in the *existing* lca_modules_lookup
-- table (module_code='S1'..'S15', module_group='scope3'). lca_line_items
-- .module_code already means "the grouping bucket this line rolls up
-- into" -- for a product line that's an EN 15804 module, for a service
-- line it's a Scope 3 category, same column, always populated, no schema
-- change needed there. This means module-breakdown grouping, scenario
-- multiplier resolution, readiness module-coverage, factor search, and
-- report/frontend module-label rendering all already work for services
-- with zero further schema change -- only the reusable-library concept
-- (lca_components -> lca_activities) and the two genuinely product-specific
-- things (mass reconciliation, material-category dimension) need new code.

