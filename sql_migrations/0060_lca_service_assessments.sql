-- ---------------------------------------------------------------------
-- Activity library -- the service-assessment equivalent of lca_components
-- ---------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS lca_activities (
  activity_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_db_id INTEGER, -- NULL = shared/global activity, else client-scoped
  activity_code VARCHAR,
  description VARCHAR NOT NULL,
  default_module_code VARCHAR REFERENCES lca_modules_lookup(module_code), -- default Scope 3 category
  default_quantity DOUBLE PRECISION,
  default_unit VARCHAR NOT NULL DEFAULT 'unit',
  notes TEXT,
  archived BOOLEAN NOT NULL DEFAULT FALSE,
  archived_at TIMESTAMP,
  archived_by VARCHAR,
  created_at TIMESTAMP NOT NULL DEFAULT NOW(),
  created_by VARCHAR,
  updated_at TIMESTAMP NOT NULL DEFAULT NOW(),
  updated_by VARCHAR
);

CREATE INDEX IF NOT EXISTS ix_lca_activities_client ON lca_activities (client_db_id, archived);
CREATE INDEX IF NOT EXISTS ix_lca_activities_code ON lca_activities (client_db_id, activity_code);

ALTER TABLE lca_line_items
  ADD COLUMN IF NOT EXISTS activity_id INTEGER REFERENCES lca_activities(activity_id);

ALTER TABLE lca_scenario_multipliers
  ADD COLUMN IF NOT EXISTS activity_id INTEGER REFERENCES lca_activities(activity_id);
