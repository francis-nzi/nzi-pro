CREATE TABLE IF NOT EXISTS lca_products (
  product_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  job_id INTEGER NOT NULL REFERENCES jobs(job_id) ON DELETE CASCADE,
  product_name VARCHAR NOT NULL,
  sku VARCHAR,
  description TEXT,
  functional_unit_value DOUBLE PRECISION NOT NULL DEFAULT 1,
  functional_unit_unit VARCHAR NOT NULL DEFAULT 'kg_product',
  system_boundary VARCHAR NOT NULL DEFAULT 'cradle_to_grave',
  lca_standard VARCHAR NOT NULL DEFAULT 'ISO 14040/14044',
  reference_year INTEGER,
  geography VARCHAR,
  assumptions TEXT,
  total_embedded_tco2e DOUBLE PRECISION NOT NULL DEFAULT 0,
  last_calculated_at TIMESTAMP,
  created_at TIMESTAMP NOT NULL DEFAULT NOW(),
  created_by VARCHAR,
  updated_at TIMESTAMP NOT NULL DEFAULT NOW(),
  updated_by VARCHAR
);

CREATE INDEX IF NOT EXISTS ix_lca_products_job ON lca_products (job_id, product_id);

CREATE TABLE IF NOT EXISTS lca_inventory_items (
  item_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id INTEGER NOT NULL REFERENCES lca_products(product_id) ON DELETE CASCADE,
  stage_key VARCHAR NOT NULL,
  item_name VARCHAR NOT NULL,
  item_description TEXT,
  quantity DOUBLE PRECISION NOT NULL DEFAULT 0,
  unit VARCHAR,
  allocation_pct DOUBLE PRECISION NOT NULL DEFAULT 100,
  origin_country VARCHAR,
  raw_material_origin VARCHAR,
  process_name VARCHAR,
  energy_kwh DOUBLE PRECISION,
  waste_qty DOUBLE PRECISION,
  transport_mode VARCHAR,
  distance_km DOUBLE PRECISION,
  use_phase_energy_kwh DOUBLE PRECISION,
  recycling_rate_pct DOUBLE PRECISION,
  landfill_rate_pct DOUBLE PRECISION,
  mapped_factor_db_id INTEGER,
  factor_value DOUBLE PRECISION,
  factor_unit VARCHAR,
  factor_source VARCHAR,
  lci_database_name VARCHAR,
  data_quality VARCHAR NOT NULL DEFAULT 'secondary',
  is_gap_filled BOOLEAN NOT NULL DEFAULT FALSE,
  gap_fill_method VARCHAR,
  calculation_notes TEXT,
  created_at TIMESTAMP NOT NULL DEFAULT NOW(),
  created_by VARCHAR,
  updated_at TIMESTAMP NOT NULL DEFAULT NOW(),
  updated_by VARCHAR
);

CREATE INDEX IF NOT EXISTS ix_lca_items_product ON lca_inventory_items (product_id, stage_key);
CREATE INDEX IF NOT EXISTS ix_lca_items_factor ON lca_inventory_items (mapped_factor_db_id);

CREATE TABLE IF NOT EXISTS lca_result_snapshots (
  snapshot_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id INTEGER NOT NULL REFERENCES lca_products(product_id) ON DELETE CASCADE,
  calculated_at TIMESTAMP NOT NULL DEFAULT NOW(),
  calculated_by VARCHAR,
  total_tco2e DOUBLE PRECISION NOT NULL DEFAULT 0,
  stage_breakdown_json TEXT NOT NULL,
  hotspots_json TEXT NOT NULL,
  notes TEXT
);

CREATE INDEX IF NOT EXISTS ix_lca_snapshots_product ON lca_result_snapshots (product_id, snapshot_id DESC);
