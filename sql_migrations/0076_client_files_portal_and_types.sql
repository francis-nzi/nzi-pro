-- 0076_client_files_portal_and_types.sql
--
-- Client-level files (CRM client > Files) can now be allocated to the client
-- portal, the same way job files are, and their file type comes from an
-- admin lookup instead of a hard-coded dropdown.
--
-- Mirrored at runtime by api.admin_routes._ensure_client_file_types_lookup_table
-- and api.client_files_routes._ensure_client_files_table.

CREATE TABLE IF NOT EXISTS client_file_types_lookup (
  client_file_type_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR NOT NULL UNIQUE,
  is_active BOOLEAN NOT NULL DEFAULT TRUE
);

-- The types the upload form used to hard-code.
INSERT INTO client_file_types_lookup (name)
SELECT defaults.name
FROM (VALUES ('General'), ('Time Report'), ('Invoice'), ('Contract'),
             ('Report'), ('Correspondence'), ('Other')) AS defaults(name)
WHERE NOT EXISTS (
  SELECT 1 FROM client_file_types_lookup existing
  WHERE lower(existing.name) = lower(defaults.name)
);

-- client_files is created at runtime on first use, so it may not exist yet;
-- the runtime ensure adds these columns then.
DO $$
BEGIN
  IF to_regclass('public.client_files') IS NOT NULL THEN
    ALTER TABLE client_files ADD COLUMN IF NOT EXISTS portal_visible BOOLEAN DEFAULT FALSE;
    ALTER TABLE client_files ADD COLUMN IF NOT EXISTS portal_description TEXT;
    ALTER TABLE client_files ADD COLUMN IF NOT EXISTS portal_expires_at TIMESTAMP;
    ALTER TABLE client_files ADD COLUMN IF NOT EXISTS pinned BOOLEAN DEFAULT FALSE;

    -- Existing rows stored the dropdown's snake_case keys ("time_report");
    -- store the lookup's name instead so they match the admin lookup.
    UPDATE client_files f
    SET file_type = t.name
    FROM client_file_types_lookup t
    WHERE lower(replace(f.file_type, '_', ' ')) = lower(t.name)
      AND f.file_type <> t.name;
  END IF;
END $$;
