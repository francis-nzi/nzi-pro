CREATE TABLE IF NOT EXISTS public.quotes (
  quote_id integer generated by default as identity primary key,
  client_db_id integer not null,
  contact_id integer,
  quote_date date not null,
  valid_to date,
  salesperson text,
  payment_term_id integer,
  description text,
  notes text,
  status text not null default 'Draft',
  revision_of_quote_id integer,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

CREATE TABLE IF NOT EXISTS public.quote_lines (
  line_id integer generated by default as identity primary key,
  quote_id integer not null,
  line_type text not null default 'Line',
  sort_order integer not null default 1,
  job_type_id integer,
  description text,
  qty numeric not null default 1,
  unit_price_ex_vat numeric not null default 0,
  vat_rate_id integer,
  is_selected boolean not null default true,
  CONSTRAINT quote_lines_quote_id_fkey FOREIGN KEY (quote_id) REFERENCES public.quotes(quote_id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS quotes_client_idx ON public.quotes(client_db_id);
CREATE INDEX IF NOT EXISTS quote_lines_quote_idx ON public.quote_lines(quote_id);
