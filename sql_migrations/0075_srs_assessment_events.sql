-- 0075_srs_assessment_events.sql
--
-- Timestamped history for UK SRS Readiness assessment rounds. A finalised
-- round can now be reopened to correct scores and finalised again, which
-- overwrites finalised_at -- so each start, finalise, reopen and re-finalise
-- is recorded here instead.
--
-- Mirrored (schema only, not the backfill) in
-- services.srs_readiness.ensure_srs_readiness_schema().

CREATE TABLE IF NOT EXISTS srs_readiness_assessment_events (
  event_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  assessment_id  INTEGER NOT NULL REFERENCES srs_readiness_assessments(assessment_id) ON DELETE CASCADE,
  event_type     VARCHAR NOT NULL,
  reason         TEXT,
  detail         JSONB,
  actor          VARCHAR,
  occurred_at    TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS ix_srs_assessment_events_assessment
  ON srs_readiness_assessment_events (assessment_id, occurred_at);

-- Backfill: existing rounds' start and finalise, from their own timestamps.
-- Guarded so re-running is a no-op.
INSERT INTO srs_readiness_assessment_events (assessment_id, event_type, actor, occurred_at)
SELECT a.assessment_id, 'started', a.created_by, a.created_at
FROM srs_readiness_assessments a
WHERE NOT EXISTS (
  SELECT 1 FROM srs_readiness_assessment_events e
  WHERE e.assessment_id = a.assessment_id AND e.event_type = 'started'
);

INSERT INTO srs_readiness_assessment_events (assessment_id, event_type, actor, occurred_at)
SELECT a.assessment_id, 'finalised', a.finalised_by, a.finalised_at
FROM srs_readiness_assessments a
WHERE a.status = 'finalised' AND a.finalised_at IS NOT NULL
  AND NOT EXISTS (
    SELECT 1 FROM srs_readiness_assessment_events e
    WHERE e.assessment_id = a.assessment_id AND e.event_type IN ('finalised', 'refinalised')
  );
