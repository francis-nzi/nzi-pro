-- Source registers for Scope 1 assets and Scope 3 business travel

CREATE TABLE IF NOT EXISTS public.job_emission_groups (
  group_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  job_id INTEGER NOT NULL REFERENCES public.jobs(job_id) ON DELETE CASCADE,
  scope VARCHAR NOT NULL,
  category VARCHAR,
  group_type VARCHAR NOT NULL DEFAULT 'asset',
  group_name VARCHAR NOT NULL,
  site_id INTEGER REFERENCES public.client_sites(site_id),
  rollup_method VARCHAR NOT NULL DEFAULT 'sum',
  notes TEXT,
  enabled BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP DEFAULT NOW(),
  updated_at TIMESTAMP DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS job_emission_groups_job_type_name_uidx
ON public.job_emission_groups (job_id, group_type, group_name)
WHERE COALESCE(enabled, TRUE) = TRUE;

CREATE TABLE IF NOT EXISTS public.job_emission_sources (
  source_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  job_id INTEGER NOT NULL REFERENCES public.jobs(job_id) ON DELETE CASCADE,
  group_id INTEGER REFERENCES public.job_emission_groups(group_id) ON DELETE SET NULL,
  scope VARCHAR NOT NULL,
  category VARCHAR,
  source_type VARCHAR NOT NULL DEFAULT 'asset',
  source_subtype VARCHAR,
  site_id INTEGER REFERENCES public.client_sites(site_id),
  source_name VARCHAR NOT NULL,
  asset_identifier VARCHAR,
  employee_name VARCHAR,
  dataset_id INTEGER REFERENCES public.datasets(dataset_id),
  factor_db_id INTEGER REFERENCES public.factor_lookup(db_id),
  original_id VARCHAR,
  qty NUMERIC,
  uom VARCHAR,
  factor NUMERIC,
  ghg_unit VARCHAR,
  apply_pct NUMERIC DEFAULT 100,
  data_source VARCHAR DEFAULT 'Source Register',
  data_confidence VARCHAR DEFAULT 'M',
  notes TEXT,
  detail_json JSONB DEFAULT '{}'::jsonb,
  calc_tco2e NUMERIC,
  enabled BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP DEFAULT NOW(),
  updated_at TIMESTAMP DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS job_emission_sources_job_type_enabled_idx
ON public.job_emission_sources (job_id, source_type, enabled);

CREATE INDEX IF NOT EXISTS job_emission_sources_group_idx
ON public.job_emission_sources (group_id, enabled);
