@router.post("/jobs/{job_id}/spend-data/sync-to-scope")
def sync_spend_to_scope_data(
    job_id: int,
    body: dict = Body(default={}),
    _user: dict = Depends(_current_user),
):
    """
    Push mapped spend rows into job_scope_rows for emissions roll-up.

    Dedupe/update rule:
    - source rows are keyed as original_id = SPEND-<entry_id>
    - if an active Spend Data row already exists with same job_id/scope/original_id/site_id NULL,
      it is updated in place
    - otherwise a new scope row is inserted
    """
    actor = str(_user.get("email") or "system")
    deactivate_missing = bool(body.get("deactivate_missing", True))

    with get_conn() as con:
        _ensure_spend_tables(con)
        _job_client_id(con, int(job_id))

        # Keep schema aligned for write target.
        try:
            con.execute("ALTER TABLE job_scope_rows ADD COLUMN IF NOT EXISTS apply_pct NUMERIC DEFAULT 100")
            con.execute("ALTER TABLE job_scope_rows ADD COLUMN IF NOT EXISTS data_source VARCHAR DEFAULT 'Company Data'")
            con.execute("ALTER TABLE job_scope_rows ADD COLUMN IF NOT EXISTS data_confidence VARCHAR DEFAULT 'M'")
            con.execute("ALTER TABLE job_scope_rows ADD COLUMN IF NOT EXISTS is_custom_entry BOOLEAN DEFAULT FALSE")
            con.execute("ALTER TABLE job_scope_rows ADD COLUMN IF NOT EXISTS enabled BOOLEAN DEFAULT TRUE")
        except Exception:
            pass

        spend_df = con.execute(
            """
            SELECT entry_id, amount_net, amount_gross, conversion_currency, currency, vat_pct, notes,
                   site_id,
                   factor_db_id, factor_original_id, dataset_id,
                   mapped_scope, mapped_category, mapped_report_label,
                   mapping_confidence
            FROM job_spend_entries
            WHERE job_id = %s
              AND COALESCE(is_deleted, FALSE) = FALSE
              AND factor_db_id IS NOT NULL
              AND mapped_scope IS NOT NULL
              AND (submitted_by_portal = FALSE OR review_status = 'approved')
            ORDER BY entry_id
            """,
            [int(job_id)],
        ).df()

        if spend_df is None or spend_df.empty:
            return {"ok": True, "created": 0, "updated": 0, "deactivated": 0, "processed": 0}

        # Aggregate by (scope, factor_db_id, site_id) → one scope row per category
        groups: dict[tuple, dict[str, Any]] = {}
        for _, row in spend_df.iterrows():
            scope = str(row.get("mapped_scope") or "").strip()
            factor_db_id = _safe_optional_int(row.get("factor_db_id"))
            if not scope or not factor_db_id:
                continue
            site_id = _safe_optional_int(row.get("site_id"))
            key = (scope, factor_db_id, site_id)
            if key not in groups:
                groups[key] = {
                    "scope": scope,
                    "factor_db_id": factor_db_id,
                    "site_id": site_id,
                    "amount_gross": 0.0,
                    "currency": str(row.get("conversion_currency") or row.get("currency") or "GBP"),
                    "mapped_report_label": str(row.get("mapped_report_label") or "").strip(),
                    "mapped_category": str(row.get("mapped_category") or "").strip(),
                    "mapping_confidence": row.get("mapping_confidence"),
                    "dataset_id": row.get("dataset_id"),
                }
            groups[key]["amount_gross"] += _safe_float(row.get("amount_gross"), 0.0)

        active_original_ids: list[str] = []
        created = 0
        updated = 0

        for (scope, factor_db_id_key, site_id), grp in groups.items():
            # original_id encodes factor (and site if present) so each category gets one row
            if site_id is not None:
                original_id = f"SPEND-F{factor_db_id_key}-S{site_id}"
            else:
                original_id = f"SPEND-F{factor_db_id_key}"
            active_original_ids.append(original_id)

            factor = _factor_by_id(con, factor_db_id_key)
            if not factor:
                continue

            amount = grp["amount_gross"]
            factor_value = _safe_float(factor.get("factor"), 0.0)
            calc_tco2e = amount * factor_value
            report_label = grp["mapped_report_label"] or factor.get("report_label") or f"Spend factor {factor_db_id_key}"
            category = grp["mapped_category"] or factor.get("category") or "Spend"
            data_conf = _confidence_to_hml(grp.get("mapping_confidence"))
            currency = grp["currency"]

            existing = con.execute(
                """
                SELECT row_id
                FROM job_scope_rows
                WHERE job_id = %s
                  AND scope = %s
                  AND original_id = %s
                  AND site_id IS NOT DISTINCT FROM %s
                  AND COALESCE(data_source, '') = 'Spend Data'
                  AND COALESCE(enabled, TRUE) = TRUE
                ORDER BY row_id
                LIMIT 1
                """,
                [int(job_id), scope, original_id, site_id],
            ).fetchone()

            if existing:
                con.execute(
                    """
                    UPDATE job_scope_rows
                    SET dataset_id = %s,
                        factor_db_id = %s,
                        category = %s,
                        report_label = %s,
                        qty = %s,
                        uom = %s,
                        factor = %s,
                        ghg_unit = %s,
                        calc_tco2e = %s,
                        apply_pct = 100,
                        data_source = 'Spend Data',
                        data_confidence = %s,
                        notes = %s,
                        is_custom_entry = TRUE,
                        enabled = TRUE,
                        updated_at = NOW()
                    WHERE row_id = %s
                    """,
                    [
                        factor.get("dataset_id"),
                        factor.get("db_id"),
                        category,
                        report_label,
                        amount,
                        currency,
                        factor_value,
                        "kgCO2e",
                        calc_tco2e,
                        data_conf,
                        None,
                        int(existing[0]),
                    ],
                )
                updated += 1
            else:
                con.execute(
                    """
                    INSERT INTO job_scope_rows (
                      job_id, scope, site_id, dataset_id, factor_db_id, original_id,
                      category, report_label, qty, uom, factor, ghg_unit, calc_tco2e, apply_pct,
                      data_source, data_confidence, notes, is_custom_entry, enabled
                    )
                    VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, 100, 'Spend Data', %s, %s, TRUE, TRUE)
                    """,
                    [
                        int(job_id),
                        scope,
                        site_id,
                        factor.get("dataset_id"),
                        factor.get("db_id"),
                        original_id,
                        category,
                        report_label,
                        amount,
                        currency,
                        factor_value,
                        "kgCO2e",
                        calc_tco2e,
                        data_conf,
                        None,
                    ],
                )
                created += 1

        deactivated = 0
        if deactivate_missing:
            spend_pattern = "SPEND-%"
            if active_original_ids:
                placeholders = ",".join(["%s"] * len(active_original_ids))
                deactivated_row = con.execute(
                    f"""
                    WITH updated_rows AS (
                      UPDATE job_scope_rows
                      SET enabled = FALSE, updated_at = NOW()
                      WHERE job_id = %s
                        AND COALESCE(data_source, '') = 'Spend Data'
                        AND original_id LIKE %s
                        AND original_id NOT IN ({placeholders})
                      RETURNING 1
                    )
                    SELECT COUNT(*) FROM updated_rows
                    """,
                    [int(job_id), spend_pattern] + active_original_ids,
                ).fetchone()
                deactivated = int(deactivated_row[0] or 0) if deactivated_row else 0
            else:
                deactivated_row = con.execute(
                    """
                    WITH updated_rows AS (
                      UPDATE job_scope_rows
                      SET enabled = FALSE, updated_at = NOW()
                      WHERE job_id = %s
                        AND COALESCE(data_source, '') = 'Spend Data'
                        AND original_id LIKE %s
                      RETURNING 1
                    )
                    SELECT COUNT(*) FROM updated_rows
                    """,
                    [int(job_id), spend_pattern],
                ).fetchone()
                deactivated = int(deactivated_row[0] or 0) if deactivated_row else 0

    return {
        "ok": True,
        "created": int(created),
        "updated": int(updated),
        "deactivated": int(deactivated),
        "processed": int(created + updated),
        "synced_at": datetime.utcnow().isoformat() + "Z",
        "synced_by": actor,
    }
