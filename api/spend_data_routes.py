@router.post("/jobs/{job_id}/spend-data/upload-preview")
async def preview_spend_upload(
    job_id: int,
    file: UploadFile = File(...),
    code_type: str = Query("nominal_code"),
    site_id: int | None = Query(None),
    _user: dict = Depends(_current_user),
):
    data = await file.read()
    if not data:
        raise HTTPException(status_code=400, detail="Empty upload file")
    try:
        scan_bytes(data, filename=file.filename or "upload.csv")
    except VirusScanError as e:
        raise HTTPException(status_code=400, detail=str(e))

    with get_conn() as con:
        _ensure_spend_tables(con)
        client_db_id = _job_client_id(con, int(job_id))
        df = _parse_upload(data, file.filename or "upload.csv")

        items: list[dict[str, Any]] = []
        mapped = 0
        for _, r in df.iterrows():
            desc = str(r.get("spend_description") or "").strip()
            code = str(r.get("reference_code") or "").strip()
            explicit_factor_db_id = _safe_optional_int(r.get("factor_db_id"))
            conversion_ref = str(r.get("factor_conversion_ref") or "").strip() or None
            mapping, id_mismatch = _resolve_upload_mapping(con, explicit_factor_db_id, conversion_ref)
            mapping_source = "explicit" if mapping and (explicit_factor_db_id or conversion_ref) else "auto"
            if mapping is None:
                mapping = _auto_mapping(
                    con=con,
                    client_db_id=int(client_db_id),
                    code_type=code_type,
                    reference_code=code,
                    normalized_description=_normalize_description(desc),
                )
            if mapping:
                mapped += 1
            amount_net = _safe_float(r.get("amount_net"), 0.0)
            conversion_rate = _safe_float(r.get("conversion_rate"), 1.0)
            if conversion_rate <= 0:
                conversion_rate = 1.0
            conversion_currency = str(r.get("conversion_currency") or "GBP").strip().upper()
            converted_net = amount_net * conversion_rate
            amount = _gross_from_net(converted_net, _safe_float(r.get("vat_pct"), 0.0))
            factor = _safe_float((mapping or {}).get("factor"), 0.0)
            factor_ghg_unit = str((mapping or {}).get("ghg_unit") or "").strip() or None
            items.append(
                {
                    "reference_code": code,
                    "spend_description": desc,
                    "currency": conversion_currency,
                    "site_id": int(site_id) if site_id is not None else None,
                    "amount_net": converted_net,
                    "amount_gross": amount,
                    "vat_pct": _safe_float(r.get("vat_pct"), 0.0),
                    "conversion_currency": conversion_currency,
                    "conversion_rate": conversion_rate,
                    "mapping_status": "suggested" if mapping else "unmapped",
                    "mapping_source": mapping_source if mapping else "unmapped",
                    "mapped_scope": (mapping or {}).get("scope"),
                    "mapped_report_label": (mapping or {}).get("report_label"),
                    "factor_db_id": (mapping or {}).get("factor_db_id") or (mapping or {}).get("db_id"),
                    "factor_ghg_unit": factor_ghg_unit,
                    "unit_warning": _spend_factor_warning(factor_ghg_unit) if mapping else None,
                    "id_mismatch_warning": (
                        "Spend Conversion cell's id didn't match its code text (likely an Excel drag-fill error) "
                        "-- resolved using the code instead. Check this row's source file." if id_mismatch else None
                    ),
                    "estimated_emissions_kgco2e": amount * factor if mapping else None,
                    "estimated_emissions_tco2e": (amount * factor / 1000.0) if mapping else None,
                }
            )

    return {
        "items": items,
        "summary": {
            "count": len(items),
            "mapped": mapped,
            "unmapped": len(items) - mapped,
            "total_spend_net": round(sum(_safe_float(x.get("amount_net"), 0.0) for x in items), 2),
            "mapped_spend_net": round(sum(_safe_float(x.get("amount_net"), 0.0) for x in items if str(x.get("mapping_status") or "").lower() == "suggested"), 2),
            "unmapped_spend_net": round(sum(_safe_float(x.get("amount_net"), 0.0) for x in items if str(x.get("mapping_status") or "").lower() != "suggested"), 2),
            "warning_count": len([x for x in items if x.get("unit_warning")]),
            "id_mismatch_count": len([x for x in items if x.get("id_mismatch_warning")]),
        },
    }


@router.post("/jobs/{job_id}/spend-data/upload-commit")
async def commit_spend_upload(
    request: Request,
    job_id: int,
    file: UploadFile = File(...),
    code_type: str = Query("nominal_code"),
    replace_existing: bool = Query(False),
    site_id: int | None = Query(None),
    _user: dict = Depends(_current_user),
):
    actor = str(_user.get("email") or "system")
    data = await file.read()
    if not data:
        raise HTTPException(status_code=400, detail="Empty upload file")
    try:
        scan_bytes(data, filename=file.filename or "upload.csv")
    except VirusScanError as e:
        raise HTTPException(status_code=400, detail=str(e))

    with get_conn() as con:
        _ensure_spend_tables(con)
        client_db_id = _job_client_id(con, int(job_id))
        df = _parse_upload(data, file.filename or "upload.csv")

        if replace_existing:
            replaced_ids = [
                int(r[0])
                for r in con.execute(
                    "SELECT entry_id FROM job_spend_entries WHERE job_id=%s AND COALESCE(is_deleted, FALSE) = FALSE",
                    [int(job_id)],
                ).fetchall()
            ]
            con.execute(
                """
                UPDATE job_spend_entries
                SET is_deleted = TRUE, updated_at = NOW()
                WHERE job_id = %s AND COALESCE(is_deleted, FALSE) = FALSE
                """,
                [int(job_id)],
            )
            if replaced_ids:
                record_audit_event(
                    con,
                    request=request,
                    actor=_user,
                    action="bulk_delete",
                    entity_type="job_spend_entry",
                    entity_id=None,
                    job_id=int(job_id),
                    metadata={"reason": "replace_existing on upload", "count": len(replaced_ids), "entry_ids": replaced_ids},
                )

        inserted = 0
        auto_mapped = 0
        id_mismatches = 0
        for _, r in df.iterrows():
            explicit_factor_db_id = _safe_optional_int(r.get("factor_db_id"))
            conversion_ref = str(r.get("factor_conversion_ref") or "").strip() or None
            factor_override, id_mismatch = _resolve_upload_mapping(con, explicit_factor_db_id, conversion_ref)
            if id_mismatch:
                id_mismatches += 1
            saved = _persist_spend_row(
                con=con,
                job_id=int(job_id),
                client_db_id=int(client_db_id),
                site_id=int(site_id) if site_id is not None else None,
                source_type="upload",
                code_type=code_type,
                reference_code=str(r.get("reference_code") or "").strip(),
                spend_description=str(r.get("spend_description") or "").strip(),
                currency=str(r.get("currency") or "GBP").strip().upper(),
                conversion_currency=str(r.get("conversion_currency") or "GBP").strip().upper(),
                conversion_rate=_safe_float(r.get("conversion_rate"), 1.0),
                amount_net=_safe_float(r.get("amount_net"), 0.0),
                vat_pct=_safe_float(r.get("vat_pct"), 0.0),
                notes=(
                    "Auto-corrected: Spend Conversion cell's id didn't match its code text "
                    "(likely an Excel drag-fill error) -- resolved using the code instead."
                    if id_mismatch else None
                ),
                actor=actor,
                factor_override=factor_override,
            )
            inserted += 1
            if saved.get("auto_mapped"):
                auto_mapped += 1

        record_audit_event(
            con,
            request=request,
            actor=_user,
            action="upload",
            entity_type="job_spend_entry",
            entity_id=None,
            job_id=int(job_id),
            metadata={
                "inserted": inserted,
                "auto_mapped": auto_mapped,
                "unmapped": inserted - auto_mapped,
                "id_mismatches": id_mismatches,
                "replace_existing": replace_existing,
                "filename": file.filename,
            },
        )

    return {
        "ok": True,
        "inserted": inserted,
        "auto_mapped": auto_mapped,
        "unmapped": inserted - auto_mapped,
        "id_mismatches": id_mismatches,
    }


