def _normalize_description(value: Any) -> str:
    text = str(value or "").strip().lower()
    text = re.sub(r"[^a-z0-9]+", " ", text)
    return re.sub(r"\s+", " ", text).strip()


def _safe_float(value: Any, default: float = 0.0) -> float:
    if value is None:
        return default
    try:
        text = str(value).replace(",", "").strip()
        val = float(text) if text else default
        if math.isnan(val) or math.isinf(val):
            return default
        return val
    except Exception:
        return default


def _gross_from_net(amount_net: float, vat_pct: float) -> float:
    return float(amount_net) * (1.0 + (float(vat_pct) / 100.0))


def _net_from_gross(amount_gross: float, vat_pct: float) -> float:
    divisor = 1.0 + (float(vat_pct) / 100.0)
    if divisor == 0:
        return float(amount_gross)
    return float(amount_gross) / divisor


def _is_nan_like(value: Any) -> bool:
    if value is None:
        return True
    try:
        if isinstance(value, float) and (math.isnan(value) or math.isinf(value)):
            return True
    except Exception:
        pass
    text = str(value).strip().lower()
    return text in {"", "nan", "none", "null", "nat", "inf", "-inf", "infinity", "-infinity"}


def _safe_optional_int(value: Any) -> int | None:
    if _is_nan_like(value):
        return None
    try:
        return int(float(str(value).strip()))
    except Exception:
        return None


def _safe_optional_str(value: Any) -> str | None:
    if _is_nan_like(value):
        return None
    text = str(value).strip()
    return text or None


def _has_column(con, table_name: str, column_name: str) -> bool:
    row = con.execute(
        """
        SELECT 1
        FROM information_schema.columns
        WHERE table_schema = current_schema()
          AND table_name = %s
          AND column_name = %s
        LIMIT 1
        """,
        [str(table_name), str(column_name)],
    ).fetchone()
    return bool(row)


def _factor_label_expr(con, alias: str = "") -> str:
    prefix = f"{alias}." if alias else ""
    if _has_column(con, "factor_lookup", "report_label"):
        return f"COALESCE({prefix}report_label, {prefix}column_text)"
    return f"{prefix}column_text"


def _factor_category_expr(con, alias: str = "") -> str:
    prefix = f"{alias}." if alias else ""
    if _has_column(con, "factor_lookup", "category"):
        return f"COALESCE({prefix}category, {prefix}level_2, {prefix}level_1, 'Uncategorized')"
    return f"COALESCE({prefix}level_2, {prefix}level_1, 'Uncategorized')"


