@router.post("/credit-notes/{credit_note_id}/email-pdf")
def email_credit_note_pdf(credit_note_id: int, body: dict = Body(...), _user: dict = Depends(_current_user), request: Request = None):
    try:
        to_email = str(body.get("to") or "").strip()
        if not to_email:
            raise HTTPException(status_code=400, detail="to is required")
        cc_emails = [e.strip() for e in str(body.get("cc") or "").split(",") if e.strip()]
        requested_subject = str(body.get("subject") or "").strip()
        requested_message = str(body.get("message") or "").strip()
        with get_conn() as con:
            _ensure_credit_note_tables(con)
            org_id = _quote_org_id(_user)
            credit_note = _serialize_credit_note(con, int(credit_note_id), org_id=org_id)
            pdf_bytes = _render_credit_note_pdf_bytes(credit_note)
            sender = str(_user.get("email") or _user.get("user_id") or "system")
            email_ctx = {
                "credit_note_number": str(credit_note.get("credit_note_number") or f"CN{int(credit_note_id):06d}"),
                "client_name": str(credit_note.get("client_name") or ""),
                "attention_name": str(credit_note.get("client_name") or ""),
                "job_number": str(credit_note.get("job_number") or ""),
                "sender_name": str(_user.get("full_name") or sender),
                "custom_message": requested_message,
            }
            rendered = build_email_content(
                con=con,
                template_key="credit_note_send",
                context=email_ctx,
                fallback_subject=f"Credit Note {credit_note.get('credit_note_number') or credit_note_id} from {str((credit_note.get('company_profile') or {}).get('company_display_name') or 'Net Zero International')}",
                fallback_body="Please find the attached credit note PDF.",
                sender_identifier=sender,
                override_subject=requested_subject or None,
                override_body=requested_message or None,
            )
            send_res = send_tracked_email(
                con,
                to_email=to_email,
                cc=cc_emails or None,
                subject=rendered["subject"],
                body_text=rendered["body_text"],
                body_html=rendered["body_html"],
                created_by=sender,
                template_key="credit_note_send",
                entity_type="credit_note",
                entity_id=int(credit_note_id),
                client_db_id=_safe_int(credit_note.get("client_db_id"), None),
                job_id=_safe_int(credit_note.get("job_id"), None),
                metadata={"kind": "credit_note_pdf"},
                attachment={
                    "bytes": pdf_bytes,
                    "filename": f"{credit_note.get('credit_note_number') or f'credit-note-{credit_note_id}'}.pdf",
                    "mime": "application/pdf",
                },
                raise_on_error=False,
            )
            con.execute(
                """
                INSERT INTO credit_note_email_log (credit_note_id, org_id, sent_to, subject, body, sent_by, sent_at)
                VALUES (%s, %s, %s, %s, %s, %s, NOW())
                """,
                [int(credit_note_id), org_id, to_email, rendered["subject"], rendered["body_html"], sender],
            )
            if str(send_res.get("status") or "") == "sent" and str(credit_note.get("status") or "").strip().lower() == "draft":
                con.execute(
                    "UPDATE credit_notes SET status = 'Sent', updated_at = NOW() WHERE credit_note_id = %s AND org_id = %s",
                    [int(credit_note_id), org_id],
                )
            if str(send_res.get("status") or "") != "sent":
                raise HTTPException(status_code=500, detail=f"Failed to send email: {send_res.get('error') or 'Unknown error'}")
            record_audit_event(
                con, request=request, actor=_user, action="credit_note_sent",
                entity_type="credit_note", entity_id=int(credit_note_id),
                client_id=_safe_int(credit_note.get("client_db_id"), None), job_id=_safe_int(credit_note.get("job_id"), None),
                metadata={"sent_to": to_email, "cc": cc_emails, "subject": rendered["subject"], "kind": "credit_note_pdf"},
            )
        return {"ok": True, "credit_note_id": int(credit_note_id), "sent_to": to_email, "email_id": int(send_res.get('email_id') or 0)}
    except HTTPException:
        raise
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Failed to email credit note PDF: {e}")
