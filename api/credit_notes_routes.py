def _next_credit_note_number(con, org_id: str | None = None) -> str:
    org_clause = " AND org_id = %s" if org_id else ""
    params = [org_id] if org_id else []
    df = con.execute(
        f"SELECT credit_note_number FROM credit_notes WHERE credit_note_number IS NOT NULL{org_clause}",
        params,
    ).df()
    max_num = 999
    if df is not None and not df.empty:
        for _, r in df.iterrows():
            cn = str(r.get("credit_note_number") or "").strip()
            m = re.match(r"^CN(\d+)$", cn, flags=re.IGNORECASE)
            if not m:
                continue
            value = int(m.group(1))
            if value > max_num:
                max_num = value
    return f"CN{max_num + 1:06d}"


def _credit_note_lines_for(con, credit_note_id: int, org_id: str | None = None) -> list[dict[str, Any]]:
    org_clause = " AND cn.org_id = %s" if org_id else ""
    params: list[Any] = [int(credit_note_id)]
    if org_id:
        params.append(str(org_id).strip())
    df = con.execute(
        """
        SELECT cnl.credit_note_line_id, cnl.credit_note_id, cnl.sort_order, cnl.item_id, ji.item_name,
               cnl.description, cnl.unit, cnl.qty, cnl.unit_price_ex_vat, cnl.amount_ex_vat,
               cnl.vat_rate_id, cnl.vat_rate_pct, cnl.notes
        FROM credit_note_lines cnl
        JOIN credit_notes cn ON cn.credit_note_id = cnl.credit_note_id
        LEFT JOIN job_items ji ON ji.item_id = cnl.item_id
        WHERE cnl.credit_note_id = %s
        """ + org_clause + """
        ORDER BY COALESCE(cnl.sort_order, 0), cnl.credit_note_line_id
        """,
        params,
    ).df()
    lines: list[dict[str, Any]] = []
    if df is None or df.empty:
        return lines
    for _, r in df.iterrows():
        qty = _safe_float(r.get("qty"), 0.0)
        rate = _safe_float(r.get("unit_price_ex_vat"), 0.0)
        amount = _safe_float(r.get("amount_ex_vat"), qty * rate)
        lines.append(
            {
                "credit_note_line_id": _safe_int(r.get("credit_note_line_id"), 0),
                "sort_order": _safe_int(r.get("sort_order"), 0),
                "item_id": _safe_int(r.get("item_id"), None),
                "item_name": str(r.get("item_name") or ""),
                "description": str(r.get("description") or ""),
                "unit": str(r.get("unit") or ""),
                "qty": qty,
                "rate": rate,
                "amount": round(amount, 2),
                "vat_rate_id": _safe_int(r.get("vat_rate_id"), None),
                "vat_rate_pct": _safe_float(r.get("vat_rate_pct"), 0.0),
                "notes": str(r.get("notes") or ""),
            }
        )
    return lines


def _write_credit_note_lines(con, credit_note_id: int, lines: list[dict[str, Any]], org_id: str | None = None) -> None:
    if org_id:
        con.execute(
            "DELETE FROM credit_note_lines WHERE credit_note_id = %s AND org_id = %s",
            [int(credit_note_id), org_id],
        )
    else:
        con.execute("DELETE FROM credit_note_lines WHERE credit_note_id = %s", [int(credit_note_id)])
    for idx, line in enumerate(lines):
        qty = _safe_float(line.get("qty"), 0.0)
        rate = _safe_float(line.get("rate"), 0.0)
        amount = _safe_float(line.get("amount"), qty * rate)
        con.execute(
            """
            INSERT INTO credit_note_lines (
              credit_note_id, org_id, sort_order, item_id, description, unit,
              qty, unit_price_ex_vat, amount_ex_vat, vat_rate_id, vat_rate_pct, notes
            )
            VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
            """,
            [
                int(credit_note_id),
                str(org_id).strip() if org_id else None,
                _safe_int(line.get("sort_order"), idx + 1),
                _safe_int(line.get("item_id"), None),
                str(line.get("description") or ""),
                str(line.get("unit") or ""),
                qty,
                rate,
                amount,
                _safe_int(line.get("vat_rate_id"), None),
                _safe_float(line.get("vat_rate_pct"), 0.0),
                str(line.get("notes") or ""),
            ],
        )


def _serialize_credit_note(con, credit_note_id: int, org_id: str | None = None) -> dict[str, Any]:
    org_clause = " AND org_id = %s" if org_id else ""
    params: list[Any] = [int(credit_note_id)]
    if org_id:
        params.append(str(org_id).strip())
    row = con.execute(
        """
        SELECT credit_note_id, client_db_id, job_id, invoice_id, credit_note_number, credit_note_date,
               currency_code, subtotal, vat, total, status, notes,
               xero_credit_note_id, xero_credit_note_number, xero_status, xero_sync_status,
               xero_synced_at, xero_sync_error, created_at, updated_at, applied_amount, applied_date
        FROM credit_notes
        WHERE credit_note_id = %s
        """ + org_clause + """
        """,
        params,
    ).fetchone()
    if not row:
        raise HTTPException(status_code=404, detail="Credit note not found")
    lines = _credit_note_lines_for(con, int(credit_note_id), org_id=org_id)
    if lines:
        totals = _invoice_totals_from_lines(lines)
    else:
        totals = {
            "subtotal": round(_safe_float(row[7]), 2),
            "vat": round(_safe_float(row[8]), 2),
            "total": round(_safe_float(row[9]), 2),
        }
    job_id = _safe_int(row[2], None)
    job_number = ""
    if job_id is not None:
        j_row = con.execute("SELECT job_number FROM jobs WHERE job_id = %s", [job_id]).fetchone()
        if j_row:
            job_number = str(j_row[0] or "")
    invoice_id = _safe_int(row[3], None)
    invoice_number = ""
    if invoice_id is not None:
        inv_row = con.execute("SELECT invoice_number FROM invoices WHERE invoice_id = %s", [invoice_id]).fetchone()
        if inv_row:
            invoice_number = str(inv_row[0] or "")
    client_db_id = int(row[1])
    c_row = con.execute(
        "SELECT client_name, addr_line1, addr_line2, addr_city, addr_region, addr_postcode, addr_country FROM clients WHERE db_id = %s",
        [client_db_id],
    ).fetchone()
    client_name = str(c_row[0] or "") if c_row else ""
    bill_to = ""
    if c_row:
        address_lines = [str(c_row[i] or "").strip() for i in range(1, 7)]
        bill_to = "\n".join([line for line in [client_name, *address_lines] if line])
    return {
        "credit_note_id": int(row[0]),
        "client_db_id": client_db_id,
        "client_name": client_name,
        "job_id": job_id,
        "job_number": job_number,
        "invoice_id": invoice_id,
        "invoice_number": invoice_number,
        "credit_note_number": str(row[4] or ""),
        "credit_note_date": row[5].isoformat() if row[5] else None,
        "currency_code": str(row[6] or "GBP"),
        "subtotal": totals["subtotal"],
        "vat": totals["vat"],
        "total": totals["total"],
        "status": str(row[10] or "Draft"),
        "notes": str(row[11] or ""),
        "xero_credit_note_id": str(row[12] or "") if row[12] is not None else "",
        "xero_credit_note_number": str(row[13] or "") if row[13] is not None else "",
        "xero_status": str(row[14] or "") if row[14] is not None else "",
        "xero_sync_status": str(row[15] or "") if row[15] is not None else "pending",
        "xero_synced_at": row[16].isoformat() if row[16] else None,
        "xero_sync_error": str(row[17] or "") if row[17] is not None else "",
        "created_at": row[18].isoformat() if row[18] else None,
        "updated_at": row[19].isoformat() if row[19] else None,
        "applied_amount": round(_safe_float(row[20]), 2) if len(row) > 20 else 0.0,
        "applied_date": row[21].isoformat() if len(row) > 21 and row[21] else None,
        "bill_to": bill_to,
        "lines": lines,
        "company_profile": get_company_profile(con),
    }


def _render_credit_note_pdf_bytes(credit_note: dict[str, Any]) -> bytes:
    import io

    currency = str(credit_note.get("currency_code") or "GBP").strip().upper()
    company_profile = credit_note.get("company_profile") or {}
    lines = credit_note.get("lines") or []
    left_details = [x for x in str(credit_note.get("bill_to") or "").splitlines() if x.strip()]
    middle_details = [
        ("Date", _display_date(credit_note.get("credit_note_date"))),
        ("Credit Note Number", str(credit_note.get("credit_note_number") or "-")),
        ("Job Number", str(credit_note.get("job_number") or "-")),
    ]
    if str(credit_note.get("invoice_number") or "").strip():
        middle_details.append(("Related Invoice", str(credit_note.get("invoice_number"))))
    totals_rows = [
        ("Sub-total", f"{_safe_float(credit_note.get('subtotal'), 0.0):,.2f}"),
        ("VAT", f"{_safe_float(credit_note.get('vat'), 0.0):,.2f}"),
        (f"Total {currency}", f"{_safe_float(credit_note.get('total'), 0.0):,.2f}"),
    ]

    buf = io.BytesIO()
    doc = SimpleDocTemplate(
        buf,
        pagesize=A4,
        leftMargin=10 * mm,
        rightMargin=10 * mm,
        topMargin=10 * mm,
        bottomMargin=14 * mm,
        title=str(credit_note.get("credit_note_number") or f"Credit Note {credit_note.get('credit_note_id')}"),
    )
    story = _build_financial_pdf_story(
        doc_title="CREDIT NOTE",
        left_details=left_details,
        middle_details=middle_details,
        subject_line=None,
        currency_code=str(credit_note.get("currency_code") or "GBP"),
        lines=lines,
        options_lines=None,
        totals_rows=totals_rows,
        notes=str(credit_note.get("notes") or ""),
        payment_terms_text=None,
        company_profile=company_profile,
    )
    footer = _pdf_footer(company_profile)
    doc.build(story, onFirstPage=footer, onLaterPages=footer)
    return buf.getvalue()


