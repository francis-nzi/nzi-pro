@router.post("/invoices/{invoice_id}/credit-notes")
def create_credit_note_from_invoice(invoice_id: int, body: dict = Body(default={}), _user: dict = Depends(_current_user), request: Request = None):
    try:
        with get_conn() as con:
            _ensure_credit_note_tables(con)
            org_id = _quote_org_id(_user)
            invoice = _serialize_invoice(con, int(invoice_id), org_id=org_id)

            lines = body.get("lines")
            if lines is not None and not isinstance(lines, list):
                raise HTTPException(status_code=400, detail="lines must be an array")
            if lines is None:
                # Default to a full credit of the invoice -- copy its lines as-is;
                # the user can edit quantities/amounts before saving.
                lines = [
                    {
                        "sort_order": l.get("sort_order"),
                        "item_id": l.get("item_id"),
                        "description": l.get("description"),
                        "unit": l.get("unit"),
                        "qty": l.get("qty"),
                        "rate": l.get("rate"),
                        "amount": l.get("amount"),
                        "vat_rate_id": l.get("vat_rate_id"),
                        "vat_rate_pct": l.get("vat_rate_pct"),
                        "notes": l.get("notes"),
                    }
                    for l in (invoice.get("lines") or [])
                ]

            payload = {
                "job_id": invoice.get("job_id"),
                "invoice_id": int(invoice_id),
                "credit_note_number": body.get("credit_note_number"),
                "credit_note_date": body.get("credit_note_date"),
                "currency_code": invoice.get("currency_code"),
                "status": body.get("status") or "Draft",
                "notes": body.get("notes") if body.get("notes") is not None else invoice.get("notes"),
                "lines": lines,
            }
            return create_credit_note(int(invoice["client_db_id"]), payload, _user, request=request)
    except HTTPException:
        raise
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Failed to create credit note from invoice: {e}")


@router.patch("/credit-notes/{credit_note_id}")
def update_credit_note(credit_note_id: int, body: dict = Body(...), _user: dict = Depends(_current_user), request: Request = None):
    try:
        with get_conn() as con:
            _ensure_credit_note_tables(con)
            org_id = _quote_org_id(_user)
            exists = con.execute(
                "SELECT credit_note_id, xero_credit_note_id FROM credit_notes WHERE credit_note_id = %s AND org_id = %s",
                [int(credit_note_id), org_id],
            ).fetchone()
            if not exists:
                raise HTTPException(status_code=404, detail="Credit note not found")
            xero_credit_note_id = str(exists[1] or "").strip() if len(exists) > 1 else ""
            before = _serialize_credit_note(con, int(credit_note_id), org_id=org_id)

            updates = []
            params: list[Any] = []
            for key, col in [
                ("job_id", "job_id"),
                ("invoice_id", "invoice_id"),
                ("credit_note_number", "credit_note_number"),
                ("credit_note_date", "credit_note_date"),
                ("currency_code", "currency_code"),
                ("subtotal", "subtotal"),
                ("vat", "vat"),
                ("total", "total"),
                ("status", "status"),
                ("notes", "notes"),
            ]:
                if key not in body:
                    continue
                value = body.get(key)
                if key in ("job_id", "invoice_id"):
                    value = _safe_int(value, None)
                elif key == "currency_code":
                    value = str(value or "GBP").upper()
                elif key in ("subtotal", "vat", "total"):
                    value = _safe_float(value, 0.0)
                updates.append(f"{col} = %s")
                params.append(value)

            if "lines" in body:
                lines = body.get("lines") or []
                if not isinstance(lines, list):
                    raise HTTPException(status_code=400, detail="lines must be an array")
                _write_credit_note_lines(con, int(credit_note_id), lines, org_id=org_id)
                line_totals = _invoice_totals_from_lines(lines)
                updates.extend(["subtotal = %s", "vat = %s", "total = %s"])
                params.extend([line_totals["subtotal"], line_totals["vat"], line_totals["total"]])

            if not updates:
                raise HTTPException(status_code=400, detail="No updates provided")

            if xero_credit_note_id:
                updates.append("xero_sync_status = %s")
                params.append("needs_resync")
                updates.append("xero_sync_error = %s")
                params.append(None)
            updates.append("updated_at = NOW()")
            params.append(int(credit_note_id))
            params.append(org_id)
            con.execute(f"UPDATE credit_notes SET {', '.join(updates)} WHERE credit_note_id = %s AND org_id = %s", params)
            result = _serialize_credit_note(con, int(credit_note_id), org_id=org_id)
            record_audit_event(
                con, request=request, actor=_user, action="credit_note_updated",
                entity_type="credit_note", entity_id=int(credit_note_id),
                client_id=_safe_int(result.get("client_db_id"), None), job_id=_safe_int(result.get("job_id"), None),
                before=before, after=result,
            )
            return result
    except HTTPException:
        raise
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Failed to update credit note: {e}")


@router.delete("/credit-notes/{credit_note_id}")
def delete_credit_note(credit_note_id: int, _user: dict = Depends(_current_user), request: Request = None):
    try:
        with get_conn() as con:
            _ensure_credit_note_tables(con)
            org_id = _quote_org_id(_user)
            exists = con.execute(
                "SELECT credit_note_id FROM credit_notes WHERE credit_note_id = %s AND org_id = %s",
                [int(credit_note_id), org_id],
            ).fetchone()
            if not exists:
                raise HTTPException(status_code=404, detail="Credit note not found")
            before = _serialize_credit_note(con, int(credit_note_id), org_id=org_id)
            _write_credit_note_lines(con, int(credit_note_id), [], org_id=org_id)
            con.execute("DELETE FROM xero_credit_note_links WHERE credit_note_id = %s", [int(credit_note_id)])
            con.execute("DELETE FROM credit_notes WHERE credit_note_id = %s AND org_id = %s", [int(credit_note_id), org_id])
            record_audit_event(
                con, request=request, actor=_user, action="credit_note_deleted",
                entity_type="credit_note", entity_id=int(credit_note_id),
                client_id=_safe_int(before.get("client_db_id"), None), job_id=_safe_int(before.get("job_id"), None),
                before=before,
            )
        return {"ok": True, "credit_note_id": int(credit_note_id)}
    except HTTPException:
        raise
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Failed to delete credit note: {e}")


