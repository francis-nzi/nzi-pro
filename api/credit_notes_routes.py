def create_credit_note(client_id: int, body: dict = Body(...), _user: dict = Depends(_current_user), request: Request = None):
    try:
        with get_conn() as con:
            _ensure_credit_note_tables(con)
            org_id = _quote_org_id(_user)
            _require_org_plan_active(con, org_id)
            client_exists = con.execute(
                "SELECT db_id FROM clients WHERE db_id = %s AND org_id = %s",
                [int(client_id), org_id],
            ).fetchone()
            if not client_exists:
                raise HTTPException(status_code=404, detail="Client not found")
            job_id = _safe_int(body.get("job_id"), None)
            if job_id is None:
                raise HTTPException(status_code=400, detail="job_id is required to create a credit note")
            job_exists = con.execute(
                "SELECT job_id FROM jobs WHERE job_id = %s AND client_db_id = %s",
                [job_id, int(client_id)],
            ).fetchone()
            if not job_exists:
                raise HTTPException(status_code=400, detail="job_id does not belong to this client")
            invoice_id = _safe_int(body.get("invoice_id"), None)
            if invoice_id is not None:
                invoice_exists = con.execute(
                    "SELECT invoice_id FROM invoices WHERE invoice_id = %s AND client_db_id = %s",
                    [invoice_id, int(client_id)],
                ).fetchone()
                if not invoice_exists:
                    raise HTTPException(status_code=400, detail="invoice_id does not belong to this client")

            credit_note_number = str(body.get("credit_note_number") or "").strip() or _next_credit_note_number(con, org_id=org_id)
            credit_note_date = str(body.get("credit_note_date") or date.today().isoformat())

            lines = body.get("lines") or []
            if not isinstance(lines, list):
                raise HTTPException(status_code=400, detail="lines must be an array")
            computed_totals = _invoice_totals_from_lines(lines) if lines else None

            con.execute(
                """
                INSERT INTO credit_notes (
                  client_db_id, org_id, job_id, invoice_id, credit_note_number, credit_note_date,
                  currency_code, subtotal, vat, total, status, notes,
                  created_at, updated_at
                )
                VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, NOW(), NOW())
                """,
                [
                    int(client_id),
                    org_id,
                    job_id,
                    invoice_id,
                    credit_note_number,
                    credit_note_date,
                    str(body.get("currency_code") or "GBP").upper(),
                    computed_totals["subtotal"] if computed_totals else _safe_float(body.get("subtotal"), 0.0),
                    computed_totals["vat"] if computed_totals else _safe_float(body.get("vat"), 0.0),
                    computed_totals["total"] if computed_totals else _safe_float(body.get("total"), 0.0),
                    str(body.get("status") or "Draft"),
                    str(body.get("notes") or ""),
                ],
            )
            row = con.execute(
                "SELECT MAX(credit_note_id) FROM credit_notes WHERE client_db_id = %s AND org_id = %s",
                [int(client_id), org_id],
            ).fetchone()
            if not row or row[0] is None:
                raise HTTPException(status_code=500, detail="Failed to create credit note")
            credit_note_id = int(row[0])
            if lines:
                _write_credit_note_lines(con, credit_note_id, lines, org_id=org_id)
                con.execute(
                    "UPDATE credit_notes SET subtotal = %s, vat = %s, total = %s, updated_at = NOW() WHERE credit_note_id = %s",
                    [computed_totals["subtotal"], computed_totals["vat"], computed_totals["total"], int(credit_note_id)],
                )
            result = _serialize_credit_note(con, credit_note_id, org_id=org_id)
            record_audit_event(
                con, request=request, actor=_user, action="credit_note_created",
                entity_type="credit_note", entity_id=credit_note_id, client_id=int(client_id), job_id=job_id, after=result,
            )
            return result
    except HTTPException:
        raise
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Failed to create credit note: {e}")


