@router.get("/cards")
def list_databank_cards(
    category: str = Query(default=""),
    country: str = Query(default=""),
    reporting_year: int | None = Query(default=None),
    subject_id: int | None = Query(default=None),
    query: str = Query(default=""),
    include_inactive: bool = Query(default=False),
    limit: int = Query(default=200, ge=1, le=1000),
    _user: dict = Depends(_current_user),
):
    _require_team_user(_user)
    try:
        with get_conn() as con:
            _ensure_databank_tables(con)
            where = []
            params: list[Any] = []
            if category.strip():
                where.append("lower(c.category) = lower(%s)")
                params.append(category.strip())
            if country.strip():
                where.append("lower(COALESCE(c.country, '')) = lower(%s)")
                params.append(country.strip())
            if reporting_year is not None:
                where.append("c.reporting_year = %s")
                params.append(int(reporting_year))
            if subject_id is not None:
                where.append("c.subject_id = %s")
                params.append(int(subject_id))
            if query.strip():
                q = f"%{query.strip()}%"
                where.append("(c.title ILIKE %s OR c.content ILIKE %s OR COALESCE(c.reference_text, '') ILIKE %s)")
                params.extend([q, q, q])
            if not include_inactive:
                where.append("c.is_active = TRUE")

            where_sql = f"WHERE {' AND '.join(where)}" if where else ""
            df = con.execute(
                f"""
                SELECT
                  c.card_id, c.subject_id, s.name AS subject_name,
                  c.category, c.country, c.reporting_year, c.title, c.content,
                  c.source_type, c.source_url, c.reference_text, c.tags,
                  c.created_by, c.created_at, c.updated_at, c.is_active
                FROM databank_cards c
                LEFT JOIN databank_subjects_lookup s ON s.subject_id = c.subject_id
                {where_sql}
                ORDER BY c.created_at DESC
                LIMIT %s
                """,
                [*params, int(limit)],
            ).df()

        items = []
        categories = set()
        countries = set()
        years = set()
        if df is not None and not df.empty:
            for _, r in df.iterrows():
                cval = str(r.get("category") or "").strip()
                kval = str(r.get("country") or "").strip()
                yval = r.get("reporting_year")
                if cval:
                    categories.add(cval)
                if kval:
                    countries.add(kval)
                if yval is not None and yval == yval:
                    years.add(int(yval))
                items.append(
                    {
                        "card_id": int(r.get("card_id")),
                        "subject_id": int(r.get("subject_id")) if r.get("subject_id") is not None else None,
                        "subject_name": str(r.get("subject_name") or ""),
                        "category": cval,
                        "country": kval,
                        "reporting_year": int(yval) if yval is not None and yval == yval else None,
                        "title": str(r.get("title") or ""),
                        "content": str(r.get("content") or ""),
                        "source_type": str(r.get("source_type") or ""),
                        "source_url": str(r.get("source_url") or ""),
                        "reference_text": str(r.get("reference_text") or ""),
                        "tags": str(r.get("tags") or ""),
                        "created_by": str(r.get("created_by") or ""),
                        "created_at": r.get("created_at").isoformat() if r.get("created_at") else None,
                        "updated_at": r.get("updated_at").isoformat() if r.get("updated_at") else None,
                        "is_active": bool(r.get("is_active")),
                    }
                )

        return {
            "items": items,
            "facets": {
                "categories": sorted(list(categories), key=lambda x: x.lower()),
                "countries": sorted(list(countries), key=lambda x: x.lower()),
                "years": sorted(list(years), reverse=True),
            },
        }
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Failed to list databank cards: {e}")


@router.post("/cards")
def create_databank_card(body: dict = Body(...), _user: dict = Depends(_current_user)):
    actor = _require_team_user(_user)
    subject_id = body.get("subject_id")
    category = str(body.get("category") or "").strip()
    country = str(body.get("country") or "").strip()
    title = str(body.get("title") or "").strip()
    content = str(body.get("content") or "").strip()
    source_type = str(body.get("source_type") or "").strip()
    source_url = str(body.get("source_url") or "").strip()
    reference_text = str(body.get("reference_text") or "").strip()
    tags = str(body.get("tags") or "").strip()
    reporting_year = body.get("reporting_year")

    if not category:
        raise HTTPException(status_code=400, detail="category is required")
    if not title:
        raise HTTPException(status_code=400, detail="title is required")
    if not content:
        raise HTTPException(status_code=400, detail="content is required")
    if subject_id is None:
        raise HTTPException(status_code=400, detail="subject_id is required")

    try:
        year_val = int(reporting_year) if reporting_year not in (None, "", "null") else None
    except Exception:
        raise HTTPException(status_code=400, detail="reporting_year must be a valid year")

    try:
        with get_conn() as con:
            _ensure_databank_tables(con)
            con.execute(
                """
                INSERT INTO databank_cards (
                  subject_id, category, country, reporting_year,
                  title, content, source_type, source_url, reference_text, tags,
                  created_by, created_at, updated_at, is_active
                )
                VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, NOW(), NOW(), TRUE)
                """,
                [
                    int(subject_id),
                    category,
                    country,
                    year_val,
                    title,
                    content,
                    source_type,
                    source_url,
                    reference_text,
                    tags,
                    actor,
                ],
            )
        return {"ok": True, "message": "Data card created"}
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Failed to create data card: {e}")


@router.patch("/cards/{card_id}")
def update_databank_card(card_id: int, body: dict = Body(...), _user: dict = Depends(_current_user)):
    _require_team_user(_user)
    try:
        with get_conn() as con:
            _ensure_databank_tables(con)
            updates = []
            params: list[Any] = []
            if "subject_id" in body:
                updates.append("subject_id = %s")
                params.append(int(body.get("subject_id")))
            if "category" in body:
                category = str(body.get("category") or "").strip()
                if not category:
                    raise HTTPException(status_code=400, detail="category cannot be empty")
                updates.append("category = %s")
                params.append(category)
            if "country" in body:
                updates.append("country = %s")
                params.append(str(body.get("country") or "").strip())
            if "reporting_year" in body:
                rv = body.get("reporting_year")
                updates.append("reporting_year = %s")
                params.append(int(rv) if rv not in (None, "", "null") else None)
            if "title" in body:
                title = str(body.get("title") or "").strip()
                if not title:
                    raise HTTPException(status_code=400, detail="title cannot be empty")
                updates.append("title = %s")
                params.append(title)
            if "content" in body:
                content = str(body.get("content") or "").strip()
                if not content:
                    raise HTTPException(status_code=400, detail="content cannot be empty")
                updates.append("content = %s")
                params.append(content)
            if "source_type" in body:
                updates.append("source_type = %s")
                params.append(str(body.get("source_type") or "").strip())
            if "source_url" in body:
                updates.append("source_url = %s")
                params.append(str(body.get("source_url") or "").strip())
            if "reference_text" in body:
                updates.append("reference_text = %s")
                params.append(str(body.get("reference_text") or "").strip())
            if "tags" in body:
                updates.append("tags = %s")
                params.append(str(body.get("tags") or "").strip())
            if "is_active" in body:
                updates.append("is_active = %s")
                params.append(bool(body.get("is_active")))

            if not updates:
                return {"ok": True, "message": "No fields to update"}

            updates.append("updated_at = NOW()")
            params.append(int(card_id))
            con.execute(
                f"UPDATE databank_cards SET {', '.join(updates)} WHERE card_id = %s",
                params,
            )
        return {"ok": True, "message": "Data card updated"}
    except HTTPException:
        raise
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Failed to update data card: {e}")


