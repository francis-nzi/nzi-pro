def _looks_like_echo(text: str, query: str) -> bool:
    base = (text or "").strip().lower()
    q = (query or "").strip().lower()
    if not base:
        return True
    if not q:
        return False
    if q in base and len(base) <= max(180, int(len(q) * 1.8)):
        return True
    return base.startswith("draft insight")


def _openai_suggestions(subject: str, country: str, category: str, year: int | None, query: str, industry: str) -> list[dict[str, Any]]:
    try:
        from openai import OpenAI
    except ImportError:
        return _suggestions_fallback(subject, country, category, year, query)

    api_key = os.environ.get("OPENAI_API_KEY")
    if not api_key:
        return _suggestions_fallback(subject, country, category, year, query)

    model = os.environ.get("OPENAI_MODEL", "gpt-4.1")
    client = OpenAI(api_key=api_key)

    prompt = (
        "Return ONLY valid JSON array with up to 10 objects using keys: "
        "title, content, category, country, reporting_year, source_url, reference_text. "
        "Each item should be useful for a sustainability data bank card.\n"
        f"Subject: {subject or 'General'}\n"
        f"Country: {country or 'Global'}\n"
        f"Category: {category or 'General'}\n"
        f"Year: {year if year else 'N/A'}\n"
        f"Industry: {industry or 'General'}\n"
        f"Research focus: {query or 'Key climate legislation, COP developments, and practical reductions guidance'}\n"
        "Prioritize credible references and include short reference_text notes."
    )

    try:
        response = client.chat.completions.create(
            model=model,
            messages=[{"role": "user", "content": prompt}],
            max_tokens=1800,
            temperature=0.2,
        )
        content = (response.choices[0].message.content or "").strip() if response.choices else ""
        parsed = _parse_json_array(content)
        if not parsed:
            return _suggestions_fallback(subject, country, category, year, query)
        normalized: list[dict[str, Any]] = []
        for row in parsed[:10]:
            title = str(row.get("title") or "").strip()
            content_text = str(row.get("content") or "").strip()
            if _looks_like_echo(title, query):
                continue
            if _looks_like_echo(content_text, query):
                continue
            normalized.append(
                {
                    "title": title,
                    "content": content_text,
                    "category": str(row.get("category") or category or "General").strip(),
                    "country": str(row.get("country") or country or "Global").strip(),
                    "reporting_year": int(row.get("reporting_year")) if str(row.get("reporting_year") or "").strip().isdigit() else year,
                    "source_url": str(row.get("source_url") or "").strip(),
                    "reference_text": str(row.get("reference_text") or "").strip(),
                }
            )
        if not normalized:
            return _suggestions_fallback(subject, country, category, year, query)
        return normalized
    except Exception:
        return _suggestions_fallback(subject, country, category, year, query)


@router.get("/subjects")
def list_databank_subjects(_user: dict = Depends(_current_user)):
    _require_team_user(_user)
    try:
        with get_conn() as con:
            _ensure_databank_tables(con)
            df = con.execute(
                """
                SELECT subject_id, name, is_active
                FROM databank_subjects_lookup
                ORDER BY lower(name)
                """
            ).df()
        items = []
        if df is not None and not df.empty:
            for _, r in df.iterrows():
                items.append(
                    {
                        "subject_id": int(r.get("subject_id")),
                        "name": str(r.get("name") or ""),
                        "is_active": bool(r.get("is_active")),
                    }
                )
        return {"items": items}
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Failed to list databank subjects: {e}")


