@router.patch("/{factor_id}/archive")
def archive_custom_factor(
    factor_id: int,
    body: dict = Body(...),
    _user: dict[str, str] = Depends(_current_user),
):
    """Archive or unarchive a custom factor."""
    actor = _assert_admin(_user)

    archived = bool(body.get("archived", True))
    try:
        with get_conn() as con:
            _ensure_custom_factor_schema(con)

            exists = con.execute(
                "SELECT factor_id FROM custom_factors WHERE factor_id = ?",
                [int(factor_id)],
            ).fetchone()
            if not exists:
                raise HTTPException(status_code=404, detail=f"Custom factor {factor_id} not found")

            if archived:
                con.execute(
                    """
                    UPDATE custom_factors
                    SET archived = TRUE,
                        is_active = FALSE,
                        archived_at = CURRENT_TIMESTAMP,
                        archived_by = ?
                    WHERE factor_id = ?
                    """,
                    [actor, int(factor_id)],
                )
                message = "Custom factor archived successfully"
            else:
                con.execute(
                    """
                    UPDATE custom_factors
                    SET archived = FALSE,
                        is_active = TRUE,
                        archived_at = NULL,
                        archived_by = NULL
                    WHERE factor_id = ?
                    """,
                    [int(factor_id)],
                )
                message = "Custom factor unarchived successfully"

            return {"ok": True, "message": message}
    except HTTPException:
        raise
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Failed to archive custom factor: {e}")


@router.delete("/{factor_id}")
def delete_custom_factor(
    factor_id: int,
    _user: dict[str, str] = Depends(_current_user),
):
    """Permanently delete a custom factor. Admin only."""
    _assert_admin(_user)

    try:
        with get_conn() as con:
            _ensure_custom_factor_schema(con)

            exists = con.execute(
                "SELECT factor_id FROM custom_factors WHERE factor_id = ?",
                [int(factor_id)],
            ).fetchone()
            if not exists:
                raise HTTPException(status_code=404, detail=f"Custom factor {factor_id} not found")

            # Child rows are ON DELETE CASCADE, but keep this explicit for resilience.
            if _table_exists(con, "custom_factor_year_values"):
                con.execute("DELETE FROM custom_factor_year_values WHERE factor_id = ?", [int(factor_id)])
            con.execute("DELETE FROM custom_factors WHERE factor_id = ?", [int(factor_id)])

            return {"ok": True, "message": "Custom factor permanently deleted"}
    except HTTPException:
        raise
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Failed to delete custom factor: {e}")
