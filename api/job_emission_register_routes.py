def _sheet_rows(ws, alias_map: dict[str, str]) -> list[dict[str, Any]]:
    headers: list[str | None] = []
    for cell in next(ws.iter_rows(min_row=1, max_row=1, values_only=True), []):
        headers.append(alias_map.get(_norm_text(cell), _norm_text(cell) or None))

    rows: list[dict[str, Any]] = []
    for raw_row in ws.iter_rows(min_row=2, values_only=True):
        record: dict[str, Any] = {}
        has_value = False
        for idx, value in enumerate(raw_row):
            if idx >= len(headers):
                break
            key = headers[idx]
            if not key:
                continue
            record[key] = value
            if value is not None and str(value).strip() != "":
                has_value = True
        if has_value:
            rows.append(record)
    return rows


def _ensure_register_group(
    con,
    *,
    job_id: int,
    group_name: str,
    scope: str,
    group_type: str,
    category: str | None = None,
    site_id: int | None = None,
    rollup_method: str = "sum",
    dataset_id: int | None = None,
    factor_db_id: int | None = None,
    original_id: str | None = None,
    factor: Any | None = None,
    ghg_unit: str | None = None,
    uom: str | None = None,
    notes: str | None = None,
) -> tuple[int | None, bool]:
    normalized_name = str(group_name or "").strip()
    if not normalized_name:
        return None, False

    existing = con.execute(
        """
        SELECT group_id
        FROM job_emission_groups
        WHERE job_id=%s
          AND lower(group_name) = lower(%s)
          AND lower(group_type) = lower(%s)
          AND COALESCE(enabled, TRUE) = TRUE
        ORDER BY group_id
        LIMIT 1
        """,
        [int(job_id), normalized_name, str(group_type or "asset").strip() or "asset"],
    ).fetchone()
    if existing:
        group_id = _safe_int(existing[0])
        if group_id is not None and any(
            value is not None for value in (dataset_id, factor_db_id, original_id, factor, ghg_unit, uom)
        ):
            con.execute(
                """
                UPDATE job_emission_groups
                SET dataset_id = COALESCE(dataset_id, %s),
                    factor_db_id = COALESCE(factor_db_id, %s),
                    original_id = COALESCE(original_id, %s),
                    factor = COALESCE(factor, %s),
                    ghg_unit = COALESCE(ghg_unit, %s),
                    uom = COALESCE(uom, %s),
                    updated_at = NOW()
                WHERE group_id = %s
                """,
                [dataset_id, factor_db_id, original_id, factor, ghg_unit, uom, group_id],
            )
        return group_id, False

    row = con.execute(
        """
        INSERT INTO job_emission_groups (
            job_id, scope, category, group_type, group_name, site_id, rollup_method,
            dataset_id, factor_db_id, original_id, factor, ghg_unit, uom, notes
        )
        VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
        RETURNING group_id
        """,
        [
            int(job_id),
            scope,
            category,
            str(group_type or "asset").strip() or "asset",
            normalized_name,
            site_id,
            str(rollup_method or "sum").strip() or "sum",
            dataset_id,
            factor_db_id,
            original_id,
            factor,
            ghg_unit,
            uom,
            notes,
        ],
    ).fetchone()
    return (_safe_int(row[0]) if row else None, True)


