def _ensure_schema(con) -> None:
    con.execute(
        """
        CREATE TABLE IF NOT EXISTS job_emission_groups (
          group_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          job_id INTEGER NOT NULL REFERENCES jobs(job_id) ON DELETE CASCADE,
          scope VARCHAR NOT NULL,
          category VARCHAR,
          group_type VARCHAR NOT NULL DEFAULT 'asset',
          group_name VARCHAR NOT NULL,
          site_id INTEGER REFERENCES client_sites(site_id),
          rollup_method VARCHAR NOT NULL DEFAULT 'sum',
          dataset_id INTEGER REFERENCES datasets(dataset_id),
          factor_db_id INTEGER REFERENCES factor_lookup(db_id),
          original_id VARCHAR,
          factor NUMERIC,
          ghg_unit VARCHAR,
          uom VARCHAR,
          notes TEXT,
          enabled BOOLEAN NOT NULL DEFAULT TRUE,
          created_at TIMESTAMP DEFAULT NOW(),
          updated_at TIMESTAMP DEFAULT NOW()
        )
        """
    )
    con.execute(
        """
        CREATE UNIQUE INDEX IF NOT EXISTS job_emission_groups_job_type_name_uidx
        ON job_emission_groups (job_id, group_type, group_name)
        WHERE COALESCE(enabled, TRUE) = TRUE
        """
    )
    con.execute("ALTER TABLE job_emission_groups ADD COLUMN IF NOT EXISTS dataset_id INTEGER REFERENCES datasets(dataset_id)")
    con.execute("ALTER TABLE job_emission_groups ADD COLUMN IF NOT EXISTS factor_db_id INTEGER REFERENCES factor_lookup(db_id)")
    con.execute("ALTER TABLE job_emission_groups ADD COLUMN IF NOT EXISTS original_id VARCHAR")
    con.execute("ALTER TABLE job_emission_groups ADD COLUMN IF NOT EXISTS factor NUMERIC")
    con.execute("ALTER TABLE job_emission_groups ADD COLUMN IF NOT EXISTS ghg_unit VARCHAR")
    con.execute("ALTER TABLE job_emission_groups ADD COLUMN IF NOT EXISTS uom VARCHAR")
    con.execute(
        """
        CREATE INDEX IF NOT EXISTS job_emission_groups_factor_idx
        ON job_emission_groups (job_id, group_type, factor_db_id, enabled)
        """
    )
    con.execute(
        """
        CREATE TABLE IF NOT EXISTS job_emission_sources (
          source_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          job_id INTEGER NOT NULL REFERENCES jobs(job_id) ON DELETE CASCADE,
          group_id INTEGER REFERENCES job_emission_groups(group_id) ON DELETE SET NULL,
          scope VARCHAR NOT NULL,
          category VARCHAR,
          source_type VARCHAR NOT NULL DEFAULT 'asset',
          source_subtype VARCHAR,
          site_id INTEGER REFERENCES client_sites(site_id),
          source_name VARCHAR NOT NULL,
          asset_identifier VARCHAR,
          employee_name VARCHAR,
          dataset_id INTEGER REFERENCES datasets(dataset_id),
          factor_db_id INTEGER REFERENCES factor_lookup(db_id),
          original_id VARCHAR,
          qty NUMERIC,
          uom VARCHAR,
          factor NUMERIC,
          ghg_unit VARCHAR,
          apply_pct NUMERIC DEFAULT 100,
          data_source VARCHAR DEFAULT 'Source Register',
          data_confidence VARCHAR DEFAULT 'M',
          notes TEXT,
          detail_json JSONB DEFAULT '{}'::jsonb,
          calc_tco2e NUMERIC,
          enabled BOOLEAN NOT NULL DEFAULT TRUE,
          created_at TIMESTAMP DEFAULT NOW(),
          updated_at TIMESTAMP DEFAULT NOW()
        )
        """
    )
    con.execute(
        """
        CREATE INDEX IF NOT EXISTS job_emission_sources_job_type_enabled_idx
        ON job_emission_sources (job_id, source_type, enabled)
        """
    )
    con.execute(
        """
        CREATE INDEX IF NOT EXISTS job_emission_sources_group_idx
        ON job_emission_sources (group_id, enabled)
        """
    )
    con.execute(
        """
        UPDATE job_emission_groups g
        SET dataset_id = COALESCE(g.dataset_id, s.dataset_id),
            factor_db_id = COALESCE(g.factor_db_id, s.factor_db_id),
            original_id = COALESCE(g.original_id, s.original_id),
            factor = COALESCE(g.factor, s.factor),
            ghg_unit = COALESCE(g.ghg_unit, s.ghg_unit),
            uom = COALESCE(g.uom, s.uom),
            updated_at = NOW()
        FROM (
            SELECT DISTINCT ON (job_id, group_id)
              job_id, group_id, dataset_id, factor_db_id, original_id, factor, ghg_unit, uom
            FROM job_emission_sources
            WHERE group_id IS NOT NULL
              AND COALESCE(enabled, TRUE) = TRUE
              AND (
                dataset_id IS NOT NULL OR factor_db_id IS NOT NULL OR original_id IS NOT NULL
                OR factor IS NOT NULL OR ghg_unit IS NOT NULL OR uom IS NOT NULL
              )
            ORDER BY job_id, group_id, source_id
        ) s
        WHERE g.group_id = s.group_id
          AND g.job_id = s.job_id
          AND (
            g.dataset_id IS NULL OR g.factor_db_id IS NULL OR g.original_id IS NULL
            OR g.factor IS NULL OR g.ghg_unit IS NULL OR g.uom IS NULL
          )
        """
    )


def _calc_tco2e(qty: Any, factor: Any, apply_pct: Any, ghg_unit: Any) -> float:
    qty_val = float(qty or 0)
    factor_val = float(factor or 0)
    pct_val = float(apply_pct or 100)
    value = qty_val * factor_val * (pct_val / 100.0)
    if "kg" in str(ghg_unit or "kgCO2e").lower():
        value /= 1000.0
    return float(value)


