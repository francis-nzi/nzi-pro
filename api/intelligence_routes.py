@router.post("/touchpoints")
def create_touchpoint(body: dict[str, Any], _user: dict[str, str] = Depends(_current_user)):
    org_id = require_org(_user)
    client_db_id = body.get("client_db_id")
    if client_db_id is None:
        raise HTTPException(status_code=400, detail="client_db_id is required")

    touchpoint_type = _touchpoint_type_value(body.get("touchpoint_type"))
    outcome = _outcome_value(body.get("outcome"))
    summary = _normalize_text(body.get("summary"))
    if not summary:
        raise HTTPException(status_code=400, detail="summary is required")
    next_action = _normalize_text(body.get("next_action"), "")
    next_action_due = _safe_date(body.get("next_action_due"))
    occurred_at = _safe_datetime(body.get("occurred_at")) or datetime.now(timezone.utc)
    crm_owner = _default_crm_owner(_user)
    created_by = _normalize_text(_user.get("email") or _user.get("user_id"), "")
    timeline_subject = f"Touchpoint: {touchpoint_type.replace('_', ' ').title()}"
    body_lines = [summary]
    body_lines.append(f"Outcome: {outcome.replace('_', ' ').title()}")
    if next_action:
        body_lines.append(f"Next action: {next_action}")
    if next_action_due:
        body_lines.append(f"Due: {next_action_due.isoformat()}")
    timeline_body = "\n".join(line for line in body_lines if line)

    with get_conn(autocommit=False) as con:
        _ensure_schema(con)
        row = con.execute(
            """
            INSERT INTO client_touchpoints (
              org_id, client_db_id, crm_owner, touchpoint_type, summary, outcome,
              next_action, next_action_due, occurred_at, created_by
            )
            VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
            RETURNING
              touchpoint_id, client_db_id, crm_owner, touchpoint_type,
              summary, outcome, next_action, next_action_due,
              occurred_at, created_at, created_by
            """,
            [
                org_id,
                int(client_db_id),
                crm_owner,
                touchpoint_type,
                summary,
                outcome,
                next_action or None,
                next_action_due,
                occurred_at,
                created_by or None,
            ],
        ).fetchone()
        if not row:
            raise HTTPException(status_code=500, detail="Failed to save touchpoint")
        touchpoint_id = int(row[0])
        _ensure_crm_timeline_tables(con)
        con.execute(
            """
            INSERT INTO crm_events (
              client_db_id, job_id, event_type, channel, direction, subject,
              body_text, body_html, status, owner_user_id, due_at, source, source_ref,
              payload_json, is_private, created_by, created_at, updated_at
            )
            VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, NOW(), NOW())
            RETURNING event_id
            """,
            [
                int(client_db_id),
                None,
                "note",
                touchpoint_type,
                "internal",
                timeline_subject,
                timeline_body,
                None,
                "logged",
                created_by or None,
                next_action_due,
                "intelligence",
                f"touchpoint:{touchpoint_id}",
                {
                    "touchpoint_id": touchpoint_id,
                    "touchpoint_type": touchpoint_type,
                    "outcome": outcome,
                    "next_action": next_action or None,
                    "next_action_due": next_action_due.isoformat() if next_action_due else None,
                    "occurred_at": occurred_at.isoformat() if occurred_at else None,
                },
                False,
                created_by or None,
            ],
        ).fetchone()
        return {
            "touchpoint_id": touchpoint_id,
            "client_db_id": int(row[1]),
            "crm_owner": _normalize_text(row[2], "Unassigned"),
            "touchpoint_type": _normalize_text(row[3], "call"),
            "summary": _normalize_text(row[4], ""),
            "outcome": _normalize_text(row[5], "neutral"),
            "next_action": _normalize_text(row[6], ""),
            "next_action_due": _safe_date(row[7]).isoformat() if _safe_date(row[7]) else None,
            "occurred_at": _safe_datetime(row[8]).isoformat() if _safe_datetime(row[8]) else None,
            "created_at": _safe_datetime(row[9]).isoformat() if _safe_datetime(row[9]) else None,
            "created_by": _normalize_text(row[10], ""),
        }
