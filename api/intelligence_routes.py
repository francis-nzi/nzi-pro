def _load_invoice_stats(con, org_id: str, client_ids: list[int]) -> dict[int, dict[str, int]]:
    if not client_ids or not _table_exists(con, "invoices"):
        return {}
    placeholders = ",".join(["?"] * len(client_ids))
    rows = con.execute(
        f"""
        SELECT
            client_db_id,
            COALESCE(SUM(CASE WHEN LOWER(COALESCE(status, '')) = 'overdue' AND COALESCE(due_date, CURRENT_DATE) < CURRENT_DATE THEN 1 ELSE 0 END), 0) AS overdue_count,
            COALESCE(SUM(CASE WHEN LOWER(COALESCE(status, '')) NOT IN ('paid', 'void', 'refunded') THEN 1 ELSE 0 END), 0) AS open_count
        FROM invoices
        WHERE org_id = ? AND client_db_id IN ({placeholders})
        GROUP BY client_db_id
        """,
        [org_id, *client_ids],
    ).fetchall()
    stats: dict[int, dict[str, int]] = {}
    for row in rows or []:
        stats[int(row[0])] = {
            "overdue_invoices": int(row[1] or 0),
            "open_invoices": int(row[2] or 0),
        }
    return stats


def _load_jobs(con, org_id: str, client_ids: list[int]) -> dict[int, list[dict[str, Any]]]:
    if not client_ids:
        return {}
    has_job_plan = _table_exists(con, "job_plan")
    placeholders = ",".join(["?"] * len(client_ids))
    milestone_select = """
        jp.data_collection_due,
        jp.data_collection_completed_at,
        jp.first_draft_due,
        jp.first_draft_completed_at,
        jp.final_report_due,
        jp.final_report_completed_at
    """ if has_job_plan else """
        NULL AS data_collection_due,
        NULL AS data_collection_completed_at,
        NULL AS first_draft_due,
        NULL AS first_draft_completed_at,
        NULL AS final_report_due,
        NULL AS final_report_completed_at
    """
    rows = con.execute(
        f"""
        SELECT
            j.job_id,
            j.client_db_id,
            j.job_number,
            j.title,
            COALESCE(NULLIF(TRIM(j.status), ''), 'Unknown') AS status,
            j.reporting_year,
            j.start_date,
            j.due_date,
            j.created_at,
            {milestone_select}
        FROM jobs j
        LEFT JOIN clients c ON c.db_id = j.client_db_id
        {"LEFT JOIN job_plan jp ON jp.job_id = j.job_id" if has_job_plan else ""}
        WHERE COALESCE(j.org_id, c.org_id) = ? AND j.client_db_id IN ({placeholders})
        ORDER BY j.client_db_id ASC, j.reporting_year DESC NULLS LAST, j.job_id DESC
        """,
        [org_id, *client_ids],
    ).fetchall()
    grouped: dict[int, list[dict[str, Any]]] = defaultdict(list)
    for row in rows or []:
        client_id = int(row[1])
        grouped[client_id].append(
            {
                "job_id": int(row[0]),
                "client_db_id": client_id,
                "job_number": _normalize_text(row[2], ""),
                "title": _normalize_text(row[3], ""),
                "status": _normalize_text(row[4], "Unknown"),
                "reporting_year": int(row[5]) if row[5] is not None else None,
                "start_date": _safe_date(row[6]).isoformat() if _safe_date(row[6]) else None,
                "due_date": _safe_date(row[7]).isoformat() if _safe_date(row[7]) else None,
                "created_at": _safe_datetime(row[8]).isoformat() if _safe_datetime(row[8]) else None,
                "data_collection_due": _safe_date(row[9]),
                "data_collection_completed_at": _safe_datetime(row[10]),
                "first_draft_due": _safe_date(row[11]),
                "first_draft_completed_at": _safe_datetime(row[12]),
                "final_report_due": _safe_date(row[13]),
                "final_report_completed_at": _safe_datetime(row[14]),
            }
        )
    return grouped


def _aggregate_emissions(con, job_ids: list[int]) -> dict[int, float]:
    if not job_ids:
        return {}
    try:
        rows_df = load_combined_emissions_summary_rows(con, job_ids)
    except Exception:
        logger.exception("intelligence.emissions_summary_failed")
        return {}
    if rows_df is None or rows_df.empty:
        return {}
    totals: dict[int, float] = defaultdict(float)
    for _, row in rows_df.iterrows():
        job_id = row.get("job_id")
        if job_id is None:
            continue
        try:
            totals[int(job_id)] += float(row.get("emissions") or 0.0)
        except Exception:
            continue
    return {key: round(val, 2) for key, val in totals.items()}


def _pick_active_job(jobs: list[dict[str, Any]]) -> dict[str, Any] | None:
    active = [job for job in jobs if _normalize_text(job.get("status"), "").lower() not in {"completed", "archived", "cancelled"}]
    if not active:
        return None
    return active[0]


def _pick_latest_completed_job(jobs: list[dict[str, Any]]) -> dict[str, Any] | None:
    completed = [job for job in jobs if _normalize_text(job.get("status"), "").lower() in {"completed", "archived"}]
    if not completed:
        return None
    return completed[0]


def _touchpoint_due_date(last_touchpoint_date: date | None, cadence: str | None) -> date | None:
    if last_touchpoint_date is None:
        return None
    low, _mid = _cadence_window(cadence)
    return last_touchpoint_date + timedelta(days=low)


def _compute_client_record(
    *,
    client: dict[str, Any],
    jobs: list[dict[str, Any]],
    touchpoints: list[dict[str, Any]],
    invoice_stats: dict[str, int],
    emissions_by_job: dict[int, float],
) -> dict[str, Any]:
    last_touchpoint = _safe_date(touchpoints[0]["occurred_at"]) if touchpoints else None
    cadence = client.get("touchpoint_cadence")
    engagement_score, engagement_flags, days_since_contact, next_touchpoint_due = _engagement_score(last_touchpoint, cadence)

    active_job = _pick_active_job(jobs)
    active_status = _overall_milestone_status(
        [_milestone_status(job.get("data_collection_due"), job.get("data_collection_completed_at")) for job in (jobs[:1] if active_job is None else [active_job])]
    )
    milestone_score = _milestone_score(active_status)
    milestone_flags = ["MILESTONE_RED"] if active_status == "red" else []

    latest_completed_job = _pick_latest_completed_job(jobs)
    latest_year = latest_completed_job.get("reporting_year") if latest_completed_job else None
    latest_total = emissions_by_job.get(int(latest_completed_job["job_id"])) if latest_completed_job else None
    emissions_score, emissions_flags, variance_pct = _emissions_score(
        benchmark_year=client.get("benchmark_year"),
        benchmark_total=client.get("benchmark_total_tco2e"),
        net_zero_year=client.get("net_zero_year"),
        latest_year=latest_year,
        latest_total=latest_total,
    )

    overdue_invoices = int(invoice_stats.get("overdue_invoices") or 0)
    open_invoices = int(invoice_stats.get("open_invoices") or 0)
    payment_score, payment_flags = _payment_score(overdue_invoices)

    flags: list[str] = []
    flags.extend(engagement_flags)
    flags.extend(emissions_flags)
    flags.extend(milestone_flags)
    flags.extend(payment_flags)
    if client.get("engagement_end_date") is not None:
        days_remaining = (_safe_date(client["engagement_end_date"]) - date.today()).days if _safe_date(client["engagement_end_date"]) else None
        if days_remaining is not None and days_remaining <= 30:
            flags.append("RENEWAL_30")
        elif days_remaining is not None and days_remaining <= 90:
            flags.append("RENEWAL_90")
    if not any(_normalize_text(job.get("status"), "").lower() not in {"completed", "archived", "cancelled"} for job in jobs):
        flags.append("NO_ACTIVE_JOB")

    score = min(100, max(0, emissions_score + milestone_score + engagement_score + payment_score))

    risk_flags = ",".join(sorted({flag for flag in flags if flag}))
    return {
        "client_db_id": int(client["client_db_id"]),
        "client_name": client["client_name"],
        "crm_owner": client["crm_owner"],
        "health_score": int(score),
        "score_emissions": int(emissions_score),
        "score_milestones": int(milestone_score),
        "score_engagement": int(engagement_score),
        "score_payments": int(payment_score),
        "risk_flags": risk_flags,
        "last_touchpoint_date": last_touchpoint.isoformat() if last_touchpoint else None,
        "days_since_contact": days_since_contact,
        "touchpoint_due_date": _format_due_date(next_touchpoint_due),
        "active_job": active_job,
        "latest_completed_job": latest_completed_job,
        "latest_year": int(latest_year) if latest_year is not None else None,
        "latest_total_tco2e": float(latest_total) if latest_total is not None else None,
        "emissions_variance_pct": round(float(variance_pct), 1) if variance_pct is not None else None,
        "open_invoices": open_invoices,
        "overdue_invoices": overdue_invoices,
        "engagement_end_date": _safe_date(client.get("engagement_end_date")).isoformat() if _safe_date(client.get("engagement_end_date")) else None,
    }


def _build_dashboard_record(
    *,
    client: dict[str, Any],
    snapshot: dict[str, Any] | None,
    touchpoints: list[dict[str, Any]],
    invoice_stats: dict[str, int],
) -> dict[str, Any]:
    last_touchpoint = _safe_date(touchpoints[0]["occurred_at"]) if touchpoints else None
    cadence = client.get("touchpoint_cadence")
    engagement_score, engagement_flags, days_since_contact, next_touchpoint_due = _engagement_score(last_touchpoint, cadence)
    snapshot = snapshot or {}
    score = int(snapshot.get("health_score") or 0)
    risk_flags = str(snapshot.get("risk_flags") or "").strip()
    if not risk_flags:
        flags = list(engagement_flags)
        if client.get("engagement_end_date") is not None:
            days_remaining = (_safe_date(client["engagement_end_date"]) - date.today()).days if _safe_date(client["engagement_end_date"]) else None
            if days_remaining is not None and days_remaining <= 30:
                flags.append("RENEWAL_30")
            elif days_remaining is not None and days_remaining <= 90:
                flags.append("RENEWAL_90")
        risk_flags = ",".join(sorted({flag for flag in flags if flag}))
    return {
        "client_db_id": int(client["client_db_id"]),
        "client_name": client["client_name"],
        "crm_owner": client["crm_owner"],
        "health_score": score,
        "risk_flags": risk_flags,
        "last_touchpoint_date": last_touchpoint.isoformat() if last_touchpoint else None,
        "days_since_contact": days_since_contact,
        "touchpoint_due_date": _format_due_date(next_touchpoint_due),
        "engagement_end_date": _safe_date(client.get("engagement_end_date")).isoformat() if _safe_date(client.get("engagement_end_date")) else None,
        "open_invoices": int(invoice_stats.get("open_invoices") or 0),
        "overdue_invoices": int(invoice_stats.get("overdue_invoices") or 0),
    }


def _refresh_snapshots(con, org_id: str, records: list[dict[str, Any]]) -> None:
    if not records:
        return
    values: list[object] = []
    placeholders: list[str] = []
    for record in records:
        placeholders.append("(?, ?, ?, ?, ?, ?, ?, ?, NOW())")
        values.extend(
            [
                org_id,
                record["client_db_id"],
                record["health_score"],
                record["score_emissions"],
                record["score_milestones"],
                record["score_engagement"],
                record["score_payments"],
                record["risk_flags"],
            ]
        )
    con.execute(
        f"""
        INSERT INTO client_health_snapshots (
          org_id, client_db_id, health_score, score_emissions,
          score_milestones, score_engagement, score_payments, risk_flags,
          computed_at
        )
        VALUES {", ".join(placeholders)}
        ON CONFLICT (org_id, client_db_id) DO UPDATE SET
          health_score = EXCLUDED.health_score,
          score_emissions = EXCLUDED.score_emissions,
          score_milestones = EXCLUDED.score_milestones,
          score_engagement = EXCLUDED.score_engagement,
          score_payments = EXCLUDED.score_payments,
          risk_flags = EXCLUDED.risk_flags,
          computed_at = NOW()
        """,
        values,
    )


def _build_talking_points(record: dict[str, Any], client: dict[str, Any]) -> list[str]:
    points: list[str] = []
    flags = {flag.strip() for flag in str(record.get("risk_flags") or "").split(",") if flag.strip()}
    days_since = record.get("days_since_contact")
    if "OVERDUE_CALL" in flags and days_since is not None:
        points.append(f"Check in - last contact was {days_since} days ago")
    if "EMISSIONS_OFF_TRACK" in flags and record.get("emissions_variance_pct") is not None:
        points.append(f"Emissions {round(float(record['emissions_variance_pct']), 1)}% above target trajectory - discuss reduction actions")
    if "MILESTONE_RED" in flags:
        points.append("Job milestone overdue - confirm data submission timeline")
    if "RENEWAL_90" in flags and record.get("engagement_end_date"):
        points.append(f"Contract renewal due {record['engagement_end_date']} - begin renewal conversation")
    if "INVOICE_OVERDUE" in flags:
        points.append("Outstanding invoice - confirm payment status")
    points.append(f"Review progress against net zero target ({client.get('net_zero_year') or 'n/a'})")
    return points


def _build_talking_points_enhanced(
    record: dict[str, Any],
    client: dict[str, Any],
    recent_touchpoints: list[dict[str, Any]],
    active_job_full: dict[str, Any] | None,
    open_tasks: list[dict[str, Any]],
) -> list[str]:
    points: list[str] = []
    flags = {flag.strip() for flag in str(record.get("risk_flags") or "").split(",") if flag.strip()}

    # 1. Agreed next action from last touchpoint
    last_tp = recent_touchpoints[0] if recent_touchpoints else None
    if last_tp and last_tp.get("next_action"):
        action = last_tp["next_action"]
        due = last_tp.get("next_action_due")
        if due:
            points.append(f"Agreed next action: {action} (due {due})")
        else:
            points.append(f"Agreed next action: {action}")

    # 2. Imminent renewal
    if "RENEWAL_30" in flags and record.get("engagement_end_date"):
        points.append(f"Engagement ends {record['engagement_end_date']} — confirm renewal or exit plan")
    elif "RENEWAL_90" in flags and record.get("engagement_end_date"):
        points.append(f"Contract renewal due {record['engagement_end_date']} — begin renewal conversation")

    # 3. Overdue milestones (specific)
    if active_job_full:
        for m in active_job_full.get("milestones", []):
            if m.get("status") == "red" and not m.get("completed"):
                points.append(f"{m['name']} milestone overdue (was due {m['due']}) — confirm delivery timeline")
            elif m.get("status") == "amber" and not m.get("completed"):
                points.append(f"{m['name']} deadline approaching — due {m['due']}")

    # 4. Overdue invoice
    if "INVOICE_OVERDUE" in flags:
        overdue = record.get("overdue_invoices", 0)
        points.append(f"{overdue} invoice{'s' if overdue != 1 else ''} overdue — confirm payment status")

    # 5. Emissions off track
    if "EMISSIONS_OFF_TRACK" in flags and record.get("emissions_variance_pct") is not None:
        pct = round(float(record["emissions_variance_pct"]), 1)
        points.append(f"Emissions {pct}% above target trajectory — discuss reduction actions")

    # 6. Overdue call (if no next action covered it above)
    if "OVERDUE_CALL" in flags and not (last_tp and last_tp.get("next_action")):
        days = record.get("days_since_contact")
        if days is not None:
            points.append(f"Check in — last contact was {days} days ago")
        else:
            points.append("No contact logged yet — this is the first touch")

    # 7. High-priority open tasks
    urgent = [t for t in open_tasks if t.get("priority") in ("urgent", "high")]
    if urgent:
        names = ", ".join(t["title"] for t in urgent[:3] if t.get("title"))
        if names:
            points.append(f"High-priority tasks open: {names}")

    # 8. Net zero progress (always)
    net_zero = client.get("net_zero_year")
    if net_zero:
        points.append(f"Review progress against net zero target ({net_zero})")

    return points


def _serialize_job(job: dict[str, Any] | None) -> dict[str, Any] | None:
    if not job:
        return None
    due_date = _safe_date(job.get("due_date"))
    next_milestone_name = None
    next_milestone_due = None
    for name, due_key, completed_key in (
        ("Data Collection", "data_collection_due", "data_collection_completed_at"),
        ("First Draft", "first_draft_due", "first_draft_completed_at"),
        ("Final Report", "final_report_due", "final_report_completed_at"),
    ):
        due = job.get(due_key)
        completed = job.get(completed_key)
        if due and not completed:
            next_milestone_name = name
            next_milestone_due = _safe_date(due)
            break
    days_to_milestone = (next_milestone_due - date.today()).days if next_milestone_due else None
    milestone_status = _overall_milestone_status(
        [_milestone_status(job.get("data_collection_due"), job.get("data_collection_completed_at")),
         _milestone_status(job.get("first_draft_due"), job.get("first_draft_completed_at")),
         _milestone_status(job.get("final_report_due"), job.get("final_report_completed_at"))]
    )
    return {
        "job_id": int(job["job_id"]),
        "job_number": job.get("job_number"),
        "title": job.get("title"),
        "status": job.get("status"),
        "milestone_status": milestone_status,
        "next_milestone": next_milestone_name,
        "days_to_milestone": days_to_milestone,
        "due_date": due_date.isoformat() if due_date else None,
    }


def _serialize_job_full(job: dict[str, Any] | None) -> dict[str, Any] | None:
    if not job:
        return None
    milestones = []
    for name, due_key, completed_key in (
        ("Data Collection", "data_collection_due", "data_collection_completed_at"),
        ("First Draft", "first_draft_due", "first_draft_completed_at"),
        ("Final Report", "final_report_due", "final_report_completed_at"),
    ):
        due = job.get(due_key)
        completed = job.get(completed_key)
        status = _milestone_status(due, completed)
        milestones.append({
            "name": name,
            "due": _safe_date(due).isoformat() if _safe_date(due) else None,
            "completed": bool(completed),
            "completed_at": _safe_datetime(completed).isoformat() if _safe_datetime(completed) else None,
            "status": status,
        })
    overall_status = _overall_milestone_status([m["status"] for m in milestones])
    next_milestone_name = None
    next_milestone_due_str = None
    days_to_milestone = None
    for m in milestones:
        if not m["completed"] and m["due"]:
            next_milestone_name = m["name"]
            next_milestone_due_str = m["due"]
            due_date = _safe_date(m["due"])
            if due_date:
                days_to_milestone = (due_date - date.today()).days
            break
    due_date = _safe_date(job.get("due_date"))
    return {
        "job_id": int(job["job_id"]),
        "job_number": job.get("job_number"),
        "title": job.get("title"),
        "status": job.get("status"),
        "reporting_year": job.get("reporting_year"),
        "milestone_status": overall_status,
        "milestones": milestones,
        "next_milestone": next_milestone_name,
        "next_milestone_due": next_milestone_due_str,
        "days_to_milestone": days_to_milestone,
        "due_date": due_date.isoformat() if due_date else None,
    }


def _load_recent_notes(con, client_db_id: int, limit: int = 5) -> list[dict[str, Any]]:
    """Load recent notes for a client from client_notes, crm_events, and job_communications."""
    notes: list[dict[str, Any]] = []

    # 1. client_notes table
    try:
        rows = con.execute(
            """
            SELECT
                cn.note_id,
                cn.subject,
                cn.note_text,
                cn.author,
                cn.job_id,
                j.job_number,
                j.title AS job_title,
                COALESCE(cn.updated_at, cn.created_at) AS note_at
            FROM client_notes cn
            LEFT JOIN jobs j ON j.job_id = cn.job_id
            WHERE cn.client_db_id = ?
              AND COALESCE(cn.archived, FALSE) = FALSE
              AND cn.note_text IS NOT NULL AND cn.note_text != ''
            ORDER BY COALESCE(cn.updated_at, cn.created_at) DESC NULLS LAST
            LIMIT ?
            """,
            [int(client_db_id), limit],
        ).fetchall()
        for row in rows or []:
            notes.append({
                "source": "client_note",
                "source_label": "Client Note",
                "note_id": int(row[0]),
                "subject": _normalize_text(row[1], "") or None,
                "note_text": _normalize_text(row[2], ""),
                "author": _normalize_text(row[3], ""),
                "job_id": int(row[4]) if row[4] is not None else None,
                "job_number": _normalize_text(row[5], "") or None,
                "job_title": _normalize_text(row[6], "") or None,
                "note_at": _safe_datetime(row[7]).isoformat() if _safe_datetime(row[7]) else None,
            })
    except Exception:
        pass

    # 2. crm_events (event_type = 'note')
    try:
        rows = con.execute(
            """
            SELECT
                e.event_id,
                e.subject,
                e.body_text,
                e.created_by,
                e.job_id,
                j.job_number,
                j.title AS job_title,
                COALESCE(e.event_at, e.updated_at, e.created_at) AS note_at
            FROM crm_events e
            LEFT JOIN jobs j ON j.job_id = e.job_id
            WHERE e.client_db_id = ?
              AND lower(COALESCE(e.event_type, '')) = 'note'
              AND COALESCE(e.archived, FALSE) = FALSE
              AND e.body_text IS NOT NULL AND e.body_text != ''
            ORDER BY COALESCE(e.event_at, e.updated_at, e.created_at) DESC NULLS LAST
            LIMIT ?
            """,
            [int(client_db_id), limit],
        ).fetchall()
        for row in rows or []:
            notes.append({
                "source": "crm_event",
                "source_label": "CRM Note",
                "note_id": int(row[0]),
                "subject": _normalize_text(row[1], "") or None,
                "note_text": _normalize_text(row[2], ""),
                "author": _normalize_text(row[3], ""),
                "job_id": int(row[4]) if row[4] is not None else None,
                "job_number": _normalize_text(row[5], "") or None,
                "job_title": _normalize_text(row[6], "") or None,
                "note_at": _safe_datetime(row[7]).isoformat() if _safe_datetime(row[7]) else None,
            })
    except Exception:
        pass

    # 3. job_communications (channel = 'note') for this client's jobs
    try:
        rows = con.execute(
            """
            SELECT
                jc.communication_id,
                jc.subject,
                jc.message_text,
                jc.created_by,
                jc.job_id,
                j.job_number,
                j.title AS job_title,
                COALESCE(jc.event_at, jc.updated_at, jc.created_at) AS note_at
            FROM job_communications jc
            JOIN jobs j ON j.job_id = jc.job_id
            WHERE j.client_db_id = ?
              AND lower(COALESCE(jc.channel, '')) = 'note'
              AND COALESCE(jc.archived, FALSE) = FALSE
              AND jc.message_text IS NOT NULL AND jc.message_text != ''
            ORDER BY COALESCE(jc.event_at, jc.updated_at, jc.created_at) DESC NULLS LAST
            LIMIT ?
            """,
            [int(client_db_id), limit],
        ).fetchall()
        for row in rows or []:
            notes.append({
                "source": "job_note",
                "source_label": "Job Note",
                "note_id": int(row[0]),
                "subject": _normalize_text(row[1], "") or None,
                "note_text": _normalize_text(row[2], ""),
                "author": _normalize_text(row[3], ""),
                "job_id": int(row[4]) if row[4] is not None else None,
                "job_number": _normalize_text(row[5], "") or None,
                "job_title": _normalize_text(row[6], "") or None,
                "note_at": _safe_datetime(row[7]).isoformat() if _safe_datetime(row[7]) else None,
            })
    except Exception:
        pass

    # Sort all combined notes by date descending, return top N
    notes.sort(key=lambda n: str(n.get("note_at") or ""), reverse=True)
    return notes[:limit]


def _load_crm_tasks(con, client_db_id: int) -> list[dict[str, Any]]:
    if not _table_exists(con, "crm_tasks"):
        return []
    try:
        rows = con.execute(
            """
            SELECT task_id, client_db_id, job_id, title, details, assignee_user_id,
                   priority, due_at, status, created_at
            FROM crm_tasks
            WHERE client_db_id = ?
              AND status NOT IN ('completed', 'cancelled', 'archived')
            ORDER BY
                CASE priority
                    WHEN 'urgent' THEN 1
                    WHEN 'high' THEN 2
                    WHEN 'normal' THEN 3
                    ELSE 4
                END,
                due_at ASC NULLS LAST,
                task_id ASC
            LIMIT 20
            """,
            [int(client_db_id)],
        ).fetchall()
    except Exception:
        return []
    tasks: list[dict[str, Any]] = []
    for row in rows or []:
        tasks.append(
            {
                "task_id": int(row[0]),
                "client_db_id": int(row[1]),
                "job_id": int(row[2]) if row[2] is not None else None,
                "title": _normalize_text(row[3], ""),
                "details": _normalize_text(row[4], ""),
                "assignee_user_id": _normalize_text(row[5], ""),
                "priority": _normalize_text(row[6], "normal"),
                "due_at": _safe_datetime(row[7]).isoformat() if _safe_datetime(row[7]) else None,
                "status": _normalize_text(row[8], "open"),
                "created_at": _safe_datetime(row[9]).isoformat() if _safe_datetime(row[9]) else None,
            }
        )
    return tasks


