def _ingest_inbound_email(
    con,
    *,
    from_email: str,
    from_name: str,
    to_email: str,
    subject: str,
    content: str,
    received_at: str | None,
    message_id: str,
    source_tag: str,
    job_id: int | None = None,
    client_db_id: int | None = None,
) -> dict[str, Any]:
    _ensure_tables(con)
    resolved_job_id, resolved_client_id = _resolve_job_client(con, job_id, client_db_id, subject)
    if resolved_job_id is None:
        return {"ok": True, "matched": False, "message": "Inbound email received but no job mapping found"}

    automation_key = f"inbound-email:{message_id}" if message_id else None
    if automation_key:
        exists = con.execute(
            """
            SELECT communication_id
            FROM job_communications
            WHERE job_id = %s AND automation_key = %s
            LIMIT 1
            """,
            [int(resolved_job_id), automation_key],
        ).fetchone()
        if exists:
            return {
                "ok": True,
                "matched": True,
                "deduplicated": True,
                "job_id": int(resolved_job_id),
                "communication_id": int(exists[0]),
            }

    row = con.execute(
        """
        INSERT INTO job_communications (
          job_id, client_db_id, direction, channel, subject, message_text,
          from_name, from_email, to_email, status, event_at, automation_key, created_by, updated_at
        )
        VALUES (%s, %s, 'inbound', 'email', %s, %s, %s, %s, %s, 'received', %s, %s, %s, NOW())
        RETURNING communication_id
        """,
        [
            int(resolved_job_id),
            int(resolved_client_id) if resolved_client_id is not None else None,
            subject or "(No subject)",
            content,
            from_name or None,
            from_email or None,
            to_email or None,
            received_at,
            automation_key,
            source_tag,
        ],
    ).fetchone()
    communication_id = int(row[0])
    auto_task = _maybe_create_auto_followup_task(
        con,
        job_id=int(resolved_job_id),
        communication_id=communication_id,
        from_email=from_email,
        subject=subject,
        message_text=content,
    )
    return {
        "ok": True,
        "matched": True,
        "job_id": int(resolved_job_id),
        "communication_id": communication_id,
        "auto_task": auto_task,
    }


@router.get("/jobs/{job_id}/communications")
def list_job_communications(job_id: int, _user: dict = Depends(_current_user)):
    _ = _actor(_user)
    try:
        with get_conn() as con:
            _ensure_tables(con)
            job_row = con.execute("SELECT client_db_id FROM jobs WHERE job_id = %s", [int(job_id)]).fetchone()
            if not job_row:
                raise HTTPException(status_code=404, detail="Job not found")
            client_db_id = int(job_row[0]) if job_row[0] is not None else None

            comm_df = con.execute(
                """
                SELECT communication_id, job_id, client_db_id, direction, channel, subject, message_text,
                       scope, category, site_id, site_name,
                       from_name, from_email, to_name, to_email, status, event_at, requires_follow_up,
                       follow_up_due, is_private, archived, archived_at, archived_by, updated_by, automation_key, created_by, created_at, updated_at
                FROM job_communications
                WHERE job_id = %s
                  AND COALESCE(archived, FALSE) = FALSE
                ORDER BY COALESCE(event_at, created_at) DESC, communication_id DESC
                LIMIT 500
                """,
                [int(job_id)],
            ).df()

            task_df = con.execute(
                """
                SELECT task_id, job_id, communication_id, title, details, assigned_to, priority, status, due_date,
                       created_by, created_at, updated_at, completed_at, completed_by
                FROM job_communication_tasks
                WHERE job_id = %s
                ORDER BY
                  CASE WHEN lower(status) IN ('open','in_progress') THEN 0 ELSE 1 END,
                  due_date ASC NULLS LAST,
                  task_id DESC
                LIMIT 500
                """,
                [int(job_id)],
            ).df()

            users_df = con.execute(
                """
                SELECT email, full_name
                FROM users
                WHERE COALESCE(status, 'Active') = 'Active'
                ORDER BY lower(full_name), lower(email)
                """
            ).df()

            contacts_df = con.execute(
                """
                SELECT contact_id, full_name, email, is_primary
                FROM client_contacts
                WHERE client_db_id = %s
                ORDER BY is_primary DESC, lower(full_name)
                """,
                [int(client_db_id)] if client_db_id is not None else [-1],
            ).df()

        communications: list[dict[str, Any]] = []
        if comm_df is not None and not comm_df.empty:
            for _, row in comm_df.iterrows():
                communications.append(_serialize_comm(row.to_dict()))

        tasks: list[dict[str, Any]] = []
        if task_df is not None and not task_df.empty:
            for _, row in task_df.iterrows():
                tasks.append(_serialize_task(row.to_dict()))

        users: list[dict[str, str]] = []
        if users_df is not None and not users_df.empty:
            for _, row in users_df.iterrows():
                users.append(
                    {
                        "email": str(row.get("email") or "").strip(),
                        "full_name": str(row.get("full_name") or "").strip(),
                    }
                )

        contacts: list[dict[str, Any]] = []
        if contacts_df is not None and not contacts_df.empty:
            for _, row in contacts_df.iterrows():
                contacts.append(
                    {
                        "contact_id": int(row.get("contact_id")),
                        "full_name": str(row.get("full_name") or ""),
                        "email": str(row.get("email") or ""),
                        "is_primary": bool(row.get("is_primary")) if row.get("is_primary") is not None else False,
                    }
                )

        open_tasks = sum(1 for t in tasks if str(t.get("status") or "").lower() in ("open", "in_progress"))
        overdue_tasks = sum(
            1
            for t in tasks
            if t.get("due_date")
            and str(t.get("status") or "").lower() in ("open", "in_progress")
            and str(t.get("due_date")) < date.today().isoformat()
        )

        return {
            "job_id": int(job_id),
            "client_db_id": client_db_id,
            "communications": communications,
            "tasks": tasks,
            "lookups": {
                "users": users,
                "contacts": contacts,
            },
            "summary": {
                "communications_count": len(communications),
                "open_tasks_count": int(open_tasks),
                "overdue_tasks_count": int(overdue_tasks),
            },
        }
    except HTTPException:
        raise
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Failed to load communications: {e}")


