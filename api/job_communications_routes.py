def _get_milestone_names(con, milestone_template_id: int | None) -> list[str]:
    defaults = ["Data Collection", "First Draft", "Final Report"]
    if milestone_template_id is None:
        return defaults
    try:
        df = con.execute(
            """
            SELECT milestone_name
            FROM milestone_template_items
            WHERE template_id = %s
            ORDER BY COALESCE(sort_order, 9999), item_id
            LIMIT 3
            """,
            [int(milestone_template_id)],
        ).df()
        if df is None or df.empty:
            return defaults
        names = [str(r.get("milestone_name") or "").strip() for _, r in df.iterrows()]
        names = [x for x in names if x]
        if not names:
            return defaults
        while len(names) < 3:
            names.append(defaults[len(names)])
        return names[:3]
    except Exception:
        return defaults


def _split_address_lines(value: str) -> list[str]:
    txt = str(value or "").strip()
    if not txt:
        return []
    if "\n" in txt:
        return [line.strip() for line in txt.splitlines() if line.strip()]
    parts = [p.strip() for p in txt.split(",") if p.strip()]
    return parts


