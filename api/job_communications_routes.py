def _m365_token(cfg: dict[str, str]) -> str:
    if not (cfg["tenant_id"] and cfg["client_id"] and cfg["client_secret"]):
        raise RuntimeError("M365_TENANT_ID, M365_CLIENT_ID, M365_CLIENT_SECRET must be set")
    token_url = f"https://login.microsoftonline.com/{cfg['tenant_id']}/oauth2/v2.0/token"
    payload = urlparse.urlencode(
        {
            "grant_type": "client_credentials",
            "client_id": cfg["client_id"],
            "client_secret": cfg["client_secret"],
            "scope": "https://graph.microsoft.com/.default",
        }
    ).encode("utf-8")
    req = urlrequest.Request(token_url, data=payload, method="POST")
    req.add_header("Content-Type", "application/x-www-form-urlencoded")
    with urlrequest.urlopen(req, timeout=20) as resp:
        parsed = json.loads(resp.read().decode("utf-8"))
    token = str(parsed.get("access_token") or "").strip()
    if not token:
        raise RuntimeError("Failed to obtain Microsoft Graph token")
    return token


def _m365_graph_get(token: str, url: str) -> dict[str, Any]:
    req = urlrequest.Request(url, method="GET")
    req.add_header("Authorization", f"Bearer {token}")
    req.add_header("Accept", "application/json")
    with urlrequest.urlopen(req, timeout=30) as resp:
        return json.loads(resp.read().decode("utf-8"))


def _strip_html(raw_html: str) -> str:
    txt = re.sub(r"<\s*br\s*/?\s*>", "\n", raw_html, flags=re.IGNORECASE)
    txt = re.sub(r"<[^>]+>", " ", txt)
    txt = html.unescape(txt)
    txt = re.sub(r"\s+\n", "\n", txt)
    txt = re.sub(r"\n\s+", "\n", txt)
    txt = re.sub(r"[ \t]{2,}", " ", txt)
    return txt.strip()


def _extract_message_id_from_resource(resource: str) -> str | None:
    r = str(resource or "").strip()
    m = re.search(r"/messages/([^/?]+)", r, flags=re.IGNORECASE)
    if m:
        return m.group(1)
    return None


def _m365_fetch_message(token: str, mailbox_user: str, message_id: str) -> dict[str, Any]:
    select_cols = ",".join(
        [
            "id",
            "subject",
            "receivedDateTime",
            "internetMessageId",
            "bodyPreview",
            "body",
            "from",
            "toRecipients",
            "conversationId",
        ]
    )
    url = f"https://graph.microsoft.com/v1.0/users/{urlparse.quote(mailbox_user)}/messages/{urlparse.quote(message_id)}?$select={select_cols}"
    return _m365_graph_get(token, url)


def _m365_to_inbound_payload(msg: dict[str, Any]) -> dict[str, Any]:
    from_obj = (msg.get("from") or {}).get("emailAddress") or {}
    to_recipients = msg.get("toRecipients") or []
    to_email = ""
    if to_recipients and isinstance(to_recipients, list):
        first = to_recipients[0] or {}
        to_email = str((first.get("emailAddress") or {}).get("address") or "").strip()
    raw_html = str((msg.get("body") or {}).get("content") or "")
    body_type = str((msg.get("body") or {}).get("contentType") or "").lower()
    if body_type == "html":
        content = _strip_html(raw_html) or str(msg.get("bodyPreview") or "")
    else:
        content = raw_html or str(msg.get("bodyPreview") or "")
    return {
        "from_email": str(from_obj.get("address") or "").strip(),
        "from_name": str(from_obj.get("name") or "").strip(),
        "to_email": to_email,
        "subject": str(msg.get("subject") or "").strip(),
        "text": content.strip(),
        "received_at": str(msg.get("receivedDateTime") or "").strip() or None,
        "message_id": str(msg.get("internetMessageId") or msg.get("id") or "").strip(),
    }


@router.post("/communications/inbound/m365/notifications")
def inbound_m365_notifications(
    body: dict = Body(default={}),
    validationToken: str | None = Query(default=None),
):
    """
    Microsoft Graph notification endpoint.
    - Supports subscription validation via `validationToken` query.
    - Processes Graph notifications by fetching message payload via Graph API.
    """
    if validationToken:
        return PlainTextResponse(content=validationToken)

    cfg = _m365_config()
    if not cfg["mailbox_user"]:
        raise HTTPException(status_code=503, detail="M365_MAILBOX_USER is not configured")

    value = body.get("value") or []
    if not isinstance(value, list):
        raise HTTPException(status_code=400, detail="Invalid payload")

    try:
        token = _m365_token(cfg)
        processed = 0
        matched = 0
        errors: list[str] = []
        with get_conn() as con:
            for item in value:
                try:
                    if cfg["client_state"]:
                        incoming_state = str(item.get("clientState") or "").strip()
                        if incoming_state and incoming_state != cfg["client_state"]:
                            continue
                    message_id = _extract_message_id_from_resource(str(item.get("resource") or ""))
                    if not message_id:
                        continue
                    msg = _m365_fetch_message(token, cfg["mailbox_user"], message_id)
                    payload = _m365_to_inbound_payload(msg)
                    result = _ingest_inbound_email(
                        con,
                        from_email=str(payload.get("from_email") or ""),
                        from_name=str(payload.get("from_name") or ""),
                        to_email=str(payload.get("to_email") or ""),
                        subject=str(payload.get("subject") or ""),
                        content=str(payload.get("text") or ""),
                        received_at=payload.get("received_at"),
                        message_id=str(payload.get("message_id") or ""),
                        source_tag="webhook:m365",
                    )
                    processed += 1
                    if result.get("matched"):
                        matched += 1
                except Exception as ie:
                    errors.append(str(ie))
                    continue
        return {"ok": True, "processed": processed, "matched": matched, "errors": errors[:20]}
    except HTTPException:
        raise
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Failed to process m365 notifications: {e}")


@router.post("/communications/inbound/m365/sync")
def inbound_m365_sync(
    body: dict = Body(default={}),
    _user: dict = Depends(_current_user),
):
    """
    Manual pull sync for recent mailbox messages from Microsoft Graph.
    Useful as a fallback while webhook subscriptions are being finalized.
    """
    _ = _actor(_user)
    cfg = _m365_config()
    if not cfg["mailbox_user"]:
        raise HTTPException(status_code=503, detail="M365_MAILBOX_USER is not configured")
    top = int(body.get("top") or 25)
    top = max(1, min(100, top))
    try:
        token = _m365_token(cfg)
        select_cols = ",".join(
            [
                "id",
                "subject",
                "receivedDateTime",
                "internetMessageId",
                "bodyPreview",
                "body",
                "from",
                "toRecipients",
            ]
        )
        # Read latest inbox messages.
        list_url = (
            f"https://graph.microsoft.com/v1.0/users/{urlparse.quote(cfg['mailbox_user'])}/mailFolders/inbox/messages"
            f"?$top={top}&$orderby=receivedDateTime desc&$select={select_cols}"
        )
        payload = _m365_graph_get(token, list_url)
        values = payload.get("value") or []
        processed = 0
        matched = 0
        with get_conn() as con:
            for msg in values:
                inbound = _m365_to_inbound_payload(msg)
                result = _ingest_inbound_email(
                    con,
                    from_email=str(inbound.get("from_email") or ""),
                    from_name=str(inbound.get("from_name") or ""),
                    to_email=str(inbound.get("to_email") or ""),
                    subject=str(inbound.get("subject") or ""),
                    content=str(inbound.get("text") or ""),
                    received_at=inbound.get("received_at"),
                    message_id=str(inbound.get("message_id") or ""),
                    source_tag="sync:m365",
                )
                processed += 1
                if result.get("matched"):
                    matched += 1
        return {"ok": True, "processed": processed, "matched": matched}
    except HTTPError as e:
        try:
            details = e.read().decode("utf-8")
        except Exception:
            details = str(e)
        raise HTTPException(status_code=500, detail=f"Microsoft Graph error: {details}")
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Failed to sync inbound m365 emails: {e}")


def _ensure_m365_subscription_table(con) -> None:
    con.execute(
        """
        CREATE TABLE IF NOT EXISTS crm_m365_subscriptions (
          id SERIAL PRIMARY KEY,
          subscription_id VARCHAR NOT NULL UNIQUE,
          resource VARCHAR NOT NULL,
          notification_url VARCHAR NOT NULL,
          expiration_datetime TIMESTAMP NOT NULL,
          client_state VARCHAR,
          created_at TIMESTAMP NOT NULL DEFAULT NOW(),
          renewed_at TIMESTAMP,
          is_active BOOLEAN NOT NULL DEFAULT TRUE
        )
        """
    )


def _m365_graph_post(token: str, url: str, payload: dict) -> dict:
    data = json.dumps(payload).encode("utf-8")
    req = urlrequest.Request(url, data=data, method="POST")
    req.add_header("Authorization", f"Bearer {token}")
    req.add_header("Content-Type", "application/json")
    req.add_header("Accept", "application/json")
    with urlrequest.urlopen(req, timeout=30) as resp:
        return json.loads(resp.read().decode("utf-8"))


def _m365_graph_patch(token: str, url: str, payload: dict) -> dict:
    data = json.dumps(payload).encode("utf-8")
    req = urlrequest.Request(url, data=data, method="PATCH")
    req.add_header("Authorization", f"Bearer {token}")
    req.add_header("Content-Type", "application/json")
    req.add_header("Accept", "application/json")
    with urlrequest.urlopen(req, timeout=30) as resp:
        body = resp.read()
        return json.loads(body.decode("utf-8")) if body.strip() else {}


@router.post("/communications/inbound/m365/subscription/register")
def register_m365_subscription(body: dict = Body(default={}), _user: dict = Depends(_current_user)):
    """
    Register a Microsoft Graph webhook subscription so inbound emails to the admin
    mailbox are pushed to /communications/inbound/m365/notifications in real time.

    Requires env vars: M365_TENANT_ID, M365_CLIENT_ID, M365_CLIENT_SECRET, M365_MAILBOX_USER
    Optional: M365_CLIENT_STATE (secret used to verify notifications), APP_PUBLIC_URL

    The Azure app registration needs Mail.Read application permission (admin-consented).
    Subscriptions expire after ~3 days — call /renew to extend.
    """
    cfg = _m365_config()
    if not all([cfg["tenant_id"], cfg["client_id"], cfg["client_secret"], cfg["mailbox_user"]]):
        raise HTTPException(status_code=503, detail="M365 env vars not fully configured (need TENANT_ID, CLIENT_ID, CLIENT_SECRET, MAILBOX_USER)")

    app_url = str(body.get("app_public_url") or os.getenv("APP_PUBLIC_URL") or "").strip().rstrip("/")
    if not app_url:
        raise HTTPException(status_code=400, detail="Provide app_public_url in body or set APP_PUBLIC_URL env var (e.g. https://your-app.onrender.com/api/backend)")

    notification_url = f"{app_url}/communications/inbound/m365/notifications"
    resource = f"users/{cfg['mailbox_user']}/mailFolders/inbox/messages"

    from datetime import datetime, timedelta, timezone
    expiry = datetime.now(timezone.utc) + timedelta(minutes=4200)
    expiry_str = expiry.strftime("%Y-%m-%dT%H:%M:%S.0000000Z")

    try:
        token = _m365_token(cfg)
        payload = {
            "changeType": "created",
            "notificationUrl": notification_url,
            "resource": resource,
            "expirationDateTime": expiry_str,
            "latestSupportedTlsVersion": "v1_2",
        }
        if cfg["client_state"]:
            payload["clientState"] = cfg["client_state"]

        result = _m365_graph_post(token, "https://graph.microsoft.com/v1.0/subscriptions", payload)
        subscription_id = str(result.get("id") or "").strip()
        if not subscription_id:
            raise HTTPException(status_code=500, detail=f"Graph did not return a subscription id: {result}")

        with get_conn() as con:
            _ensure_m365_subscription_table(con)
            con.execute(
                """
                INSERT INTO crm_m365_subscriptions (subscription_id, resource, notification_url, expiration_datetime, client_state, is_active)
                VALUES (%s, %s, %s, %s, %s, TRUE)
                ON CONFLICT (subscription_id) DO UPDATE
                  SET is_active = TRUE, renewed_at = NOW(), expiration_datetime = EXCLUDED.expiration_datetime
                """,
                [subscription_id, resource, notification_url, expiry.replace(tzinfo=None), cfg["client_state"] or None],
            )

        return {
            "ok": True,
            "subscription_id": subscription_id,
            "notification_url": notification_url,
            "resource": resource,
            "expires": expiry_str,
            "note": "Subscription expires in ~3 days. Call /renew before then to keep it active.",
        }
    except HTTPError as e:
        try:
            details = e.read().decode("utf-8")
        except Exception:
            details = str(e)
        raise HTTPException(status_code=500, detail=f"Graph error registering subscription: {details}")
    except HTTPException:
        raise
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Failed to register M365 subscription: {e}")


@router.post("/communications/inbound/m365/subscription/renew")
def renew_m365_subscription(body: dict = Body(default={}), _user: dict = Depends(_current_user)):
    """
    Renew an existing M365 Graph subscription before it expires (~3-day lifetime).
    Pass subscription_id in body, or omit to renew the most recent active one.
    """
    cfg = _m365_config()
    if not all([cfg["tenant_id"], cfg["client_id"], cfg["client_secret"]]):
        raise HTTPException(status_code=503, detail="M365 env vars not configured")

    subscription_id = str(body.get("subscription_id") or "").strip()

    try:
        with get_conn() as con:
            _ensure_m365_subscription_table(con)
            if not subscription_id:
                row = con.execute(
                    "SELECT subscription_id FROM crm_m365_subscriptions WHERE is_active = TRUE ORDER BY created_at DESC LIMIT 1"
                ).fetchone()
                if not row:
                    raise HTTPException(status_code=404, detail="No active subscription found. Register one first.")
                subscription_id = str(row[0])

            from datetime import datetime, timedelta, timezone
            expiry = datetime.now(timezone.utc) + timedelta(minutes=4200)
            expiry_str = expiry.strftime("%Y-%m-%dT%H:%M:%S.0000000Z")

            token = _m365_token(cfg)
            _m365_graph_patch(
                token,
                f"https://graph.microsoft.com/v1.0/subscriptions/{urlparse.quote(subscription_id)}",
                {"expirationDateTime": expiry_str},
            )
            con.execute(
                """
                UPDATE crm_m365_subscriptions
                SET expiration_datetime = %s, renewed_at = NOW()
                WHERE subscription_id = %s
                """,
                [expiry.replace(tzinfo=None), subscription_id],
            )

        return {"ok": True, "subscription_id": subscription_id, "renewed_until": expiry_str}
    except HTTPError as e:
        try:
            details = e.read().decode("utf-8")
        except Exception:
            details = str(e)
        raise HTTPException(status_code=500, detail=f"Graph error renewing subscription: {details}")
    except HTTPException:
        raise
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Failed to renew M365 subscription: {e}")


def renew_m365_subscriptions_due(threshold_hours: int = 24) -> dict:
    """
    Renew all active M365 subscriptions expiring within threshold_hours.
    Returns {"renewed": [...], "skipped": int, "errors": [...]}
    Called by the internal cron endpoint.
    """
    from datetime import datetime, timedelta, timezone

    cfg = _m365_config()
    if not all([cfg["tenant_id"], cfg["client_id"], cfg["client_secret"]]):
        return {"renewed": [], "skipped": 0, "errors": ["M365 env vars not configured"]}

    renewed = []
    errors = []

    with get_conn() as con:
        _ensure_m365_subscription_table(con)
        cutoff = datetime.now(timezone.utc) + timedelta(hours=threshold_hours)
        rows = con.execute(
            """
            SELECT subscription_id FROM crm_m365_subscriptions
            WHERE is_active = TRUE AND expiration_datetime < %s
            ORDER BY expiration_datetime ASC
            """,
            [cutoff.replace(tzinfo=None)],
        ).fetchall()

        if not rows:
            return {"renewed": [], "skipped": 0, "errors": []}

        try:
            token = _m365_token(cfg)
        except Exception as e:
            return {"renewed": [], "skipped": len(rows), "errors": [f"Token error: {e}"]}

        expiry = datetime.now(timezone.utc) + timedelta(minutes=4200)
        expiry_str = expiry.strftime("%Y-%m-%dT%H:%M:%S.0000000Z")

        for (subscription_id,) in rows:
            try:
                _m365_graph_patch(
                    token,
                    f"https://graph.microsoft.com/v1.0/subscriptions/{urlparse.quote(subscription_id)}",
                    {"expirationDateTime": expiry_str},
                )
                con.execute(
                    "UPDATE crm_m365_subscriptions SET expiration_datetime = %s, renewed_at = NOW() WHERE subscription_id = %s",
                    [expiry.replace(tzinfo=None), subscription_id],
                )
                renewed.append({"subscription_id": subscription_id, "renewed_until": expiry_str})
            except Exception as e:
                errors.append({"subscription_id": subscription_id, "error": str(e)})

    return {"renewed": renewed, "skipped": 0, "errors": errors}


@router.get("/communications/inbound/m365/subscription/status")
def m365_subscription_status(_user: dict = Depends(_current_user)):
    """List all registered M365 subscriptions and their expiry status."""
    try:
        with get_conn() as con:
            _ensure_m365_subscription_table(con)
            df = con.execute(
                """
                SELECT subscription_id, resource, notification_url, expiration_datetime,
                       is_active, created_at, renewed_at
                FROM crm_m365_subscriptions
                ORDER BY created_at DESC
                LIMIT 20
                """
            ).df()
        items = []
        if df is not None and not df.empty:
            from datetime import datetime, timezone
            now = datetime.now(timezone.utc)
            for _, r in df.iterrows():
                exp = r.get("expiration_datetime")
                exp_iso = exp.isoformat() if exp else None
                expired = (exp.replace(tzinfo=timezone.utc) < now) if exp else True
                items.append({
                    "subscription_id": str(r.get("subscription_id") or ""),
                    "resource": str(r.get("resource") or ""),
                    "notification_url": str(r.get("notification_url") or ""),
                    "expiration_datetime": exp_iso,
                    "is_active": bool(r.get("is_active")),
                    "expired": expired,
                    "created_at": r.get("created_at").isoformat() if r.get("created_at") else None,
                    "renewed_at": r.get("renewed_at").isoformat() if r.get("renewed_at") else None,
                })
        return {"items": items}
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Failed to load subscription status: {e}")
