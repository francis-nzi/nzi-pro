def _choose_followup_rule(subject: str, message_text: str) -> dict[str, Any] | None:
    txt = f"{subject or ''}\n{message_text or ''}".lower()
    urgent = ["urgent", "asap", "immediately", "critical", "today", "blocking", "blocked"]
    high = ["issue", "problem", "error", "cannot", "can't", "failed", "failure", "complaint", "escalation"]
    normal = ["please", "can you", "could you", "when", "deadline", "clarify", "confirm", "update"]
    if any(k in txt for k in urgent):
        return {"priority": "urgent", "due_days": 1, "status": "open"}
    if any(k in txt for k in high):
        return {"priority": "high", "due_days": 2, "status": "open"}
    if any(k in txt for k in normal) or "?" in txt:
        return {"priority": "normal", "due_days": 5, "status": "open"}
    return None


def _resolve_assignee(con, job_id: int) -> str | None:
    row = con.execute(
        """
        SELECT j.crm_name, c.crm_owner
        FROM jobs j
        LEFT JOIN clients c ON c.db_id = j.client_db_id
        WHERE j.job_id = %s
        """,
        [int(job_id)],
    ).fetchone()
    if not row:
        return None
    candidate_names = [str(row[0] or "").strip(), str(row[1] or "").strip()]
    candidate_names = [x for x in candidate_names if x]
    for c in candidate_names:
        u = con.execute(
            """
            SELECT email, full_name
            FROM users
            WHERE lower(coalesce(email,'')) = lower(%s) OR lower(coalesce(full_name,'')) = lower(%s)
            LIMIT 1
            """,
            [c, c],
        ).fetchone()
        if u:
            return str(u[0] or u[1] or "").strip() or None
    return candidate_names[0] if candidate_names else None


def _maybe_create_auto_followup_task(
    con,
    *,
    job_id: int,
    communication_id: int,
    from_email: str,
    subject: str,
    message_text: str,
) -> dict[str, Any] | None:
    rule = _choose_followup_rule(subject, message_text)
    if not rule:
        return None

    exists = con.execute(
        """
        SELECT 1
        FROM job_communication_tasks
        WHERE job_id = %s AND communication_id = %s
        LIMIT 1
        """,
        [int(job_id), int(communication_id)],
    ).fetchone()
    if exists:
        return None

    assignee = _resolve_assignee(con, int(job_id))
    due = date.today() + timedelta(days=int(rule["due_days"]))
    title = f"Inbound follow-up: {subject[:110] if subject else '(No subject)'}"
    details = (
        f"Auto-created from inbound email.\n"
        f"From: {from_email or '-'}\n"
        f"Subject: {subject or '(No subject)'}\n\n"
        f"{message_text[:2000]}"
    )
    row = con.execute(
        """
        INSERT INTO job_communication_tasks (
          job_id, communication_id, title, details, assigned_to, priority, status, due_date, created_by, updated_at
        )
        VALUES (%s, %s, %s, %s, %s, %s, %s, %s, 'system:auto-inbound', NOW())
        RETURNING task_id
        """,
        [
            int(job_id),
            int(communication_id),
            title,
            details,
            assignee,
            str(rule["priority"]),
            str(rule["status"]),
            due.isoformat(),
        ],
    ).fetchone()
    return {"task_id": int(row[0]), "assigned_to": assignee, "priority": str(rule["priority"]), "due_date": due.isoformat()}


