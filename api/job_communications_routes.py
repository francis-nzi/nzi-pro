def _display_date(value: Any) -> str:
    if isinstance(value, date):
        return f"{value.day} {value.strftime('%B %Y')}"
    text = str(value or "").strip()
    if not text:
        return "-"
    try:
        parsed = date.fromisoformat(text[:10])
        return f"{parsed.day} {parsed.strftime('%B %Y')}"
    except Exception:
        return text


