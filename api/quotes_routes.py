def _build_financial_pdf_story(
    *,
    doc_title: str,
    left_details: list[str],
    middle_details: list[tuple[str, str]],
    subject_line: str | None,
    currency_code: str | None,
    lines: list[dict[str, Any]],
    options_lines: list[dict[str, Any]] | None,
    totals_rows: list[tuple[str, str]],
    notes: str | None,
    payment_terms_text: str | None,
    company_profile: dict[str, Any],
) -> list[Any]:
    styles = getSampleStyleSheet()
    title_style = ParagraphStyle("FinancialTitle", parent=styles["Title"], fontSize=28, leading=30, spaceAfter=3 * mm, alignment=0)
    normal_style = ParagraphStyle("FinancialNormal", parent=styles["Normal"], fontSize=10.5, leading=14)
    label_style = ParagraphStyle("FinancialLabel", parent=styles["Normal"], fontSize=10.5, leading=13, fontName="Helvetica-Bold")
    label_style_right = ParagraphStyle("FinancialLabelRight", parent=label_style, alignment=2)
    value_style = ParagraphStyle("FinancialValue", parent=styles["Normal"], fontSize=10.5, leading=13)
    value_style_right = ParagraphStyle("FinancialValueRight", parent=value_style, alignment=2)
    company_style = ParagraphStyle("FinancialCompany", parent=styles["Normal"], fontSize=9.5, leading=13, alignment=2)
    subject_style = ParagraphStyle("FinancialSubject", parent=styles["Heading2"], fontSize=14, leading=16, fontName="Helvetica-Bold")

    currency = str(currency_code or "GBP").strip().upper()
    amount_header = f"Amount {currency}"
    story: list[Any] = []

    left_text = "<br/>".join([line for line in left_details if str(line or "").strip()])
    middle_parts: list[str] = []
    for label, value in middle_details:
        middle_parts.append(f"<b>{label}</b><br/>{value or '-'}<br/><br/>")
    middle_text = "".join(middle_parts).strip()

    right_parts: list[Any] = []
    company_name = str(company_profile.get("company_display_name") or company_profile.get("company_legal_name") or "Net Zero International")
    company_address = company_address_html(company_profile) or "167-169 Great Portland Street<br/>London<br/>W1W 9PF<br/>United Kingdom"
    logo_path = _nzi_logo_path()
    if logo_path:
        right_parts.append(Image(logo_path, width=48 * mm, height=24 * mm, kind="proportional"))
        right_parts.append(Spacer(1, 1 * mm))
    right_parts.append(Paragraph(f"{company_name}<br/>{company_address}", company_style))
    right_block = Table([[right_parts]], colWidths=[50 * mm])
    right_block.setStyle(TableStyle([("LEFTPADDING", (0, 0), (-1, -1), 0), ("RIGHTPADDING", (0, 0), (-1, -1), 0), ("TOPPADDING", (0, 0), (-1, -1), 0), ("BOTTOMPADDING", (0, 0), (-1, -1), 0)]))

    title_cell: list[Any] = [Paragraph(doc_title, title_style)]
    if left_text:
        title_cell.append(Spacer(1, 2 * mm))
        title_cell.append(Paragraph(left_text, normal_style))

    header = Table(
        [
            [
                title_cell,
                Paragraph(middle_text, normal_style),
                right_block,
            ]
        ],
        colWidths=[88 * mm, 52 * mm, 50 * mm],
    )
    header.setStyle(
        TableStyle(
            [
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("LEFTPADDING", (0, 0), (-1, -1), 0),
                ("RIGHTPADDING", (0, 0), (-1, -1), 0),
                ("TOPPADDING", (0, 0), (-1, -1), 0),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 0),
            ]
        )
    )
    story.append(header)
    story.append(Spacer(1, 10 * mm))

    if subject_line:
        story.append(Paragraph(subject_line, subject_style))
        story.append(Spacer(1, 6 * mm))

    def _lines_table(data_lines: list[dict[str, Any]], title: str | None = None) -> None:
        if title:
            story.append(Paragraph(f"<b>{title}</b>", normal_style))
            story.append(Spacer(1, 2 * mm))
        rows: list[list[Any]] = [["Costs", "Quantity", "Rate", "VAT %", amount_header]]
        for line in data_lines:
            qty = _safe_float(line.get("qty"), 0.0)
            rate = _safe_float(line.get("rate"), 0.0)
            amount = _safe_float(line.get("amount"), qty * rate)
            vat_pct = _safe_float(line.get("vat_rate_pct"), 0.0)
            item_name = str(line.get("item_name") or "").strip()
            description = str(line.get("description") or "").strip() or "-"
            line_notes = str(line.get("notes") or "").strip()
            top = f"<b>{item_name}</b><br/>" if item_name else ""
            detail = f"{top}{description}"
            if line_notes:
                detail = f"{detail}<br/>{line_notes}"
            rows.append(
                [
                    Paragraph(detail.replace("\n", "<br/>"), normal_style),
                    f"{qty:,.2f}",
                    f"{rate:,.2f}",
                    f"{vat_pct:.1f}%",
                    f"{amount:,.2f}",
                ]
            )
        lines_table = Table(rows, colWidths=[100 * mm, 20 * mm, 23 * mm, 21 * mm, 26 * mm])
        lines_table.setStyle(
            TableStyle(
                [
                    ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                    ("LINEBELOW", (0, 0), (-1, 0), 0.8, colors.HexColor("#222222")),
                    ("ALIGN", (1, 0), (-1, -1), "RIGHT"),
                    ("VALIGN", (0, 0), (-1, -1), "TOP"),
                    ("LEFTPADDING", (0, 0), (-1, -1), 3),
                    ("RIGHTPADDING", (0, 0), (-1, -1), 3),
                    ("TOPPADDING", (0, 0), (-1, -1), 5),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
                    ("LINEBELOW", (0, -1), (-1, -1), 0.4, colors.HexColor("#cccccc")),
                ]
            )
        )
        story.append(lines_table)

    _lines_table(lines)
    story.append(Spacer(1, 5 * mm))

    totals_data = [
        [
            Paragraph(label, label_style if label.strip().lower().startswith("total") else value_style),
            Paragraph(value, label_style_right if label.strip().lower().startswith("total") else value_style_right),
        ]
        for label, value in totals_rows
    ]
    totals_table = Table(totals_data, colWidths=[34 * mm, 34 * mm], hAlign="RIGHT")
    totals_table.setStyle(
        TableStyle(
            [
                ("ALIGN", (1, 0), (1, -1), "RIGHT"),
                ("LEFTPADDING", (0, 0), (-1, -1), 3),
                ("RIGHTPADDING", (0, 0), (-1, -1), 3),
                ("TOPPADDING", (0, 0), (-1, -1), 3),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
                ("LINEABOVE", (0, -1), (-1, -1), 0.8, colors.HexColor("#222222")),
            ]
        )
    )
    story.append(totals_table)

    if options_lines is not None:
        story.append(Spacer(1, 5 * mm))
        if options_lines:
            _lines_table(options_lines, "Options")
        else:
            story.append(Paragraph("<b>Options</b>", normal_style))
            story.append(Spacer(1, 1.5 * mm))
            story.append(Paragraph("(No options)", normal_style))

    if payment_terms_text is not None:
        story.append(Spacer(1, 5 * mm))
        term_value = str(payment_terms_text or "").strip() or "-"
        story.append(Paragraph(f"<b>Payment terms:</b> {term_value}", normal_style))

    if str(notes or "").strip():
        story.append(Spacer(1, 6 * mm))
        story.append(Paragraph("<b>Notes</b>", normal_style))
        story.append(Paragraph(str(notes).replace("\n", "<br/>"), normal_style))

    return story


