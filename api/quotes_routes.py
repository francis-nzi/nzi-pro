def _write_lines(con, quote_id: int, lines: list[dict[str, Any]]) -> None:
    con.execute("DELETE FROM quote_lines WHERE quote_id = %s", [int(quote_id)])
    for idx, line in enumerate(lines):
        qty = _safe_float(line.get("qty"), 0.0)
        rate = _safe_float(line.get("rate"), 0.0)
        amount = _safe_float(line.get("amount"), qty * rate)
        con.execute(
            """
            INSERT INTO quote_lines (
              quote_id, line_type, sort_order, job_type_id, item_id, category, description, unit,
              qty, unit_price_ex_vat, amount_ex_vat, vat_rate_id, vat_rate_pct, is_selected, notes
            )
            VALUES (%s, %s, %s, NULL, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
            """,
            [
                int(quote_id),
                str(line.get("line_type") or "main"),
                _safe_int(line.get("sort_order"), idx + 1),
                _safe_int(line.get("item_id"), None),
                str(line.get("category") or ""),
                str(line.get("description") or ""),
                str(line.get("unit") or ""),
                qty,
                rate,
                amount,
                _safe_int(line.get("vat_rate_id"), None),
                _safe_float(line.get("vat_rate_pct"), 0.0),
                bool(line.get("is_selected") if line.get("is_selected") is not None else True),
                str(line.get("notes") or ""),
            ],
        )


@router.post("/clients/{client_id}/quotes")
def create_quote(client_id: int, body: dict = Body(...), _user: dict = Depends(_current_user)):
    try:
        with get_conn() as con:
            _ensure_quote_tables(con)
            org_id = _quote_org_id(_user)
            _require_org_plan_active(con, org_id)
            client_exists = con.execute(
                "SELECT db_id FROM clients WHERE db_id = %s" + (" AND org_id = %s" if org_id else ""),
                [int(client_id)] + ([org_id] if org_id else []),
            ).fetchone()
            if not client_exists:
                raise HTTPException(status_code=404, detail="Client not found")
            quote_date = str(body.get("quote_date") or date.today().isoformat())
            quote_number = str(body.get("quote_number") or "").strip()
            if not quote_number:
                quote_number = _next_quote_number(con, org_id=org_id)

            insert_cols = [
                "client_db_id", "contact_id", "quote_number", "quote_date", "valid_to", "salesperson",
                "payment_term_id", "currency_code", "description", "notes", "status", "revision_of_quote_id",
                "job_number", "attention", "bill_to",
            ]
            insert_vals: list[Any] = [
                int(client_id),
                _safe_int(body.get("contact_id"), None),
                quote_number,
                quote_date,
                str(body.get("valid_to") or "") or None,
                str(body.get("salesperson") or ""),
                _safe_int(body.get("payment_term_id"), 1),
                str(body.get("currency_code") or "GBP").upper(),
                str(body.get("description") or ""),
                str(body.get("notes") or ""),
                str(body.get("status") or "Draft"),
                _safe_int(body.get("revision_of_quote_id"), None),
                str(body.get("job_number") or ""),
                str(body.get("attention") or ""),
                str(body.get("bill_to") or ""),
            ]
            if org_id:
                insert_cols.insert(0, "org_id")
                insert_vals.insert(0, org_id)
            placeholders = ", ".join(["%s"] * len(insert_vals))
            con.execute(
                f"""
                INSERT INTO quotes (
                  {", ".join(insert_cols)}
                )
                VALUES ({placeholders})
                """,
                insert_vals,
            )
            row = con.execute(
                "SELECT MAX(quote_id) FROM quotes WHERE client_db_id = %s" + (" AND org_id = %s" if org_id else ""),
                [int(client_id)] + ([org_id] if org_id else []),
            ).fetchone()
            if not row or row[0] is None:
                raise HTTPException(status_code=500, detail="Failed to create quote")
            quote_id = int(row[0])

            lines = body.get("lines") or []
            if not isinstance(lines, list):
                raise HTTPException(status_code=400, detail="lines must be an array")
            _write_lines(con, quote_id, lines)

            return _serialize_quote(con, quote_id, org_id=org_id)
    except HTTPException:
        raise
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Failed to create quote: {e}")


@router.patch("/quotes/{quote_id}")
def update_quote(quote_id: int, body: dict = Body(...), _user: dict = Depends(_current_user)):
    try:
        with get_conn() as con:
            _ensure_quote_tables(con)
            org_id = _quote_org_id(_user)
            existing = con.execute(
                "SELECT quote_id FROM quotes WHERE quote_id = %s" + (" AND org_id = %s" if org_id else ""),
                [int(quote_id)] + ([org_id] if org_id else []),
            ).fetchone()
            if not existing:
                raise HTTPException(status_code=404, detail="Quote not found")

            updates = []
            params: list[Any] = []
            for key, col in [
                ("contact_id", "contact_id"),
                ("quote_number", "quote_number"),
                ("quote_date", "quote_date"),
                ("valid_to", "valid_to"),
                ("salesperson", "salesperson"),
                ("payment_term_id", "payment_term_id"),
                ("currency_code", "currency_code"),
                ("description", "description"),
                ("notes", "notes"),
                ("status", "status"),
                ("revision_of_quote_id", "revision_of_quote_id"),
                ("job_number", "job_number"),
                ("attention", "attention"),
                ("bill_to", "bill_to"),
            ]:
                if key not in body:
                    continue
                value = body.get(key)
                if key in ("contact_id", "payment_term_id", "revision_of_quote_id"):
                    value = _safe_int(value, None)
                elif key == "currency_code":
                    value = str(value or "GBP").upper()
                updates.append(f"{col} = %s")
                params.append(value)

            if updates:
                updates.append("updated_at = NOW()")
                params.append(int(quote_id))
                if org_id:
                    params.append(org_id)
                    con.execute(f"UPDATE quotes SET {', '.join(updates)} WHERE quote_id = %s AND org_id = %s", params)
                else:
                    con.execute(f"UPDATE quotes SET {', '.join(updates)} WHERE quote_id = %s", params)

            if "lines" in body:
                lines = body.get("lines") or []
                if not isinstance(lines, list):
                    raise HTTPException(status_code=400, detail="lines must be an array")
                _write_lines(con, int(quote_id), lines)

            return _serialize_quote(con, int(quote_id), org_id=org_id)
    except HTTPException:
        raise
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Failed to update quote: {e}")


