@router.get("/clients/{client_id}/financial/summary")
def client_financial_summary(client_id: int, _user: dict = Depends(_current_user)):
    try:
        assert_client_access(_user, int(client_id))
        with get_conn() as con:
            _ensure_quote_tables(con)
            org_id = _quote_org_id(_user)
            if org_id:
                quote_ids_df = con.execute(
                    """
                    SELECT quote_id
                    FROM quotes
                    WHERE client_db_id = %s
                      AND org_id = %s
                    """,
                    [int(client_id), org_id],
                ).df()
            else:
                quote_ids_df = con.execute(
                    """
                    SELECT quote_id
                    FROM quotes
                    WHERE client_db_id = %s
                    """,
                    [int(client_id)],
                ).df()
            quote_total = 0.0
            quote_count = 0
            if quote_ids_df is not None and not quote_ids_df.empty:
                for _, r in quote_ids_df.iterrows():
                    qid = _safe_int(r.get("quote_id"), None)
                    if qid is None:
                        continue
                    quote_count += 1
                    if org_id:
                        line_df = con.execute(
                            """
                            SELECT line_type, qty, unit_price_ex_vat, vat_rate_pct
                            FROM quote_lines
                            WHERE quote_id = %s
                              AND org_id = %s
                            """,
                            [int(qid), org_id],
                        ).df()
                    else:
                        line_df = con.execute(
                            """
                            SELECT line_type, qty, unit_price_ex_vat, vat_rate_pct
                            FROM quote_lines
                            WHERE quote_id = %s
                            """,
                            [int(qid)],
                        ).df()
                    lines = []
                    if line_df is not None and not line_df.empty:
                        for _, l in line_df.iterrows():
                            lines.append(
                                {
                                    "line_type": str(l.get("line_type") or "main"),
                                    "qty": _safe_float(l.get("qty"), 0.0),
                                    "rate": _safe_float(l.get("unit_price_ex_vat"), 0.0),
                                    "vat_rate_pct": _safe_float(l.get("vat_rate_pct"), 0.0),
                                }
                            )
                    quote_total += _compute_totals(lines)["total"]

            if org_id:
                inv_df = con.execute(
                    """
                    SELECT invoice_id, subtotal, vat, total, status, amount_paid
                    FROM invoices
                    WHERE client_db_id = %s
                      AND org_id = %s
                    """,
                    [int(client_id), org_id],
                ).df()
            else:
                inv_df = con.execute(
                    """
                    SELECT invoice_id, subtotal, vat, total, status, amount_paid
                    FROM invoices
                    WHERE client_db_id = %s
                    """,
                    [int(client_id)],
                ).df()

            invoice_count = 0
            invoiced_total = 0.0
            vat_total = 0.0
            paid_total = 0.0
            outstanding_total = 0.0
            overdue_count = 0
            if inv_df is not None and not inv_df.empty:
                invoice_count = int(len(inv_df.index))
                for _, row in inv_df.iterrows():
                    total = _safe_float(row.get("total"), 0.0)
                    vat_value = _safe_float(row.get("vat"), 0.0)
                    amount_paid = _safe_float(row.get("amount_paid"), 0.0)
                    status = str(row.get("status") or "").strip().lower()
                    invoiced_total += total
                    vat_total += vat_value
                    paid_total += amount_paid if amount_paid > 0 else (total if status == "paid" else 0.0)
                    if status not in ("paid", "void"):
                        outstanding_total += max(0.0, total - amount_paid)
                    if status == "overdue":
                        overdue_count += 1

            variance = invoiced_total - quote_total
            realization_pct = (invoiced_total / quote_total * 100.0) if quote_total > 0 else 0.0
            if org_id:
                time_df = con.execute(
                    """
                    SELECT tl.minutes, jt.unit_price_ex_vat, jt.estimated_hours
                    FROM time_logs tl
                    JOIN jobs j ON j.job_id = tl.job_id
                    LEFT JOIN job_types jt ON jt.job_type_id = j.job_type_id
                    WHERE j.client_db_id = %s
                      AND COALESCE(tl.org_id, %s) = %s
                      AND COALESCE(j.org_id, %s) = %s
                    """,
                    [int(client_id), org_id, org_id, org_id, org_id],
                ).df()
            else:
                time_df = con.execute(
                    """
                    SELECT tl.minutes, jt.unit_price_ex_vat, jt.estimated_hours
                    FROM time_logs tl
                    JOIN jobs j ON j.job_id = tl.job_id
                    LEFT JOIN job_types jt ON jt.job_type_id = j.job_type_id
                    WHERE j.client_db_id = %s
                    """,
                    [int(client_id)],
                ).df()
            actual_cost_from_time = 0.0
            logged_hours = 0.0
            if time_df is not None and not time_df.empty:
                for _, tr in time_df.iterrows():
                    minutes = _safe_float(tr.get("minutes"), 0.0)
                    hours = minutes / 60.0
                    logged_hours += hours
                    unit_price = _safe_float(tr.get("unit_price_ex_vat"), 0.0)
                    estimated_hours = _safe_float(tr.get("estimated_hours"), 0.0)
                    hourly_rate = unit_price / estimated_hours if unit_price > 0 and estimated_hours > 0 else 0.0
                    actual_cost_from_time += hours * hourly_rate
            time_cost_variance = actual_cost_from_time - quote_total
            if org_id:
                other_df = con.execute(
                    """
                    SELECT amount_ex_vat, vat_amount, total_inc_vat
                    FROM job_other_costs oc
                    JOIN jobs j ON j.job_id = oc.job_id
                    WHERE j.client_db_id = %s
                      AND COALESCE(oc.org_id, %s) = %s
                      AND COALESCE(j.org_id, %s) = %s
                    """,
                    [int(client_id), org_id, org_id, org_id, org_id],
                ).df()
            else:
                other_df = con.execute(
                    """
                    SELECT amount_ex_vat, vat_amount, total_inc_vat
                    FROM job_other_costs oc
                    JOIN jobs j ON j.job_id = oc.job_id
                    WHERE j.client_db_id = %s
                    """,
                    [int(client_id)],
                ).df()
            other_subtotal = 0.0
            other_vat = 0.0
            other_total = 0.0
            other_count = 0
            if other_df is not None and not other_df.empty:
                other_count = int(len(other_df.index))
                for _, row in other_df.iterrows():
                    other_subtotal += _safe_float(row.get("amount_ex_vat"), 0.0)
                    other_vat += _safe_float(row.get("vat_amount"), 0.0)
                    other_total += _safe_float(row.get("total_inc_vat"), 0.0)

            return {
                "client_db_id": int(client_id),
                "quotes": {
                    "count": int(quote_count),
                    "estimated_total": round(quote_total, 2),
                },
                "invoices": {
                    "count": int(invoice_count),
                    "invoiced_total": round(invoiced_total, 2),
                    "vat_total": round(vat_total, 2),
                    "paid_total": round(paid_total, 2),
                    "outstanding_total": round(outstanding_total, 2),
                    "overdue_count": int(overdue_count),
                },
                "other_costs": {
                    "count": int(other_count),
                    "subtotal": round(other_subtotal, 2),
                    "vat_total": round(other_vat, 2),
                    "total": round(other_total, 2),
                },
                "analysis": {
                    "variance_amount": round(variance, 2),
                    "realization_pct": round(realization_pct, 2),
                    "actual_cost_from_time": round(actual_cost_from_time, 2),
                    "logged_hours": round(logged_hours, 2),
                    "time_cost_variance_vs_estimate": round(time_cost_variance, 2),
                    "actual_cost_total": round(actual_cost_from_time + other_total, 2),
                    "gross_profit_after_costs": round(paid_total - (actual_cost_from_time + other_total), 2),
                },
            }
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Failed to load financial summary: {e}")


