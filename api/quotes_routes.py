@router.patch("/invoices/{invoice_id}")
def update_invoice(invoice_id: int, body: dict = Body(...), _user: dict = Depends(_current_user)):
    try:
        with get_conn() as con:
            _ensure_quote_tables(con)
            org_id = _quote_org_id(_user)
            exists = con.execute(
                "SELECT invoice_id, xero_invoice_id FROM invoices WHERE invoice_id = %s AND org_id = %s",
                [int(invoice_id), org_id],
            ).fetchone()
            if not exists:
                raise HTTPException(status_code=404, detail="Invoice not found")
            xero_invoice_id = str(exists[1] or "").strip() if len(exists) > 1 else ""

            updates = []
            params: list[Any] = []
            for key, col in [
                ("job_id", "job_id"),
                ("quote_id", "quote_id"),
                ("invoice_number", "invoice_number"),
                ("invoice_date", "invoice_date"),
                ("due_date", "due_date"),
                ("currency_code", "currency_code"),
                ("subtotal", "subtotal"),
                ("vat", "vat"),
                ("total", "total"),
                ("status", "status"),
                ("notes", "notes"),
                ("paid_date", "paid_date"),
                ("amount_paid", "amount_paid"),
            ]:
                if key not in body:
                    continue
                value = body.get(key)
                if key in ("job_id", "quote_id"):
                    value = _safe_int(value, None)
                elif key == "currency_code":
                    value = str(value or "GBP").upper()
                elif key in ("subtotal", "vat", "total", "amount_paid"):
                    value = _safe_float(value, 0.0)
                elif key in ("due_date", "paid_date") and (value is None or str(value).strip() == ""):
                    value = None
                updates.append(f"{col} = %s")
                params.append(value)

            line_totals = None
            if "lines" in body:
                lines = body.get("lines") or []
                if not isinstance(lines, list):
                    raise HTTPException(status_code=400, detail="lines must be an array")
                _write_invoice_lines(con, int(invoice_id), lines, org_id=org_id)
                line_totals = _invoice_totals_from_lines(lines)
                updates.extend(["subtotal = %s", "vat = %s", "total = %s"])
                params.extend([line_totals["subtotal"], line_totals["vat"], line_totals["total"]])

            if not updates:
                raise HTTPException(status_code=400, detail="No updates provided")

            if xero_invoice_id:
                updates.append("xero_sync_status = %s")
                params.append("needs_resync")
                updates.append("xero_sync_error = %s")
                params.append(None)
            updates.append("updated_at = NOW()")
            params.append(int(invoice_id))
            params.append(org_id)
            con.execute(f"UPDATE invoices SET {', '.join(updates)} WHERE invoice_id = %s AND org_id = %s", params)
            return _serialize_invoice(con, int(invoice_id), org_id=org_id)
    except HTTPException:
        raise
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Failed to update invoice: {e}")


