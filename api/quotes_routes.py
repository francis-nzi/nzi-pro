def _compute_totals(lines: list[dict[str, Any]]) -> dict[str, float]:
    subtotal = 0.0
    vat = 0.0
    options_subtotal = 0.0
    options_vat = 0.0
    for line in lines:
        qty = _safe_float(line.get("qty"), 0.0)
        rate = _safe_float(line.get("rate"), 0.0)
        line_vat_pct = _safe_float(line.get("vat_rate_pct"), 0.0)
        amount = qty * rate
        line_vat = amount * (line_vat_pct / 100.0)
        is_option = str(line.get("line_type") or "main").lower() == "option"
        if is_option:
            options_subtotal += amount
            options_vat += line_vat
        else:
            subtotal += amount
            vat += line_vat
    return {
        "subtotal": round(subtotal, 2),
        "vat": round(vat, 2),
        "total": round(subtotal + vat, 2),
        "options_subtotal": round(options_subtotal, 2),
        "options_vat": round(options_vat, 2),
        "options_total": round(options_subtotal + options_vat, 2),
    }


def _next_quote_number(con, org_id: str | None = None) -> str:
    org_clause = " AND org_id = %s" if org_id else ""
    params = [org_id] if org_id else []
    df = con.execute(
        f"SELECT quote_number FROM quotes WHERE quote_number IS NOT NULL{org_clause}",
        params,
    ).df()
    max_base = 999
    if df is not None and not df.empty:
        for _, r in df.iterrows():
            qn = str(r.get("quote_number") or "").strip()
            m = re.match(r"^Q(\d+)(?:/(\d+))?$", qn, flags=re.IGNORECASE)
            if not m:
                continue
            base_num = int(m.group(1))
            if base_num > max_base:
                max_base = base_num
    nxt = max_base + 1
    return f"Q{nxt:06d}/1"


def _revision_quote_number(con, base_prefix: str, org_id: str | None = None) -> str:
    """Given base prefix like Q001000, return next revision suffix /N."""
    org_clause = " AND org_id = %s" if org_id else ""
    params: list[Any] = [f"{base_prefix}/%"]
    if org_id:
        params.append(org_id)
    df = con.execute(
        f"""
        SELECT quote_number
        FROM quotes
        WHERE quote_number ILIKE %s{org_clause}
        """,
        params,
    ).df()
    max_rev = 0
    if df is not None and not df.empty:
        for _, r in df.iterrows():
            qn = str(r.get("quote_number") or "").strip()
            m = re.match(rf"^{re.escape(base_prefix)}/(\d+)$", qn, flags=re.IGNORECASE)
            if not m:
                continue
            rev = int(m.group(1))
            if rev > max_rev:
                max_rev = rev
    return f"{base_prefix}/{max_rev + 1}"


def _default_due_date(invoice_date_str: str | None) -> str:
    """Default due date: 7 days after the invoice date."""
    try:
        base = date.fromisoformat(str(invoice_date_str or "")[:10])
    except Exception:
        base = date.today()
    return (base + timedelta(days=7)).isoformat()


def _next_invoice_number(con, org_id: str | None = None) -> str:
    org_clause = " AND org_id = %s" if org_id else ""
    params = [org_id] if org_id else []
    df = con.execute(
        f"SELECT invoice_number FROM invoices WHERE invoice_number IS NOT NULL{org_clause}",
        params,
    ).df()
    max_num = 999
    if df is not None and not df.empty:
        for _, r in df.iterrows():
            inv = str(r.get("invoice_number") or "").strip()
            m = re.match(r"^I(\d+)$", inv, flags=re.IGNORECASE)
            if not m:
                continue
            value = int(m.group(1))
            if value > max_num:
                max_num = value
    return f"I{max_num + 1:06d}"


def _invoice_lines_for(con, invoice_id: int, org_id: str | None = None) -> list[dict[str, Any]]:
    org_clause = " AND i.org_id = %s" if org_id else ""
    params: list[Any] = [int(invoice_id)]
    if org_id:
        params.append(str(org_id).strip())
    df = con.execute(
        """
        SELECT il.invoice_line_id, il.invoice_id, il.sort_order, il.item_id, ji.item_name, il.description, il.unit,
               il.qty, il.unit_price_ex_vat, il.amount_ex_vat, il.vat_rate_id, il.vat_rate_pct, il.notes
        FROM invoice_lines il
        JOIN invoices i ON i.invoice_id = il.invoice_id
        LEFT JOIN job_items ji ON ji.item_id = il.item_id
        WHERE il.invoice_id = %s
        """ + org_clause + """
        ORDER BY COALESCE(il.sort_order, 0), il.invoice_line_id
        """,
        params,
    ).df()
    lines: list[dict[str, Any]] = []
    if df is None or df.empty:
        return lines
    for _, r in df.iterrows():
        qty = _safe_float(r.get("qty"), 0.0)
        rate = _safe_float(r.get("unit_price_ex_vat"), 0.0)
        amount = _safe_float(r.get("amount_ex_vat"), qty * rate)
        lines.append(
            {
                "invoice_line_id": _safe_int(r.get("invoice_line_id"), 0),
                "sort_order": _safe_int(r.get("sort_order"), 0),
                "item_id": _safe_int(r.get("item_id"), None),
                "item_name": str(r.get("item_name") or ""),
                "description": str(r.get("description") or ""),
                "unit": str(r.get("unit") or ""),
                "qty": qty,
                "rate": rate,
                "amount": round(amount, 2),
                "vat_rate_id": _safe_int(r.get("vat_rate_id"), None),
                "vat_rate_pct": _safe_float(r.get("vat_rate_pct"), 0.0),
                "notes": str(r.get("notes") or ""),
            }
        )
    return lines


def _invoice_totals_from_lines(lines: list[dict[str, Any]]) -> dict[str, float]:
    subtotal = 0.0
    vat = 0.0
    for line in lines:
        qty = _safe_float(line.get("qty"), 0.0)
        rate = _safe_float(line.get("rate"), 0.0)
        vat_pct = _safe_float(line.get("vat_rate_pct"), 0.0)
        amount = _safe_float(line.get("amount"), qty * rate)
        subtotal += amount
        vat += amount * (vat_pct / 100.0)
    return {
        "subtotal": round(subtotal, 2),
        "vat": round(vat, 2),
        "total": round(subtotal + vat, 2),
    }


