def _serialize_quote(con, quote_id: int, org_id: str | None = None) -> dict[str, Any]:
    quote_org_clause = " AND quotes.org_id = %s" if org_id else ""
    line_org_clause = " AND q.org_id = %s" if org_id else ""
    params: list[Any] = [int(quote_id)]
    if org_id:
        params.append(str(org_id).strip())
    q = con.execute(
        """
        SELECT quotes.quote_id, quotes.client_db_id, quotes.contact_id, quotes.quote_number, quotes.quote_date, quotes.valid_to, quotes.salesperson,
               quotes.payment_term_id, pt.name AS payment_term_name, quotes.currency_code, quotes.description, quotes.notes, quotes.status, quotes.revision_of_quote_id,
               quotes.job_number, quotes.attention, quotes.bill_to, quotes.created_at, quotes.updated_at, quotes.org_id, c.client_name
        FROM quotes
        LEFT JOIN payment_terms_lookup pt ON pt.term_id = quotes.payment_term_id
        LEFT JOIN clients c ON c.db_id = quotes.client_db_id
        WHERE quotes.quote_id = %s
        """ + quote_org_clause + """
        """,
        params,
    ).fetchone()
    if not q:
        raise HTTPException(status_code=404, detail="Quote not found")

    df = con.execute(
        """
        SELECT ql.line_id, ql.quote_id, ql.line_type, ql.sort_order, ql.item_id, ji.item_name, ql.category, ql.description, ql.unit,
               ql.qty, ql.unit_price_ex_vat, ql.amount_ex_vat, ql.vat_rate_id, ql.vat_rate_pct, ql.is_selected, ql.notes
        FROM quote_lines ql
        JOIN quotes q ON q.quote_id = ql.quote_id
        LEFT JOIN job_items ji ON ji.item_id = ql.item_id
        WHERE ql.quote_id = %s
        """ + line_org_clause + """
        ORDER BY COALESCE(ql.sort_order, 0), ql.line_id
        """,
        params,
    ).df()

    lines: list[dict[str, Any]] = []
    if df is not None and not df.empty:
        for _, r in df.iterrows():
            qty = _safe_float(r.get("qty"), 0.0)
            rate = _safe_float(r.get("unit_price_ex_vat"), 0.0)
            amount = _safe_float(r.get("amount_ex_vat"), qty * rate)
            lines.append(
                {
                    "line_id": _safe_int(r.get("line_id"), 0),
                    "line_type": str(r.get("line_type") or "main"),
                    "sort_order": _safe_int(r.get("sort_order"), 0),
                    "item_id": _safe_int(r.get("item_id"), None),
                    "item_name": str(r.get("item_name") or ""),
                    "category": str(r.get("category") or ""),
                    "description": str(r.get("description") or ""),
                    "unit": str(r.get("unit") or ""),
                    "qty": qty,
                    "rate": rate,
                    "amount": round(amount, 2),
                    "vat_rate_id": _safe_int(r.get("vat_rate_id"), None),
                    "vat_rate_pct": _safe_float(r.get("vat_rate_pct"), 0.0),
                    "is_selected": bool(r.get("is_selected") if r.get("is_selected") is not None else True),
                    "notes": str(r.get("notes") or ""),
                }
            )

    totals = _compute_totals(lines)
    return {
        "quote_id": int(q[0]),
        "client_db_id": int(q[1]),
        "client_name": str(q[20] or "") if len(q) > 20 and q[20] is not None else "",
        "contact_id": _safe_int(q[2], None),
        "quote_number": str(q[3] or ""),
        "quote_date": q[4].isoformat() if q[4] else None,
        "valid_to": q[5].isoformat() if q[5] else None,
        "salesperson": str(q[6] or ""),
        "payment_term_id": _safe_int(q[7], None),
        "payment_term_name": str(q[8] or ""),
        "currency_code": str(q[9] or "GBP"),
        "description": str(q[10] or ""),
        "notes": str(q[11] or ""),
        "status": str(q[12] or ""),
        "revision_of_quote_id": _safe_int(q[13], None),
        "job_number": str(q[14] or ""),
        "attention": str(q[15] or ""),
        "bill_to": str(q[16] or ""),
        "created_at": q[17].isoformat() if q[17] else None,
        "updated_at": q[18].isoformat() if q[18] else None,
        "lines": lines,
        "totals": totals,
        "company_profile": get_company_profile(con),
        "org_id": str(q[19] or "") if len(q) > 19 and q[19] is not None else str(org_id or ""),
    }


