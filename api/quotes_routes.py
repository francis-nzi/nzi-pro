def convert_quote_to_invoice(quote_id: int, body: dict = Body(default={}), _user: dict = Depends(_current_user)):
    try:
        with get_conn() as con:
            _ensure_quote_tables(con)
            org_id = _quote_org_id(_user)
            quote = _serialize_quote(con, int(quote_id), org_id=org_id)
            invoice_number = _next_invoice_number(con, org_id=org_id)
            invoice_date = str(body.get("invoice_date") or date.today().isoformat())
            due_date = str(body.get("due_date") or "").strip() or _default_due_date(invoice_date)
            status = str(body.get("status") or "Draft")

            lines = []
            for idx, line in enumerate(quote.get("lines") or []):
                if str(line.get("line_type") or "main").lower() == "option":
                    continue
                lines.append(
                    {
                        "sort_order": idx + 1,
                        "item_id": _safe_int(line.get("item_id"), None),
                        "description": str(line.get("description") or ""),
                        "unit": str(line.get("unit") or ""),
                        "qty": _safe_float(line.get("qty"), 0.0),
                        "rate": _safe_float(line.get("rate"), 0.0),
                        "amount": _safe_float(line.get("amount"), 0.0),
                        "vat_rate_id": _safe_int(line.get("vat_rate_id"), None),
                        "vat_rate_pct": _safe_float(line.get("vat_rate_pct"), 0.0),
                        "notes": str(line.get("notes") or ""),
                    }
                )
            totals = _invoice_totals_from_lines(lines)

            con.execute(
                """
                INSERT INTO invoices (
                  client_db_id, org_id, job_id, quote_id, invoice_number, invoice_date, due_date,
                  currency_code, subtotal, vat, total, status, notes, paid_date, amount_paid,
                  created_at, updated_at
                )
                VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, NULL, 0, NOW(), NOW())
                """,
                [
                    int(quote["client_db_id"]),
                    org_id,
                    _safe_int(body.get("job_id"), None),
                    int(quote_id),
                    invoice_number,
                    invoice_date,
                    due_date,
                    str(quote.get("currency_code") or "GBP"),
                    totals["subtotal"],
                    totals["vat"],
                    totals["total"],
                    status,
                    str(body.get("notes") or quote.get("notes") or ""),
                ],
            )
            row = con.execute(
                "SELECT MAX(invoice_id) FROM invoices WHERE client_db_id = %s AND org_id = %s",
                [int(quote["client_db_id"]), org_id],
            ).fetchone()
            if not row or row[0] is None:
                raise HTTPException(status_code=500, detail="Failed to convert quote to invoice")
            invoice_id = int(row[0])
            _write_invoice_lines(con, int(invoice_id), lines, org_id=org_id)
            return _serialize_invoice(con, int(invoice_id), org_id=org_id)
    except HTTPException:
        raise
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Failed to convert quote to invoice: {e}")


