@router.post("/clients/{client_id}/invoices")
def create_invoice(client_id: int, body: dict = Body(...), _user: dict = Depends(_current_user)):
    try:
        with get_conn() as con:
            _ensure_quote_tables(con)
            org_id = _quote_org_id(_user)
            _require_org_plan_active(con, org_id)
            client_exists = con.execute(
                "SELECT db_id FROM clients WHERE db_id = %s AND org_id = %s",
                [int(client_id), org_id],
            ).fetchone()
            if not client_exists:
                raise HTTPException(status_code=404, detail="Client not found")
            job_id = _safe_int(body.get("job_id"), None)
            if job_id is None:
                raise HTTPException(status_code=400, detail="job_id is required to create an invoice")
            job_exists = con.execute(
                "SELECT job_id FROM jobs WHERE job_id = %s AND client_db_id = %s",
                [job_id, int(client_id)],
            ).fetchone()
            if not job_exists:
                raise HTTPException(status_code=400, detail="job_id does not belong to this client")
            invoice_number = str(body.get("invoice_number") or "").strip() or _next_invoice_number(con, org_id=org_id)
            invoice_date = str(body.get("invoice_date") or date.today().isoformat())

            lines = body.get("lines") or []
            if not isinstance(lines, list):
                raise HTTPException(status_code=400, detail="lines must be an array")
            computed_totals = _invoice_totals_from_lines(lines) if lines else None

            con.execute(
                """
                INSERT INTO invoices (
                  client_db_id, org_id, job_id, quote_id, invoice_number, invoice_date, due_date,
                  currency_code, subtotal, vat, total, status, notes, paid_date, amount_paid,
                  created_at, updated_at
                )
                VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, NOW(), NOW())
                """,
                [
                    int(client_id),
                    org_id,
                    job_id,
                    _safe_int(body.get("quote_id"), None),
                    invoice_number,
                    invoice_date,
                    str(body.get("due_date") or "").strip() or _default_due_date(invoice_date),
                    str(body.get("currency_code") or "GBP").upper(),
                    computed_totals["subtotal"] if computed_totals else _safe_float(body.get("subtotal"), 0.0),
                    computed_totals["vat"] if computed_totals else _safe_float(body.get("vat"), 0.0),
                    computed_totals["total"] if computed_totals else _safe_float(body.get("total"), 0.0),
                    str(body.get("status") or "Draft"),
                    str(body.get("notes") or ""),
                    str(body.get("paid_date") or "") or None,
                    _safe_float(body.get("amount_paid"), 0.0),
                ],
            )
            row = con.execute(
                "SELECT MAX(invoice_id) FROM invoices WHERE client_db_id = %s AND org_id = %s",
                [int(client_id), org_id],
            ).fetchone()
            if not row or row[0] is None:
                raise HTTPException(status_code=500, detail="Failed to create invoice")
            invoice_id = int(row[0])
            if lines:
                _write_invoice_lines(con, invoice_id, lines, org_id=org_id)
                con.execute(
                    "UPDATE invoices SET subtotal = %s, vat = %s, total = %s, updated_at = NOW() WHERE invoice_id = %s",
                    [computed_totals["subtotal"], computed_totals["vat"], computed_totals["total"], int(invoice_id)],
                )
            return _serialize_invoice(con, invoice_id, org_id=org_id)
    except HTTPException:
        raise
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Failed to create invoice: {e}")


