def _get_sessions_for_run(con, org_id: str, training_course_run_id: int) -> list[dict[str, Any]]:
    rows = con.execute(
        """
        SELECT s.training_course_session_id, s.org_id, s.training_course_run_id, s.session_title, s.session_date,
               s.start_time, s.end_time, s.session_hours, s.delivery_mode, s.venue_name, s.venue_address,
               s.online_meeting_url, s.online_meeting_id, s.online_passcode, s.status, s.notes,
               COALESCE(counts.attendance_count, 0), COALESCE(counts.attended_count, 0),
               s.created_at, s.created_by, s.updated_at, s.updated_by
        FROM training_course_sessions s
        LEFT JOIN (
          SELECT training_course_session_id,
                 COUNT(*) AS attendance_count,
                 COUNT(*) FILTER (WHERE attendance_status = 'attended') AS attended_count
          FROM training_session_attendance
          WHERE org_id = ?::text
          GROUP BY training_course_session_id
        ) counts ON counts.training_course_session_id = s.training_course_session_id
        WHERE s.org_id = ?::text AND s.training_course_run_id = ?
        ORDER BY COALESCE(s.session_date, CURRENT_DATE), s.start_time NULLS LAST, s.training_course_session_id
        """,
        [org_id, org_id, int(training_course_run_id)],
    ).fetchall()
    sessions: list[dict[str, Any]] = []
    for row in rows:
        attendance_rows = con.execute(
            """
            SELECT a.training_session_attendance_id, a.org_id, a.training_course_session_id, a.training_booking_id,
                   a.attendance_status, a.attendance_minutes, a.notes, b.person_name, b.person_email, c.client_name,
                   b.booking_source, b.participant_type, b.attendance_status, b.entitlement_id,
                   a.created_at, a.created_by, a.updated_at, a.updated_by
            FROM training_session_attendance a
            JOIN training_bookings b ON b.training_booking_id = a.training_booking_id
            LEFT JOIN clients c ON c.db_id = b.client_db_id
            WHERE a.org_id = ?::text AND a.training_course_session_id = ?
            ORDER BY b.person_name, a.training_session_attendance_id
            """,
            [org_id, int(row[0])],
        ).fetchall()
        sessions.append(_session_payload(row, [_attendance_payload(att) for att in attendance_rows]))
    return sessions


