    actor = _actor(_user)
    booking_id = _clean_int(body.get("booking_id"))
    if booking_id is None:
        raise HTTPException(status_code=400, detail="booking_id is required")
    with get_conn() as con:
        _ensure_tables(con)
        _assert_entitlement_access(_user, con, int(training_entitlement_id), org_id)
        _assert_booking_access(_user, con, int(booking_id), org_id)
        _sync_booking_entitlement(con, int(booking_id), int(training_entitlement_id), actor, org_id)
        row = con.execute(
            """
            SELECT e.training_entitlement_id, e.org_id, e.source_job_id,
                   COALESCE(e.source_job_number, j.job_number),
                   e.source_client_db_id, e.entitlement_type, e.status, e.allocated_to_booking_id,
                   e.reserved_at, e.consumed_at, e.expires_at, e.notes,
                   c.client_name, COALESCE(b.person_name, ''),
                   e.created_at, e.created_by, e.updated_at, e.updated_by
            FROM training_entitlements e
            LEFT JOIN jobs j ON j.job_id = e.source_job_id
            LEFT JOIN clients c ON c.db_id = e.source_client_db_id
            LEFT JOIN training_bookings b ON b.training_booking_id = e.allocated_to_booking_id
            WHERE e.training_entitlement_id = ? AND e.org_id = ?
            """,
            [int(training_entitlement_id), org_id],
        ).fetchone()
        return _entitlement_payload(row)
