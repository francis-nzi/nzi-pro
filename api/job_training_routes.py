    for idx, question in enumerate(questions, start=1):
        elements.append(Paragraph(f"{idx}. {html.escape(question)}", styles["QBody"]))
        elements.append(Spacer(1, 12 * mm))
    doc.build(elements)
    return buffer.getvalue()


