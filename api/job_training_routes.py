def _clean_text(value: Any) -> str | None:
    if value is None:
        return None
    text = str(value).strip()
    return text or None


def _clean_int(value: Any) -> int | None:
    if value in (None, ""):
        return None
    try:
        return int(value)
    except Exception:
        return None


def _clean_float(value: Any) -> float | None:
    if value in (None, ""):
        return None
    try:
        return float(value)
    except Exception:
        return None


def _clean_bool(value: Any, default: bool = True) -> bool:
    if value in (None, ""):
        return default
    if isinstance(value, bool):
        return value
    return str(value).strip().lower() in {"1", "true", "yes", "y", "on"}


def _json_text(value: Any, default: list[Any] | dict[str, Any] | None = None) -> str:
    if value in (None, ""):
        return json.dumps(default if default is not None else [])
    if isinstance(value, str):
        text = value.strip()
        if not text:
            return json.dumps(default if default is not None else [])
        try:
            parsed = json.loads(text)
            return json.dumps(parsed)
        except Exception:
            return text
    try:
        return json.dumps(value)
    except Exception:
        return json.dumps(default if default is not None else [])


def _json_list(value: Any, default: list[Any] | None = None) -> list[Any]:
    if value in (None, ""):
        return list(default or [])
    if isinstance(value, list):
        return value
    if isinstance(value, tuple):
        return list(value)
    try:
        parsed = json.loads(str(value))
        if isinstance(parsed, list):
            return parsed
    except Exception:
        pass
    return list(default or [])


def _safe_date_text(value: Any) -> str:
    if value is None:
        return ""
    if isinstance(value, (date, datetime)):
        try:
            return value.isoformat()
        except Exception:
            return str(value)
    return str(value)


def _safe_datetime_text(value: Any) -> str | None:
    if value is None:
        return None
    if isinstance(value, datetime):
        return value.isoformat()
    try:
        return datetime.fromisoformat(str(value)).isoformat()
    except Exception:
        return str(value)


