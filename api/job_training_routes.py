def _resolve_training_product(con, org_id: str, product_id: int | None) -> dict[str, Any] | None:
    if product_id is None:
        return None
    row = con.execute(
        """
        SELECT training_product_id, org_id, product_code, product_name, description, default_hours,
               default_delivery_mode, default_capacity, default_min_attendees, certificate_policy,
               default_documents_json, is_active, created_at, created_by, updated_at, updated_by
        FROM training_products
        WHERE training_product_id = ? AND org_id = ?
        """,
        [int(product_id), org_id],
    ).fetchone()
    return _product_payload(row) if row else None


def _list_training_products(con, org_id: str, include_inactive: bool = False) -> list[dict[str, Any]]:
    sql = """
        SELECT training_product_id, org_id, product_code, product_name, description, default_hours,
               default_delivery_mode, default_capacity, default_min_attendees, certificate_policy,
               default_documents_json, is_active, created_at, created_by, updated_at, updated_by
        FROM training_products
        WHERE org_id = ?
    """
    params: list[Any] = [org_id]
    if not include_inactive:
        sql += " AND is_active = TRUE"
    sql += " ORDER BY product_name ASC, training_product_id DESC"
    rows = con.execute(sql, params).fetchall()
    return [_product_payload(row) for row in rows]


def _get_course_run_rows(con, org_id: str, job_id: int) -> list[dict[str, Any]]:
    run_rows = con.execute(
        """
        SELECT r.training_course_run_id, r.org_id, r.job_id, r.training_product_id, p.product_name,
               r.run_name, r.course_code, r.total_hours, r.delivery_mode, r.capacity, r.min_attendees,
               r.status, r.workflow_stage_key, r.start_date, r.end_date, r.venue_name, r.venue_address,
               r.online_meeting_url, r.online_meeting_id, r.online_passcode, r.notes,
               COALESCE(counts.booking_count, 0), COALESCE(counts.confirmed_count, 0),
               r.created_at, r.created_by, r.updated_at, r.updated_by
        FROM training_course_runs r
        LEFT JOIN training_products p ON p.training_product_id = r.training_product_id
        LEFT JOIN (
          SELECT training_course_run_id,
                 COUNT(*) AS booking_count,
                 COUNT(*) FILTER (WHERE attendance_status IN ('booked', 'confirmed', 'attended')) AS confirmed_count
          FROM training_bookings
          WHERE org_id = ?
          GROUP BY training_course_run_id
        ) counts ON counts.training_course_run_id = r.training_course_run_id
        WHERE r.org_id = ? AND r.job_id = ?
        ORDER BY COALESCE(r.start_date, CURRENT_DATE), r.training_course_run_id DESC
        """,
        [org_id, org_id, int(job_id)],
    ).fetchall()
    if not run_rows:
        return []

    run_ids = [int(row[0]) for row in run_rows]
    placeholders = ",".join(["?"] * len(run_ids))
    booking_rows = con.execute(
        f"""
        SELECT b.training_booking_id, b.org_id, b.training_course_run_id, b.client_db_id, b.contact_id,
               b.participant_type, b.booking_source, b.person_name, b.person_email, b.person_phone,
               b.billing_status, b.attendance_status, b.special_requirements, b.consent_status,
               b.notes, b.entitlement_id, c.client_name, e.source_job_number,
               e.status, COALESCE(b2.person_name, ''),
               b.created_at, b.created_by, b.updated_at, b.updated_by
        FROM training_bookings b
        LEFT JOIN clients c ON c.db_id = b.client_db_id
        LEFT JOIN training_entitlements e ON e.training_entitlement_id = b.entitlement_id
        LEFT JOIN training_bookings b2 ON b2.training_booking_id = e.allocated_to_booking_id
        WHERE b.org_id = ? AND b.training_course_run_id IN ({placeholders})
        ORDER BY b.training_course_run_id, b.person_name, b.training_booking_id
        """,
        [org_id, *run_ids],
    ).fetchall()
    bookings_by_run: dict[int, list[dict[str, Any]]] = {run_id: [] for run_id in run_ids}
    for row in booking_rows:
        bookings_by_run.setdefault(int(row[2]), []).append(_booking_payload(row))

    payload: list[dict[str, Any]] = []
    for row in run_rows:
        run_payload = _run_payload(row, bookings_by_run.get(int(row[0]), []))
        payload.append(run_payload)
    return payload


def _get_available_entitlements(con, org_id: str) -> list[dict[str, Any]]:
    rows = con.execute(
        """
        SELECT e.training_entitlement_id, e.org_id, e.source_job_id, COALESCE(e.source_job_number, j.job_number),
               e.source_client_db_id, e.entitlement_type, e.status, e.allocated_to_booking_id,
               e.reserved_at, e.consumed_at, e.expires_at, e.notes,
               c.client_name, COALESCE(b.person_name, ''),
               e.created_at, e.created_by, e.updated_at, e.updated_by
        FROM training_entitlements e
        LEFT JOIN jobs j ON j.job_id = e.source_job_id
        LEFT JOIN clients c ON c.db_id = e.source_client_db_id
        LEFT JOIN training_bookings b ON b.training_booking_id = e.allocated_to_booking_id
        WHERE e.org_id = ? AND e.status IN ('available', 'reserved')
        ORDER BY CASE e.status WHEN 'available' THEN 0 WHEN 'reserved' THEN 1 ELSE 2 END,
                 e.training_entitlement_id DESC
        """,
        [org_id],
    ).fetchall()
    return [_entitlement_payload(row) for row in rows]


