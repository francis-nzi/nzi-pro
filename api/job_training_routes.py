@router.delete("/training-course-runs/{training_course_run_id}")
def delete_training_run(
    training_course_run_id: int,
    _user: dict[str, str] = Depends(_current_user),
):
    assert_permission(_user, "jobs.edit")
    org_id = require_org(_user)
    with get_conn() as con:
        _ensure_tables(con)
        run = con.execute(
            "SELECT training_course_run_id FROM training_course_runs WHERE training_course_run_id = ? AND org_id = ?::text",
            [int(training_course_run_id), org_id],
        ).fetchone()
        if not run:
            raise HTTPException(status_code=404, detail="Course run not found")
        active = con.execute(
            "SELECT COUNT(*) FROM training_bookings WHERE training_course_run_id = ? AND attendance_status NOT IN ('cancelled', 'no_show')",
            [int(training_course_run_id)],
        ).fetchone()
        if active and int(active[0]) > 0:
            raise HTTPException(
                status_code=409,
                detail=f"Cannot delete run with {active[0]} active booking(s). Cancel all bookings first.",
            )
        con.execute(
            "DELETE FROM training_course_runs WHERE training_course_run_id = ? AND org_id = ?::text",
            [int(training_course_run_id), org_id],
        )
        return {"ok": True}


