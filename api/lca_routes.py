@router.post("/jobs/{job_id}/lca/products/{product_id}/bom-upload")
async def upload_bom_file(
    job_id: int,
    product_id: int,
    file: UploadFile = File(...),
    _user: dict[str, str] = Depends(_current_user),
):
    try:
        filename = str(file.filename or "").strip().lower()
        raw = await file.read()
        if not raw:
            raise HTTPException(status_code=400, detail="Uploaded file is empty")

        if filename.endswith(".csv"):
            df = pd.read_csv(io.BytesIO(raw))
        elif filename.endswith(".xlsx") or filename.endswith(".xlsm") or filename.endswith(".xls"):
            df = pd.read_excel(io.BytesIO(raw))
        else:
            raise HTTPException(status_code=400, detail="Unsupported file type. Use CSV or XLSX.")

        if df is None or df.empty:
            raise HTTPException(status_code=400, detail="No rows found in BOM file")

        norm_map = {_normalize_col(c): c for c in df.columns}

        def getv(row: Any, names: list[str], default: Any = None) -> Any:
            for name in names:
                original = norm_map.get(_normalize_col(name))
                if original is not None:
                    val = row.get(original)
                    if val is not None and str(val).strip() != "":
                        return val
            return default

        inserted = 0
        mapped = 0
        gap_filled = 0
        skipped = 0

        with get_conn() as con:
            _ensure_tables(con)
            if not _product_exists(con, int(job_id), int(product_id)):
                raise HTTPException(status_code=404, detail="LCA product not found")
            dataset_ids = _resolve_lca_dataset_ids(con, int(job_id), int(product_id))

            for _, row in df.iterrows():
                item_name = str(
                    getv(
                        row,
                        ["item_name", "material", "material_name", "component", "component_name", "name", "description"],
                        "",
                    )
                    or ""
                ).strip()
                if not item_name:
                    skipped += 1
                    continue

                stage_raw = str(getv(row, ["stage", "stage_key", "lifecycle_stage"], "materials") or "materials").strip().lower()
                stage_key = stage_raw if stage_raw in STAGE_KEYS else "materials"
                qty = safe_float(getv(row, ["quantity", "qty", "weight", "unit_weight", "mass"], 0))
                unit = str(getv(row, ["unit", "uom", "units"], "kg") or "kg").strip()
                origin_country = str(getv(row, ["origin_country", "country", "raw_material_origin_country"], "") or "").strip()
                item_description = str(getv(row, ["item_description", "description", "notes"], "") or "").strip()
                explicit_factor = safe_float(getv(row, ["factor", "factor_value", "emission_factor"], 0))
                explicit_factor_unit = str(getv(row, ["factor_unit", "emission_factor_unit"], "kgCO2e/unit") or "kgCO2e/unit").strip()

                row_insert = con.execute(
                    """
                    INSERT INTO lca_inventory_items (
                      product_id, stage_key, item_name, item_description, quantity, unit,
                      origin_country, raw_material_origin, factor_value, factor_unit,
                      data_quality, created_by, updated_by
                    )
                    VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
                    RETURNING item_id
                    """,
                    [
                        int(product_id),
                        stage_key,
                        item_name,
                        item_description or None,
                        qty,
                        unit or None,
                        origin_country or None,
                        origin_country or None,
                        explicit_factor,
                        explicit_factor_unit,
                        "secondary",
                        _actor(_user),
                        _actor(_user),
                    ],
                ).fetchone()
                item_id = int(row_insert[0])
                inserted += 1

                if explicit_factor > 0:
                    continue

                candidates = _find_factor_candidates(
                    con,
                    item_name=item_name,
                    stage_key=stage_key,
                    unit=unit,
                    country=origin_country,
                    dataset_ids=dataset_ids,
                )
                if candidates:
                    top = candidates[0]
                    con.execute(
                        """
                        UPDATE lca_inventory_items
                        SET mapped_factor_db_id = %s, factor_value = %s, factor_unit = %s, factor_source = %s,
                            lci_database_name = %s, is_gap_filled = FALSE, gap_fill_method = NULL,
                            updated_at = NOW(), updated_by = %s
                        WHERE item_id = %s
                        """,
                        [
                            int(top["db_id"]),
                            safe_float(top["factor"]),
                            str(top.get("uom") or "kgCO2e/unit"),
                            str(top.get("source") or "factor_lookup"),
                            "factor_lookup",
                            _actor(_user),
                            item_id,
                        ],
                    )
                    mapped += 1
                else:
                    estimate, method = _estimate_gap_factor(con, stage_key, unit, dataset_ids=dataset_ids)
                    if estimate > 0:
                        con.execute(
                            """
                            UPDATE lca_inventory_items
                            SET factor_value = %s, factor_unit = COALESCE(NULLIF(factor_unit, ''), %s),
                                factor_source = 'predictive_estimate', lci_database_name = 'estimated',
                                is_gap_filled = TRUE, gap_fill_method = %s, updated_at = NOW(), updated_by = %s
                            WHERE item_id = %s
                            """,
                            [estimate, "kgCO2e/unit", method, _actor(_user), item_id],
                        )
                        gap_filled += 1

            summary = _recalculate_product(con, int(product_id), _user)

        return {
            "ok": True,
            "rows_total": int(len(df.index)),
            "inserted": inserted,
            "mapped": mapped,
            "gap_filled": gap_filled,
            "skipped": skipped,
            "dataset_ids_used": dataset_ids,
            "summary": summary,
        }
    except HTTPException:
        raise
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Failed to import BOM file: {e}")
