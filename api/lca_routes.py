def _job_exists(con, job_id: int) -> bool:
    row = con.execute("SELECT 1 FROM jobs WHERE job_id = %s LIMIT 1", [int(job_id)]).fetchone()
    return bool(row)


def _product_exists(con, job_id: int, product_id: int) -> bool:
    row = con.execute(
        "SELECT 1 FROM lca_products WHERE job_id = %s AND product_id = %s LIMIT 1",
        [int(job_id), int(product_id)],
    ).fetchone()
    return bool(row)


def _table_exists(con, table_name: str) -> bool:
    row = con.execute(
        """
        SELECT EXISTS (
          SELECT 1
          FROM information_schema.tables
          WHERE table_name = %s
        )
        """,
        [str(table_name)],
    ).fetchone()
    return bool(row and row[0])


def _to_int_list(raw: Any) -> list[int]:
    if raw is None:
        return []
    if isinstance(raw, (list, tuple, set)):
        items = list(raw)
    else:
        text = str(raw).strip()
        if not text:
            return []
        items = [x.strip() for x in text.split(",")]
    out: list[int] = []
    for v in items:
        try:
            iv = int(v)
            if iv > 0:
                out.append(iv)
        except Exception:
            continue
    return sorted(set(out))


def _get_product_dataset_ids(con, product_id: int) -> list[int]:
    df = con.execute(
        "SELECT dataset_id FROM lca_product_datasets WHERE product_id = %s ORDER BY dataset_id",
        [int(product_id)],
    ).df()
    if df is None or df.empty:
        return []
    out: list[int] = []
    for _, r in df.iterrows():
        val = r.get("dataset_id")
        if val is None:
            continue
        out.append(int(val))
    return sorted(set(out))


def _set_product_dataset_ids(con, product_id: int, dataset_ids: list[int], user: dict[str, str]) -> list[int]:
    clean = sorted(set(int(x) for x in dataset_ids if int(x) > 0))
    if clean:
        ph = ",".join(["%s"] * len(clean))
        valid_df = con.execute(
            f"SELECT dataset_id FROM datasets WHERE dataset_id IN ({ph}) AND COALESCE(archived, FALSE) = FALSE",
            clean,
        ).df()
        valid_ids = sorted(set(int(r.get("dataset_id")) for _, r in valid_df.iterrows())) if valid_df is not None and not valid_df.empty else []
    else:
        valid_ids = []

    con.execute("DELETE FROM lca_product_datasets WHERE product_id = %s", [int(product_id)])
    for dsid in valid_ids:
        con.execute(
            """
            INSERT INTO lca_product_datasets (product_id, dataset_id, created_by)
            VALUES (%s, %s, %s)
            ON CONFLICT (product_id, dataset_id) DO NOTHING
            """,
            [int(product_id), int(dsid), _actor(user)],
        )
    return valid_ids


def _get_job_dataset_ids(con, job_id: int) -> list[int]:
    out: list[int] = []
    if _table_exists(con, "job_scope_config"):
        df_scope = con.execute(
            """
            SELECT DISTINCT dataset_id
            FROM job_scope_config
            WHERE job_id = %s
              AND dataset_id IS NOT NULL
            """,
            [int(job_id)],
        ).df()
        if df_scope is not None and not df_scope.empty:
            for _, r in df_scope.iterrows():
                val = r.get("dataset_id")
                if val is not None:
                    out.append(int(val))
    if _table_exists(con, "job_additional_datasets"):
        df_additional = con.execute(
            "SELECT DISTINCT dataset_id FROM job_additional_datasets WHERE job_id = %s",
            [int(job_id)],
        ).df()
        if df_additional is not None and not df_additional.empty:
            for _, r in df_additional.iterrows():
                val = r.get("dataset_id")
                if val is not None:
                    out.append(int(val))
    return sorted(set(out))


def _resolve_lca_dataset_ids(con, job_id: int, product_id: int | None = None) -> list[int]:
    selected = _get_product_dataset_ids(con, int(product_id)) if product_id is not None else []
    if selected:
        return selected
    return _get_job_dataset_ids(con, int(job_id))


def _list_available_datasets(con) -> list[dict[str, Any]]:
    df = con.execute(
        """
        SELECT dataset_id, name, analysis_type, country, year, version
        FROM datasets
        WHERE COALESCE(archived, FALSE) = FALSE
        ORDER BY year DESC NULLS LAST, name ASC
        """
    ).df()
    out: list[dict[str, Any]] = []
    if df is None or df.empty:
        return out
    for _, r in df.iterrows():
        out.append(
            {
                "dataset_id": int(r.get("dataset_id")),
                "name": str(r.get("name") or ""),
                "analysis_type": str(r.get("analysis_type") or ""),
                "country": str(r.get("country") or ""),
                "year": int(r.get("year")) if r.get("year") is not None else None,
                "version": str(r.get("version") or ""),
            }
        )
    return out


def _load_product_item_rows(con, product_id: int) -> list[dict[str, Any]]:
    df = con.execute(
        """
        SELECT item_id, stage_key, item_name, quantity, factor_value, factor_unit,
               allocation_pct, is_gap_filled, data_quality
        FROM lca_inventory_items
        WHERE product_id = %s
        ORDER BY item_id
        """,
        [int(product_id)],
    ).df()
    if df is None or df.empty:
        return []
    rows: list[dict[str, Any]] = []
    for _, r in df.iterrows():
        rows.append(
            {
                "item_id": int(r.get("item_id") or 0),
                "stage_key": str(r.get("stage_key") or "materials"),
                "item_name": str(r.get("item_name") or "Unnamed item"),
                "quantity": safe_float(r.get("quantity")),
                "factor_value": safe_float(r.get("factor_value")),
                "factor_unit": str(r.get("factor_unit") or "kgCO2e/unit"),
                "allocation_pct": safe_float(r.get("allocation_pct"), 100.0),
                "is_gap_filled": bool(r.get("is_gap_filled") or False),
                "data_quality": str(r.get("data_quality") or "secondary"),
            }
        )
    return rows


def _recalculate_product(con, product_id: int, user: dict[str, str]) -> dict[str, Any]:
    rows = _load_product_item_rows(con, int(product_id))
    summary = summarize_items(rows)
    con.execute(
        """
        UPDATE lca_products
        SET total_embedded_tco2e = %s,
            last_calculated_at = NOW(),
            updated_at = NOW(),
            updated_by = %s
        WHERE product_id = %s
        """,
        [summary["total_tco2e"], _actor(user), int(product_id)],
    )
    con.execute(
        """
        INSERT INTO lca_result_snapshots (
          product_id, calculated_by, total_tco2e, stage_breakdown_json, hotspots_json, notes
        )
        VALUES (%s, %s, %s, %s, %s, %s)
        """,
        [
            int(product_id),
            _actor(user),
            summary["total_tco2e"],
            str(summary["stage_breakdown"]),
            str(summary["hotspots"]),
            "Auto recalculation",
        ],
    )
    return summary


def _find_factor_candidates(
    con,
    item_name: str,
    stage_key: str,
    unit: str,
    country: str | None,
    dataset_ids: list[int] | None = None,
) -> list[dict[str, Any]]:
    stage_keywords = {
        "materials": "material raw bom purchased goods",
        "manufacturing": "manufacturing electricity gas process plant",
        "logistics": "transport freight logistics delivery shipping",
        "use_end_of_life": "use lifecycle recycling landfill disposal waste",
    }
    keyword_blob = stage_keywords.get(stage_key, "")
    item_pattern = f"%{item_name.strip()}%"
    unit_pattern = str(unit or "").strip()
    country_pattern = str(country or "").strip()
    words = [w for w in keyword_blob.split() if w]
    keyword_expr = " OR ".join(
        [
            "(COALESCE(fl.report_label,'') ILIKE %s OR COALESCE(fl.column_text,'') ILIKE %s OR COALESCE(fl.level_1,'') ILIKE %s OR COALESCE(fl.level_2,'') ILIKE %s)"
            for _ in words
        ]
    )
    keyword_params: list[Any] = []
    for word in words:
        pat = f"%{word}%"
        keyword_params.extend([pat, pat, pat, pat])

    where_clause = "COALESCE(fl.factor, 0) > 0 AND (COALESCE(fl.report_label,'') ILIKE %s OR COALESCE(fl.column_text,'') ILIKE %s)"
    params: list[Any] = [item_pattern, item_pattern]
    if keyword_expr:
        where_clause = f"{where_clause} OR ({keyword_expr})"
        params.extend(keyword_params)

    selected = sorted(set(int(x) for x in (dataset_ids or []) if int(x) > 0))
    if selected:
        ph = ",".join(["%s"] * len(selected))
        where_clause = f"({where_clause}) AND fl.dataset_id IN ({ph})"
        params.extend(selected)

    df = con.execute(
        f"""
        SELECT
          fl.db_id,
          fl.report_label,
          fl.column_text,
          fl.uom,
          fl.factor,
          fl.source,
          fl.region,
          fl.country,
          (
            CASE WHEN COALESCE(fl.uom, '') <> '' AND lower(fl.uom) = lower(%s) THEN 20 ELSE 0 END +
            CASE WHEN %s <> '' AND lower(COALESCE(fl.country,'')) = lower(%s) THEN 15 ELSE 0 END +
            CASE WHEN COALESCE(fl.report_label,'') ILIKE %s OR COALESCE(fl.column_text,'') ILIKE %s THEN 25 ELSE 0 END
          ) AS score
        FROM v_factor_lookup fl
        WHERE {where_clause}
        ORDER BY score DESC, fl.year DESC NULLS LAST, fl.db_id DESC
        LIMIT 10
        """,
        [unit_pattern, country_pattern, country_pattern, item_pattern, item_pattern, *params],
    ).df()
    out: list[dict[str, Any]] = []
    if df is None or df.empty:
        return out
    for _, r in df.iterrows():
        out.append(
            {
                "db_id": int(r.get("db_id")),
                "label": str(r.get("report_label") or r.get("column_text") or f"Factor {r.get('db_id')}"),
                "uom": r.get("uom"),
                "factor": safe_float(r.get("factor")),
                "source": r.get("source"),
                "country": r.get("country"),
                "region": r.get("region"),
                "score": safe_float(r.get("score")),
            }
        )
    return out


def _estimate_gap_factor(
    con,
    stage_key: str,
    unit: str,
    dataset_ids: list[int] | None = None,
) -> tuple[float, str]:
    stage_words = {
        "materials": ["material", "raw", "bom", "ingredient", "component"],
        "manufacturing": ["manufacturing", "process", "electric", "gas", "plant"],
        "logistics": ["transport", "logistics", "freight", "delivery"],
        "use_end_of_life": ["use", "recycling", "landfill", "disposal", "waste"],
    }.get(stage_key, [])
    unit_text = str(unit or "").strip()

    base_sql = """
        SELECT percentile_cont(0.5) WITHIN GROUP (ORDER BY fl.factor) AS p50_factor
        FROM v_factor_lookup fl
        WHERE fl.factor IS NOT NULL
          AND fl.factor > 0
    """
    params: list[Any] = []
    if unit_text:
        base_sql += " AND lower(COALESCE(fl.uom,'')) = lower(%s)"
        params.append(unit_text)
    if stage_words:
        conditions: list[str] = []
        for _ in stage_words:
            conditions.append(
                "(COALESCE(fl.report_label,'') ILIKE %s OR COALESCE(fl.column_text,'') ILIKE %s OR COALESCE(fl.level_1,'') ILIKE %s OR COALESCE(fl.level_2,'') ILIKE %s)"
            )
        base_sql += f" AND ({' OR '.join(conditions)})"
        for word in stage_words:
            pat = f"%{word}%"
            params.extend([pat, pat, pat, pat])

    selected = sorted(set(int(x) for x in (dataset_ids or []) if int(x) > 0))
    if selected:
        ph = ",".join(["%s"] * len(selected))
        base_sql += f" AND fl.dataset_id IN ({ph})"
        params.extend(selected)

    row = con.execute(base_sql, params).fetchone()
    estimated = safe_float(row[0] if row else 0.0)
    if estimated > 0:
        return estimated, "median_factor_by_stage_and_unit"

    sql2 = """
        SELECT percentile_cont(0.5) WITHIN GROUP (ORDER BY fl.factor)
        FROM v_factor_lookup fl
        WHERE fl.factor IS NOT NULL
          AND fl.factor > 0
          AND (%s = '' OR lower(COALESCE(fl.uom,'')) = lower(%s))
    """
    params2: list[Any] = [unit_text, unit_text]
    if selected:
        ph2 = ",".join(["%s"] * len(selected))
        sql2 += f" AND fl.dataset_id IN ({ph2})"
        params2.extend(selected)
    row2 = con.execute(sql2, params2).fetchone()
    estimated2 = safe_float(row2[0] if row2 else 0.0)
    if estimated2 > 0:
        return estimated2, "median_factor_by_unit"
    return 0.0, "no_estimate_available"


def _normalize_col(col: Any) -> str:
    return str(col or "").strip().lower().replace("-", "_").replace(" ", "_")


@router.get("/jobs/{job_id}/lca/overview")
def lca_overview(job_id: int, _user: dict[str, str] = Depends(_current_user)):
    try:
        with get_conn() as con:
            _ensure_tables(con)
            if not _job_exists(con, int(job_id)):
                raise HTTPException(status_code=404, detail="Job not found")
            products_df = con.execute(
                """
                SELECT product_id, product_name, sku, functional_unit_value, functional_unit_unit,
                       system_boundary, lca_standard, total_embedded_tco2e, last_calculated_at
                FROM lca_products
                WHERE job_id = %s
                ORDER BY product_id DESC
                """,
                [int(job_id)],
            ).df()
            products: list[dict[str, Any]] = []
            portfolio_total = 0.0
            if products_df is not None and not products_df.empty:
                for _, r in products_df.iterrows():
                    product_total = safe_float(r.get("total_embedded_tco2e"))
                    portfolio_total += product_total
                    products.append(
                        {
                            "product_id": int(r.get("product_id")),
                            "product_name": r.get("product_name"),
                            "sku": r.get("sku"),
                            "functional_unit_value": safe_float(r.get("functional_unit_value"), 1.0),
                            "functional_unit_unit": r.get("functional_unit_unit"),
                            "system_boundary": r.get("system_boundary"),
                            "lca_standard": r.get("lca_standard"),
                            "total_embedded_tco2e": round(product_total, 6),
                            "last_calculated_at": str(r.get("last_calculated_at")) if r.get("last_calculated_at") else None,
                        }
                    )
            return {
                "job_id": int(job_id),
                "products_count": len(products),
                "total_embedded_tco2e": round(portfolio_total, 6),
                "products": products,
            }
    except HTTPException:
        raise
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Failed to load LCA overview: {e}")


