@router.patch("/jobs/{job_id}/lca/items/{item_id}")
def update_lca_item(job_id: int, item_id: int, body: dict = Body(...), _user: dict[str, str] = Depends(_current_user)):
    try:
        with get_conn() as con:
            _ensure_tables(con)
            item_row = con.execute(
                """
                SELECT li.product_id
                FROM lca_inventory_items li
                JOIN lca_products lp ON lp.product_id = li.product_id
                WHERE li.item_id = %s AND lp.job_id = %s
                LIMIT 1
                """,
                [int(item_id), int(job_id)],
            ).fetchone()
            if not item_row:
                raise HTTPException(status_code=404, detail="LCA item not found")
            product_id = int(item_row[0])
            edits = []
            params: list[Any] = []
            editable = [
                "stage_key", "item_name", "item_description", "quantity", "unit", "allocation_pct",
                "origin_country", "raw_material_origin", "process_name", "energy_kwh", "waste_qty",
                "transport_mode", "distance_km", "use_phase_energy_kwh", "recycling_rate_pct",
                "landfill_rate_pct", "mapped_factor_db_id", "factor_value", "factor_unit", "factor_source",
                "lci_database_name", "data_quality", "is_gap_filled", "gap_fill_method", "calculation_notes",
            ]
            for field in editable:
                if field not in body:
                    continue
                if field == "stage_key":
                    val = str(body.get(field) or "").strip()
                    if val not in STAGE_KEYS:
                        raise HTTPException(status_code=400, detail=f"Invalid stage_key: {val}")
                    edits.append(f"{field} = %s")
                    params.append(val)
                elif field in {
                    "quantity", "allocation_pct", "energy_kwh", "waste_qty", "distance_km",
                    "use_phase_energy_kwh", "recycling_rate_pct", "landfill_rate_pct", "factor_value",
                }:
                    edits.append(f"{field} = %s")
                    params.append(safe_float(body.get(field)))
                elif field == "mapped_factor_db_id":
                    raw = str(body.get(field) or "").strip()
                    edits.append(f"{field} = %s")
                    params.append(int(raw) if raw.isdigit() else None)
                elif field == "is_gap_filled":
                    edits.append(f"{field} = %s")
                    params.append(bool(body.get(field)))
                else:
                    text = str(body.get(field) or "").strip()
                    edits.append(f"{field} = %s")
                    params.append(text or None)
            if not edits:
                return {"ok": True}
            edits.extend(["updated_at = NOW()", "updated_by = %s"])
            params.append(_actor(_user))
            params.append(int(item_id))
            con.execute(f"UPDATE lca_inventory_items SET {', '.join(edits)} WHERE item_id = %s", params)
            summary = _recalculate_product(con, int(product_id), _user)
            return {"ok": True, "summary": summary}
    except HTTPException:
        raise
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Failed to update LCA item: {e}")


