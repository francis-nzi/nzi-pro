_schema_seeded = False

PORTAL_ACCESS_EXPIRY_MIN_YEAR = 2000
PORTAL_ACCESS_EXPIRY_MAX_YEAR = 9999
_PORTAL_ACCESS_EXPIRY_UNSET = object()


def normalize_portal_access_expiry(value: Any) -> datetime | None:
    """Parse a portal-access expiry and return an aware UTC datetime.

    The CRM currently sends ``datetime-local`` values without an offset, so
    naive values remain supported and are interpreted as UTC.  Keeping the
    conversion here (rather than relying on the database session timezone)
    makes API validation, runtime access checks, and the DB constraint agree.
    """
    if value is None:
        return None

    parsed: datetime
    if isinstance(value, datetime):
        parsed = value
    elif isinstance(value, date):
        parsed = datetime.combine(value, time.min)
    elif isinstance(value, str):
        text = value.strip()
        if not text:
            raise ValueError("access_expires_at must be an ISO-8601 timestamp or null")
        if text.endswith(("Z", "z")):
            text = f"{text[:-1]}+00:00"
        try:
            parsed = datetime.fromisoformat(text)
        except ValueError as exc:
            raise ValueError("access_expires_at must be a valid ISO-8601 timestamp") from exc
    else:
        raise ValueError("access_expires_at must be an ISO-8601 timestamp or null")

    if not PORTAL_ACCESS_EXPIRY_MIN_YEAR <= parsed.year <= PORTAL_ACCESS_EXPIRY_MAX_YEAR:
        raise ValueError(
            "access_expires_at year must be between "
            f"{PORTAL_ACCESS_EXPIRY_MIN_YEAR} and {PORTAL_ACCESS_EXPIRY_MAX_YEAR}"
        )

    if parsed.tzinfo is None or parsed.utcoffset() is None:
        normalized = parsed.replace(tzinfo=timezone.utc)
    else:
        try:
            normalized = parsed.astimezone(timezone.utc)
        except (OverflowError, ValueError) as exc:
            raise ValueError(
                "access_expires_at must resolve to a timestamp between years "
                f"{PORTAL_ACCESS_EXPIRY_MIN_YEAR} and {PORTAL_ACCESS_EXPIRY_MAX_YEAR}"
            ) from exc

    if not PORTAL_ACCESS_EXPIRY_MIN_YEAR <= normalized.year <= PORTAL_ACCESS_EXPIRY_MAX_YEAR:
        raise ValueError(
            "access_expires_at must resolve to a timestamp between years "
            f"{PORTAL_ACCESS_EXPIRY_MIN_YEAR} and {PORTAL_ACCESS_EXPIRY_MAX_YEAR}"
        )
    return normalized


def ensure_portal_schema(con) -> None:
    global _schema_seeded
    if _schema_seeded:
        return

    con.execute("""
        CREATE TABLE IF NOT EXISTS client_portal_users (
          portal_user_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          client_db_id    INTEGER NOT NULL REFERENCES clients(db_id) ON DELETE CASCADE,
          contact_id      INTEGER,
          email           VARCHAR NOT NULL,
          full_name       VARCHAR NOT NULL,
          password_hash   VARCHAR,
          is_active       BOOLEAN NOT NULL DEFAULT TRUE,
          created_at      TIMESTAMP NOT NULL DEFAULT NOW(),
          updated_at      TIMESTAMP NOT NULL DEFAULT NOW(),
          last_login_at   TIMESTAMP,
          created_by      VARCHAR,
          reset_token_hash VARCHAR,
          reset_token_expires TIMESTAMP
        )
    """)
    con.execute("""
        CREATE UNIQUE INDEX IF NOT EXISTS ux_portal_users_email
        ON client_portal_users (LOWER(email))
    """)

    con.execute("""
        CREATE TABLE IF NOT EXISTS report_reviews (
          review_id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          job_id              INTEGER NOT NULL REFERENCES jobs(job_id) ON DELETE CASCADE,
          status              VARCHAR(32) NOT NULL DEFAULT 'draft',
          sent_for_review_at  TIMESTAMP,
          sent_by             VARCHAR,
          approved_at         TIMESTAMP,
          approved_by_name    VARCHAR,
          approved_by_email   VARCHAR,
          pdf_generated_at    TIMESTAMP,
          created_at          TIMESTAMP NOT NULL DEFAULT NOW(),
          updated_at          TIMESTAMP NOT NULL DEFAULT NOW()
        )
    """)
    con.execute("""
        CREATE UNIQUE INDEX IF NOT EXISTS ux_report_reviews_job_id
        ON report_reviews (job_id)
    """)

    con.execute("""
        CREATE TABLE IF NOT EXISTS report_review_comments (
          comment_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          review_id         INTEGER NOT NULL REFERENCES report_reviews(review_id) ON DELETE CASCADE,
          author_type       VARCHAR(8) NOT NULL DEFAULT 'client',
          author_name       VARCHAR NOT NULL,
          author_email      VARCHAR NOT NULL,
          comment_text      TEXT NOT NULL,
          section_reference VARCHAR,
          status            VARCHAR(16) NOT NULL DEFAULT 'open',
          crm_response      TEXT,
          created_at        TIMESTAMP NOT NULL DEFAULT NOW(),
          addressed_at      TIMESTAMP,
          addressed_by      VARCHAR
        )
    """)
    con.execute("""
        CREATE INDEX IF NOT EXISTS ix_review_comments_review_id
        ON report_review_comments (review_id, created_at)
    """)

    for ddl in (
        "ALTER TABLE client_portal_users ADD COLUMN IF NOT EXISTS contact_id INTEGER",
        "ALTER TABLE client_portal_users ADD COLUMN IF NOT EXISTS reset_token_hash VARCHAR",
        "ALTER TABLE client_portal_users ADD COLUMN IF NOT EXISTS reset_token_expires TIMESTAMP",
        "ALTER TABLE client_portal_users ADD COLUMN IF NOT EXISTS invited_at TIMESTAMP",
        "ALTER TABLE client_portal_users ADD COLUMN IF NOT EXISTS invited_by VARCHAR",
        # T&C acceptance
        "ALTER TABLE client_portal_users ADD COLUMN IF NOT EXISTS accepted_tac_at TIMESTAMPTZ",
        "ALTER TABLE client_portal_users ADD COLUMN IF NOT EXISTS accepted_tac_version VARCHAR",
        # MFA (TOTP)
        "ALTER TABLE client_portal_users ADD COLUMN IF NOT EXISTS mfa_enabled BOOLEAN DEFAULT FALSE",
        "ALTER TABLE client_portal_users ADD COLUMN IF NOT EXISTS mfa_secret_encrypted TEXT",
        "ALTER TABLE client_portal_users ADD COLUMN IF NOT EXISTS mfa_setup_secret_encrypted TEXT",
        "ALTER TABLE client_portal_users ADD COLUMN IF NOT EXISTS mfa_recovery_codes_hash TEXT DEFAULT '[]'",
        "ALTER TABLE client_portal_users ADD COLUMN IF NOT EXISTS mfa_enabled_at TIMESTAMPTZ",
        "ALTER TABLE client_portal_users ADD COLUMN IF NOT EXISTS mfa_last_used_at TIMESTAMPTZ",
        # report_reviews additions
        "ALTER TABLE report_reviews ADD COLUMN IF NOT EXISTS sent_for_review_at TIMESTAMP",
        "ALTER TABLE report_reviews ADD COLUMN IF NOT EXISTS pdf_generated_at TIMESTAMP",
        "ALTER TABLE report_reviews ADD COLUMN IF NOT EXISTS portal_version_id BIGINT",
        "ALTER TABLE report_reviews ADD COLUMN IF NOT EXISTS published_at TIMESTAMP",
        "ALTER TABLE report_reviews ADD COLUMN IF NOT EXISTS published_by VARCHAR",
        "ALTER TABLE report_reviews ADD COLUMN IF NOT EXISTS pdf_version_id BIGINT",
        # Set when NZI marks a report version "Final" in Report Printing --
        # independent of the client's own approval (approved_at/approved_by_name
        # above), so the audit trail never confuses "NZI finalised this" with
        # "the client approved this".
        "ALTER TABLE report_reviews ADD COLUMN IF NOT EXISTS locked_by_crm_at TIMESTAMP",
        "ALTER TABLE report_reviews ADD COLUMN IF NOT EXISTS locked_by_crm_by VARCHAR",
    ):
        try:
            con.execute(ddl)
        except Exception:
            pass

    try:
        con.execute(
            "UPDATE client_portal_users SET invited_at = created_at, invited_by = created_by WHERE invited_at IS NULL"
        )
    except Exception:
        pass

    # client_portal_access — client-level portal access control
    con.execute("""
        CREATE TABLE IF NOT EXISTS client_portal_access (
          client_db_id       INTEGER PRIMARY KEY REFERENCES clients(db_id) ON DELETE CASCADE,
          is_enabled         BOOLEAN NOT NULL DEFAULT FALSE,
          access_expires_at  TIMESTAMPTZ,
          payment_status     VARCHAR(16) NOT NULL DEFAULT 'unpaid',
          payment_reference  VARCHAR,
          nav_config         JSONB NOT NULL DEFAULT '{}',
          notes              TEXT,
          created_at         TIMESTAMPTZ NOT NULL DEFAULT NOW(),
          updated_at         TIMESTAMPTZ NOT NULL DEFAULT NOW(),
          CONSTRAINT client_portal_access_expiry_year_check CHECK (
            access_expires_at IS NULL OR (
              access_expires_at >= TIMESTAMPTZ '2000-01-01 00:00:00+00'
              AND access_expires_at < TIMESTAMPTZ '10000-01-01 00:00:00+00'
            )
          )
        )
    """)

    # Governance: portal-user role + optional site scoping. Every existing
    # user defaults to 'ClientAdmin' (today's de facto full-access
    # behaviour) so this is purely additive -- see
    # CLIENT_PORTAL_GOVERNANCE_AUTHORIZATION_DESIGN.md. A user with zero
    # rows in portal_user_sites is unrestricted (sees all of their
    # client's sites), also matching today's behaviour with zero migration
    # risk.
    try:
        con.execute("ALTER TABLE client_portal_users ADD COLUMN IF NOT EXISTS role VARCHAR NOT NULL DEFAULT 'ClientAdmin'")
    except Exception:
        pass
    con.execute("""
        CREATE TABLE IF NOT EXISTS portal_user_sites (
          portal_user_id INTEGER NOT NULL REFERENCES client_portal_users(portal_user_id) ON DELETE CASCADE,
          site_id        INTEGER NOT NULL REFERENCES client_sites(site_id) ON DELETE CASCADE,
          PRIMARY KEY (portal_user_id, site_id)
        )
    """)

    _schema_seeded = True


