def create_reset_token(email: str, *, con=None) -> str | None:
    """Generate a reset token, store its hash, return the raw token (or None if user not found)."""
    if con is None:
        with get_conn(autocommit=False) as managed:
            return create_reset_token(email, con=managed)
    ensure_portal_schema(con)
    row = con.execute(
        "SELECT portal_user_id FROM client_portal_users WHERE LOWER(email) = LOWER(%s) AND is_active = TRUE",
        [str(email or "").strip()],
    ).fetchone()
    if not row:
        return None
    token = secrets.token_urlsafe(32)
    token_hash = hashlib.sha256(token.encode()).hexdigest()
    con.execute(
        "UPDATE client_portal_users SET reset_token_hash = %s, reset_token_expires = NOW() + INTERVAL '2 hours' WHERE portal_user_id = %s",
        [token_hash, int(row[0])],
    )
    return token


def consume_reset_token(token: str, new_password: str, *, con=None) -> bool:
    """Validate token, set new password, clear token. Returns True on success."""
    if con is None:
        with get_conn(autocommit=False) as managed:
            return consume_reset_token(token, new_password, con=managed)
    ensure_portal_schema(con)
    token_hash = hashlib.sha256(str(token or "").encode()).hexdigest()
    row = con.execute(
        """
        SELECT portal_user_id FROM client_portal_users
        WHERE reset_token_hash = %s
          AND reset_token_expires > NOW()
          AND is_active = TRUE
        """,
        [token_hash],
    ).fetchone()
    if not row:
        return False
    set_portal_user_password(int(row[0]), new_password, con=con)
    return True


# ---------------------------------------------------------------------------
# Authentication
# ---------------------------------------------------------------------------

def authenticate_portal_user(email: str, password: str, *, con=None) -> dict[str, Any] | None:
    if con is None:
        with get_conn() as managed:
            return authenticate_portal_user(email, password, con=managed)
    ensure_portal_schema(con)
    user = get_portal_user_by_email(email, con=con)
    if not user or not user.get("is_active"):
        return None
    if not user.get("password_hash"):
        return None
    if not _verify_password(password, user["password_hash"]):
        return None
    con.execute(
        "UPDATE client_portal_users SET last_login_at = NOW() WHERE portal_user_id = %s",
        [user["portal_user_id"]],
    )
    user.pop("password_hash", None)
    return user


