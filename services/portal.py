def _row_to_portal_user(row) -> dict[str, Any]:
    return {
        "portal_user_id": int(row[0]),
        "client_db_id": int(row[1]),
        "contact_id": int(row[2]) if row[2] is not None else None,
        "email": str(row[3] or ""),
        "full_name": str(row[4] or ""),
        "is_active": bool(row[5]),
        "created_at": str(row[6]) if row[6] else None,
        "last_login_at": str(row[7]) if row[7] else None,
        "created_by": str(row[8] or "") or None,
    }


def list_portal_users(client_db_id: int, *, con=None) -> list[dict[str, Any]]:
    if con is None:
        with get_conn() as managed:
            return list_portal_users(client_db_id, con=managed)
    ensure_portal_schema(con)
    rows = con.execute(
        """
        SELECT portal_user_id, client_db_id, contact_id, email, full_name,
               is_active, created_at, last_login_at, created_by
        FROM client_portal_users
        WHERE client_db_id = %s
        ORDER BY full_name ASC
        """,
        [int(client_db_id)],
    ).fetchall()
    return [_row_to_portal_user(r) for r in (rows or [])]


def get_portal_user_by_id(portal_user_id: int, *, con=None) -> dict[str, Any] | None:
    if con is None:
        with get_conn() as managed:
            return get_portal_user_by_id(portal_user_id, con=managed)
    ensure_portal_schema(con)
    row = con.execute(
        """
        SELECT portal_user_id, client_db_id, contact_id, email, full_name,
               is_active, created_at, last_login_at, created_by
        FROM client_portal_users
        WHERE portal_user_id = %s
        """,
        [int(portal_user_id)],
    ).fetchone()
    return _row_to_portal_user(row) if row else None


def get_portal_user_by_email(email: str, *, con=None) -> dict[str, Any] | None:
    """Returns user dict including password_hash (for auth only)."""
    if con is None:
        with get_conn() as managed:
            return get_portal_user_by_email(email, con=managed)
    ensure_portal_schema(con)
    row = con.execute(
        """
        SELECT portal_user_id, client_db_id, contact_id, email, full_name,
               is_active, created_at, last_login_at, created_by, password_hash
        FROM client_portal_users
        WHERE LOWER(email) = LOWER(%s)
        """,
        [str(email or "").strip()],
    ).fetchone()
    if not row:
        return None
    user = _row_to_portal_user(row)
    user["password_hash"] = row[9]
    return user


def create_portal_user(
    *,
    client_db_id: int,
    email: str,
    full_name: str,
    password: str,
    contact_id: int | None = None,
    created_by: str,
    con=None,
) -> dict[str, Any]:
    if con is None:
        with get_conn(autocommit=False) as managed:
            return create_portal_user(
                client_db_id=client_db_id,
                email=email,
                full_name=full_name,
                password=password,
                contact_id=contact_id,
                created_by=created_by,
                con=managed,
            )
    ensure_portal_schema(con)

    email = str(email or "").strip().lower()
    if not email:
        raise HTTPException(status_code=400, detail="Email is required")
    full_name = str(full_name or "").strip()
    if not full_name:
        raise HTTPException(status_code=400, detail="Full name is required")
    if not password or len(password) < 8:
        raise HTTPException(status_code=400, detail="Password must be at least 8 characters")

    existing = con.execute(
        "SELECT portal_user_id FROM client_portal_users WHERE LOWER(email) = LOWER(%s)",
        [email],
    ).fetchone()
    if existing:
        raise HTTPException(status_code=400, detail="A portal account with this email already exists")

    ph = _hash_password(password)
    row = con.execute(
        """
        INSERT INTO client_portal_users
          (client_db_id, contact_id, email, full_name, password_hash, is_active, created_by)
        VALUES (%s, %s, %s, %s, %s, TRUE, %s)
        RETURNING portal_user_id
        """,
        [int(client_db_id), contact_id, email, full_name, ph, created_by],
    ).fetchone()
    return get_portal_user_by_id(int(row[0]), con=con)


def update_portal_user(
    portal_user_id: int,
    *,
    full_name: str | None = None,
    is_active: bool | None = None,
    con=None,
) -> dict[str, Any]:
    if con is None:
        with get_conn(autocommit=False) as managed:
            return update_portal_user(portal_user_id, full_name=full_name, is_active=is_active, con=managed)
    ensure_portal_schema(con)
    user = get_portal_user_by_id(portal_user_id, con=con)
    if not user:
        raise HTTPException(status_code=404, detail="Portal user not found")
    next_name = str(full_name or "").strip() or user["full_name"]
    next_active = is_active if is_active is not None else user["is_active"]
    con.execute(
        """
        UPDATE client_portal_users
        SET full_name = %s, is_active = %s, updated_at = NOW()
        WHERE portal_user_id = %s
        """,
        [next_name, next_active, int(portal_user_id)],
    )
    return get_portal_user_by_id(portal_user_id, con=con)


def set_portal_user_password(portal_user_id: int, password: str, *, con=None) -> None:
    if con is None:
        with get_conn(autocommit=False) as managed:
            return set_portal_user_password(portal_user_id, password, con=managed)
    if not password or len(password) < 8:
        raise HTTPException(status_code=400, detail="Password must be at least 8 characters")
    ph = _hash_password(password)
    con.execute(
        "UPDATE client_portal_users SET password_hash = %s, updated_at = NOW(), reset_token_hash = NULL, reset_token_expires = NULL WHERE portal_user_id = %s",
        [ph, int(portal_user_id)],
    )


