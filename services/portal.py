def add_comment(
    review_id: int,
    *,
    author_type: str,
    author_name: str,
    author_email: str,
    comment_text: str,
    section_reference: str | None = None,
    con=None,
) -> dict[str, Any]:
    if con is None:
        with get_conn(autocommit=False) as managed:
            return add_comment(
                review_id,
                author_type=author_type,
                author_name=author_name,
                author_email=author_email,
                comment_text=comment_text,
                section_reference=section_reference,
                con=managed,
            )
    ensure_portal_schema(con)
    if author_type not in ("client", "crm"):
        raise HTTPException(status_code=400, detail="author_type must be client or crm")
    text = str(comment_text or "").strip()
    if not text:
        raise HTTPException(status_code=400, detail="Comment text is required")

    # When client adds a comment, move review to changes_requested if it was sent_for_review
    if author_type == "client":
        con.execute(
            """
            UPDATE report_reviews
            SET status = 'changes_requested', updated_at = NOW()
            WHERE review_id = %s AND status IN ('sent_for_review', 'draft')
            """,
            [int(review_id)],
        )

    row = con.execute(
        """
        INSERT INTO report_review_comments
          (review_id, author_type, author_name, author_email, comment_text, section_reference)
        VALUES (%s, %s, %s, %s, %s, %s)
        RETURNING comment_id, review_id, author_type, author_name, author_email,
                  comment_text, section_reference, status, crm_response,
                  created_at, addressed_at, addressed_by
        """,
        [int(review_id), author_type, author_name, author_email, text, section_reference or None],
    ).fetchone()
    return _row_to_comment(row)


def respond_to_comment(
    comment_id: int,
    *,
    new_status: str,
    crm_response: str | None,
    addressed_by: str,
    con=None,
) -> dict[str, Any]:
    if con is None:
        with get_conn(autocommit=False) as managed:
            return respond_to_comment(
                comment_id,
                new_status=new_status,
                crm_response=crm_response,
                addressed_by=addressed_by,
                con=managed,
            )
    ensure_portal_schema(con)
    if new_status not in ("addressed", "dismissed"):
        raise HTTPException(status_code=400, detail="status must be addressed or dismissed")
    row = con.execute(
        "SELECT comment_id, review_id FROM report_review_comments WHERE comment_id = %s",
        [int(comment_id)],
    ).fetchone()
    if not row:
        raise HTTPException(status_code=404, detail="Comment not found")

    con.execute(
        """
        UPDATE report_review_comments
        SET status = %s, crm_response = %s, addressed_at = NOW(), addressed_by = %s
        WHERE comment_id = %s
        """,
        [new_status, crm_response or None, addressed_by, int(comment_id)],
    )

    # If all comments on this review are now resolved, update review status
    open_count = con.execute(
        "SELECT COUNT(*) FROM report_review_comments WHERE review_id = %s AND status = 'open'",
        [int(row[1])],
    ).fetchone()
    if open_count and int(open_count[0]) == 0:
        con.execute(
            """
            UPDATE report_reviews
            SET status = 'sent_for_review', updated_at = NOW()
            WHERE review_id = %s AND status = 'changes_requested'
            """,
            [int(row[1])],
        )

    updated = con.execute(
        """
        SELECT comment_id, review_id, author_type, author_name, author_email,
               comment_text, section_reference, status, crm_response,
               created_at, addressed_at, addressed_by
        FROM report_review_comments WHERE comment_id = %s
        """,
        [int(comment_id)],
    ).fetchone()
    return _row_to_comment(updated)


