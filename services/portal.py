_schema_seeded = False


def ensure_portal_schema(con) -> None:
    global _schema_seeded
    if _schema_seeded:
        return

    con.execute("""
        CREATE TABLE IF NOT EXISTS client_portal_users (
          portal_user_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          client_db_id    INTEGER NOT NULL REFERENCES clients(db_id) ON DELETE CASCADE,
          contact_id      INTEGER,
          email           VARCHAR NOT NULL,
          full_name       VARCHAR NOT NULL,
          password_hash   VARCHAR,
          is_active       BOOLEAN NOT NULL DEFAULT TRUE,
          created_at      TIMESTAMP NOT NULL DEFAULT NOW(),
          updated_at      TIMESTAMP NOT NULL DEFAULT NOW(),
          last_login_at   TIMESTAMP,
          created_by      VARCHAR,
          reset_token_hash VARCHAR,
          reset_token_expires TIMESTAMP
        )
    """)
    con.execute("""
        CREATE UNIQUE INDEX IF NOT EXISTS ux_portal_users_email
        ON client_portal_users (LOWER(email))
    """)

    con.execute("""
        CREATE TABLE IF NOT EXISTS report_reviews (
          review_id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          job_id              INTEGER NOT NULL REFERENCES jobs(job_id) ON DELETE CASCADE,
          status              VARCHAR(32) NOT NULL DEFAULT 'draft',
          sent_for_review_at  TIMESTAMP,
          sent_by             VARCHAR,
          approved_at         TIMESTAMP,
          approved_by_name    VARCHAR,
          approved_by_email   VARCHAR,
          pdf_generated_at    TIMESTAMP,
          created_at          TIMESTAMP NOT NULL DEFAULT NOW(),
          updated_at          TIMESTAMP NOT NULL DEFAULT NOW()
        )
    """)
    con.execute("""
        CREATE UNIQUE INDEX IF NOT EXISTS ux_report_reviews_job_id
        ON report_reviews (job_id)
    """)

    con.execute("""
        CREATE TABLE IF NOT EXISTS report_review_comments (
          comment_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          review_id         INTEGER NOT NULL REFERENCES report_reviews(review_id) ON DELETE CASCADE,
          author_type       VARCHAR(8) NOT NULL DEFAULT 'client',
          author_name       VARCHAR NOT NULL,
          author_email      VARCHAR NOT NULL,
          comment_text      TEXT NOT NULL,
          section_reference VARCHAR,
          status            VARCHAR(16) NOT NULL DEFAULT 'open',
          crm_response      TEXT,
          created_at        TIMESTAMP NOT NULL DEFAULT NOW(),
          addressed_at      TIMESTAMP,
          addressed_by      VARCHAR
        )
    """)
    con.execute("""
        CREATE INDEX IF NOT EXISTS ix_review_comments_review_id
        ON report_review_comments (review_id, created_at)
    """)

    for ddl in (
        "ALTER TABLE client_portal_users ADD COLUMN IF NOT EXISTS contact_id INTEGER",
        "ALTER TABLE client_portal_users ADD COLUMN IF NOT EXISTS reset_token_hash VARCHAR",
        "ALTER TABLE client_portal_users ADD COLUMN IF NOT EXISTS reset_token_expires TIMESTAMP",
        "ALTER TABLE report_reviews ADD COLUMN IF NOT EXISTS sent_for_review_at TIMESTAMP",
        "ALTER TABLE report_reviews ADD COLUMN IF NOT EXISTS pdf_generated_at TIMESTAMP",
        "ALTER TABLE report_reviews ADD COLUMN IF NOT EXISTS portal_version_id BIGINT",
        "ALTER TABLE report_reviews ADD COLUMN IF NOT EXISTS published_at TIMESTAMP",
        "ALTER TABLE report_reviews ADD COLUMN IF NOT EXISTS published_by VARCHAR",
        "ALTER TABLE report_reviews ADD COLUMN IF NOT EXISTS pdf_version_id BIGINT",
    ):
        try:
            con.execute(ddl)
        except Exception:
            pass

    _schema_seeded = True


